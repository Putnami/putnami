// GenerateResult holds the output of the generate phase.
type GenerateResult struct {
	Hash    string            `json:"hash"`
	Mode    string            `json:"mode"`
	Exports map[string]string `json:"exports"`
	Assets  map[string]string `json:"assets"`
}

// BuildFlags controls which phases run.
type BuildFlags struct {
	RunGenerate  bool
	RunTranspile bool
	RunTypes     bool
	RunCompile   bool
}

// ResolveBuildFlags determines which phases to run.
// If any specific phase is requested, only those run. Otherwise all default phases run.
func ResolveBuildFlags(generate, transpile, types, compile bool) BuildFlags {
	hasSpecific := generate || transpile || types || compile
	return BuildFlags{
		RunGenerate:  boolOr(hasSpecific, generate, true),
		RunTranspile: boolOr(hasSpecific, transpile, true),
		RunTypes:     boolOr(hasSpecific, types, true),
		RunCompile:   compile,
	}
}

func boolOr(hasSpecific, specific, defaultVal bool) bool {
	if hasSpecific {
		return specific
	}
	return defaultVal
}

// ComputeContentHash computes a SHA-256 hash of source files.
func ComputeContentHash(projectPath string, patterns []string) string {
	h := sha256.New()

	var files []string
	filepath.WalkDir(filepath.Join(projectPath, "src"), func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		if isSourceFile(path) {
			files = append(files, path)
		}
		return nil
	})

	sort.Strings(files)
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			continue
		}
		h.Write(data)
	}

	sum := h.Sum(nil)
	return hex.EncodeToString(sum)[:12]
}

func isSourceFile(path string) bool {
	ext := filepath.Ext(path)
	switch ext {
	case ".ts", ".tsx", ".js", ".jsx":
		return true
	}
	return false
}

// EnsureRealDirectory ensures the path is a real directory (not a symlink).
func EnsureRealDirectory(dirPath string, clear bool) error {
	info, err := os.Lstat(dirPath)
	if err == nil {
		if info.Mode()&os.ModeSymlink != 0 {
			if err := os.Remove(dirPath); err != nil {
				return fmt.Errorf("removing symlink %s: %w", dirPath, err)
			}
		} else if info.IsDir() && clear {
			if err := os.RemoveAll(dirPath); err != nil {
				return fmt.Errorf("clearing directory %s: %w", dirPath, err)
			}
		} else if info.IsDir() {
			return nil
		}
	}
	return os.MkdirAll(dirPath, 0755)
}

// UpdateVersionContentHash reads the existing .gen/version.json (generated by the
// scheduler) and adds or updates the contentHash field. If the file doesn't exist,
// it creates a minimal version.json with just the contentHash.
func UpdateVersionContentHash(projectPath, contentHash string) (map[string]string, error) {
	versionPath := filepath.Join(projectPath, ".gen", "version.json")

	// Read existing version.json (written by scheduler before jobs run). As in
	// the scheduler's writer, a torn stamp or one that is not a JSON object
	// contributes nothing.
	info := make(map[string]any)
	if data, err := os.ReadFile(versionPath); err == nil {
		var existing map[string]any
		if json.Unmarshal(data, &existing) == nil && existing != nil {
			info = existing
		}
	}

	info["contentHash"] = contentHash

	data, err := json.MarshalIndent(info, "", "  ")
	if err != nil {
		return nil, err
	}

	os.MkdirAll(filepath.Dir(versionPath), 0755)
	if err := os.WriteFile(versionPath, append(data, '\n'), 0644); err != nil {
		return nil, err
	}

	return map[string]string{
		"version-info": versionPath,
	}, nil
}

// The packages the bundled serve entry imports. bundledServeApplication is also
// the package whose preBuild hook reports the capability manifest that makes a
// build write the entry.
const (
	bundledServeApplication = "@putnami/application"
	bundledServeRuntime     = "@putnami/runtime"
)

// BundledServeHookPackage is the package whose preBuild hook reports
// schema/capabilities.json, which makes a build write the bundled serve entry.
// The hook runs for a project that lists the package among its dependencies or
// devDependencies.
const BundledServeHookPackage = bundledServeApplication

// BundledServeImports returns the packages the bundled serve entry
// (.gen/src/serve.bundled.ts) imports, in the order it imports them. A project
// that depends on BundledServeHookPackage reads each of them from generated
// source, even when its own sources import none of them.
func BundledServeImports() []string {
	return []string{bundledServeApplication, bundledServeRuntime}
}

// GenerateBundledServe creates a bundled serve entrypoint from the activation
// metadata in capabilities.json. The generate export map is deliberately not
// consulted: the shipped, validated manifest is the single source of truth for
// which generated modules a packaged workload activates.
func GenerateBundledServe(projectPath, manifestPath string, log func(string)) (string, error) {
	pkg := project.ReadPackageJSONSafe(filepath.Join(projectPath, "package.json"))
	appEntry := "src/main.ts"
	if pkg != nil && pkg.Main != "" {
		appEntry = pkg.Main
	}

	appEntryPath := filepath.Join(projectPath, appEntry)
	if !project.FileExists(appEntryPath) {
		if log != nil {
			log("Bundled serve: app entrypoint not found at " + appEntry)
		}
		return "", nil
	}

	manifest, err := readValidatedCapabilityManifest(projectPath, manifestPath)
	if err != nil {
		return "", err
	}

	targetPath := filepath.Join(projectPath, ".gen/src/serve.bundled.ts")
	targetDir := filepath.Dir(targetPath)
	os.MkdirAll(targetDir, 0755)

	appImportPath := normalizeImportPath(project.RelativePath(targetDir, appEntryPath))

	// Manifest-declared server-side loaders only. Use static imports so
	// single-binary packagers include generated server modules. A lazy dynamic
	// import is easy for dev servers to resolve, but packaged binaries may not
	// ship .gen/src alongside the executable.
	type loaderExport struct {
		key        string
		importPath string
	}
	type loaderActivation struct {
		key  string
		path string
	}
	var activations []loaderActivation
	for _, schema := range manifest.Schemas {
		if schema.Kind == "route" &&
			schema.SourceKind == "generated" &&
			strings.HasSuffix(schema.Name, "-loader") &&
			!strings.HasSuffix(schema.Name, "client-loader") {
			activations = append(activations, loaderActivation{key: schema.Name, path: schema.Path})
		}
	}
	for _, discoverer := range manifest.Discoverers {
		if discoverer.Kind == "source" &&
			discoverer.SourceKind == "generated" &&
			strings.HasSuffix(discoverer.Name, "-loader") &&
			!strings.HasSuffix(discoverer.Name, "client-loader") {
			activations = append(activations, loaderActivation{
				key:  discoverer.Name,
				path: discoverer.Path,
			})
		}
	}
	var loaders []loaderExport
	seenLoaders := make(map[string]bool)
	for _, activation := range activations {
		if seenLoaders[activation.key] {
			return "", fmt.Errorf("capability manifest declares loader %q more than once", activation.key)
		}
		seenLoaders[activation.key] = true
		absPath, err := resolveCapabilityActivationPath(projectPath, activation.path)
		if err != nil {
			return "", fmt.Errorf("capability manifest loader %q: %w", activation.key, err)
		}
		importPath := normalizeImportPath(project.RelativePath(targetDir, absPath))
		loaders = append(loaders, loaderExport{key: activation.key, importPath: importPath})
	}
	sort.Slice(loaders, func(i, j int) bool { return loaders[i].key < loaders[j].key })
	configPaths := make([]string, 0, len(manifest.ConfigDefinitions))
	for _, definition := range manifest.ConfigDefinitions {
		configPaths = append(configPaths, definition.Path)
	}
	sort.Strings(configPaths)
	configPathsJSON, err := json.Marshal(configPaths)
	if err != nil {
		return "", fmt.Errorf("encoding capability config paths: %w", err)
	}

	var lines []string
	lines = append(lines, "import { bootstrapServe, registerModuleLoader } from '"+bundledServeApplication+"';")
	lines = append(lines, "import { assertRegisteredConfigDefinitions } from '"+bundledServeRuntime+"';")
	// The app entrypoint is imported BEFORE the generated loader modules. ES
	// modules evaluate imports in source order, and a generated loader module
	// can read config while it evaluates (`export default new ReactApplication()`
	// calls `useConfig` in its constructor). The workload's static activation
	// — the `import './activate'` at the top of `src/main.ts` that registers the
	// remote config source from an extension package — must run first, or the
	// config loader discovers no remote source and a deployed binary exits at
	// boot with CONFIG_SERVER_URL set.
	lines = append(lines, "// The app entrypoint evaluates first so its static activation (src/activate.ts)")
	lines = append(lines, "// registers config sources before any generated module reads config.")
	lines = append(lines, fmt.Sprintf("import { app } from %s;", strconv.Quote(appImportPath)))
	for i, loader := range loaders {
		lines = append(lines, fmt.Sprintf("import * as loaderModule%d from %s;", i, strconv.Quote(loader.importPath)))
	}
	lines = append(lines, "")
	lines = append(lines, "// Activate the generated server modules declared by capabilities.json.")
	for i, loader := range loaders {
		lines = append(lines, fmt.Sprintf("registerModuleLoader(%s, () => Promise.resolve(loaderModule%d));", strconv.Quote(loader.key), i))
	}
	lines = append(lines, "")
	// Route through bootstrapServe so a fatal startup failure (config load, DI,
	// plugin start) is logged as a single structured JSON line and exits
	// non-zero, instead of escaping to Bun's default multi-line stack printer.
	lines = append(lines, "await bootstrapServe(async () => {")
	lines = append(lines, "  const workload = await app();")
	lines = append(lines, "  workload.registerContributedConfigs();")
	lines = append(lines, fmt.Sprintf("  assertRegisteredConfigDefinitions(%s);", configPathsJSON))
	lines = append(lines, "  return workload;")
	lines = append(lines, "});")
	lines = append(lines, "")

	if err := os.WriteFile(targetPath, []byte(strings.Join(lines, "\n")), 0644); err != nil {
		return "", fmt.Errorf("writing bundled serve entrypoint: %w", err)
	}
	if log != nil {
		log(fmt.Sprintf("Generated bundled serve with %d module loader(s)", len(loaders)))
	}

	return targetPath, nil
}

func resolveCapabilityActivationPath(projectPath, manifestPath string) (string, error) {
	if manifestPath == "" {
		return "", fmt.Errorf("activation path is empty")
	}
	if filepath.IsAbs(manifestPath) {
		return "", fmt.Errorf("activation path must be project-relative: %s", manifestPath)
	}
	clean := filepath.Clean(filepath.FromSlash(manifestPath))
	if clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("activation path escapes the project: %s", manifestPath)
	}
	ext := strings.ToLower(filepath.Ext(clean))
	switch ext {
	case ".ts", ".tsx", ".js", ".jsx", ".mts", ".cts", ".mjs", ".cjs":
	default:
		return "", fmt.Errorf("activation path is not an importable TypeScript/JavaScript module: %s", manifestPath)
	}
	absPath := filepath.Join(projectPath, clean)
	if !project.FileExists(absPath) {
		return "", fmt.Errorf("activation module not found: %s", manifestPath)
	}
	return absPath, nil
}

func normalizeImportPath(p string) string {
	p = strings.ReplaceAll(p, "\\", "/")
	// Strip extension
	for _, ext := range []string{".tsx", ".ts", ".jsx", ".js", ".mts", ".cts", ".mjs", ".cjs"} {
		p = strings.TrimSuffix(p, ext)
	}
	if !strings.HasPrefix(p, "./") && !strings.HasPrefix(p, "../") {
		p = "./" + p
	}
	return p
}

// CopyProjectGenerateAssets copies assets from project config options.generate.assets.
// It returns the first copy that fails, so a declared asset is never missing
// from a green generate.
func CopyProjectGenerateAssets(workspaceRoot, projectPath, genDir string, emit *jsonl.Emitter) error {
	rcPath := resolveProjectConfig(projectPath)
	assets := project.GetGenerateAssets(rcPath)

	for _, entry := range assets {
		if entry.From == "" || entry.To == "" {
			continue
		}

		sourcePath := entry.From
		if strings.HasPrefix(sourcePath, "/") {
			sourcePath = filepath.Join(workspaceRoot, sourcePath)
		} else {
			sourcePath = filepath.Join(projectPath, sourcePath)
		}

		// Sanitize source path to prevent traversal outside workspace
		sourcePath = filepath.Clean(sourcePath)
		if !strings.HasPrefix(sourcePath, filepath.Clean(workspaceRoot)+string(filepath.Separator)) {
			continue
		}

		// Sanitize the destination too: `To` comes from project config (untrusted
		// in a CI checkout) and must not escape genDir, mirroring the source check.
		destPath := filepath.Clean(filepath.Join(genDir, entry.To))
		if !strings.HasPrefix(destPath, filepath.Clean(genDir)+string(filepath.Separator)) {
			continue
		}

		if !project.FileExists(sourcePath) {
			// A declared asset source that no longer exists publishes nothing.
			// Surface it instead of silently skipping — a stale "from" path is
			// otherwise invisible until something 404s in production.
			if emit != nil {
				emit.Warn(fmt.Sprintf("generate asset source not found, skipping: %s -> %s", entry.From, entry.To))
			}
			continue
		}

		info, _ := os.Stat(sourcePath)
		copyAsset := CopyFile
		if info != nil && info.IsDir() {
			copyAsset = CopyDir
		}
		if err := copyAsset(sourcePath, destPath); err != nil {
			return fmt.Errorf("copy generate asset %s -> %s: %w", entry.From, entry.To, err)
		}
	}
	return nil
}

// resolveProjectConfig returns the path to the project config file,
// preferring putnami.json and falling back to .putnamirc.json.
func resolveProjectConfig(dir string) string {
	p := filepath.Join(dir, "putnami.json")
	if project.FileExists(p) {
		return p
	}
	legacy := filepath.Join(dir, ".putnamirc.json")
	if project.FileExists(legacy) {
		return legacy
	}
	return p
}

// CopyDir recursively copies a directory.
func CopyDir(src, dst string) error {
	return filepath.WalkDir(src, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		destPath := filepath.Join(dst, rel)

		if d.IsDir() {
			return os.MkdirAll(destPath, 0755)
		}
		return CopyFile(path, destPath)
	})
}

// CopyFile copies a single file.
func CopyFile(src, dst string) error {
	os.MkdirAll(filepath.Dir(dst), 0755)

	srcFile, err := os.Open(src)
	if err != nil {
		return err
	}
	defer srcFile.Close()

	dstFile, err := os.Create(dst)
	if err != nil {
		return err
	}
	defer dstFile.Close()

	_, err = io.Copy(dstFile, srcFile)
	return err
}
