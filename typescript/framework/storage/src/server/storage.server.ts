import type { Module, Plugin } from '@putnami/application';
import { HttpPlugin, HttpResponse } from '@putnami/application';
import { useConfig, useLogger } from '@putnami/runtime';
import { FileBackend, validateKey } from '../backend/file.backend';
import { BucketHelper } from '../bucket/bucket.helper';
import { bucketRegistry } from '../bucket/bucket.registry';
import { StorageConfig, resolveTokenSecret } from '../config';
import { StorageError } from '../errors';

/**
 * Decode the `_storage/<bucket>/<key...>` path into its raw bucket and key. The
 * signing backend percent-encodes each segment, so decode them back to the
 * original values the HMAC token was signed over. Returns null on malformed
 * percent-encoding so the caller can reject the request.
 */
function parseStorageTarget(path: string): { bucket: string; key: string } | null {
  const parts = path.split('/');
  try {
    return {
      bucket: decodeURIComponent(parts[1] ?? ''),
      key: parts.slice(2).map(decodeURIComponent).join('/'),
    };
  } catch {
    return null;
  }
}

export interface StorageServerOptions {
  /** Data directory for file storage. Defaults to '.data/storage'. */
  dataDir?: string;
  /** HMAC secret for token signing. Auto-generated when omitted. */
  tokenSecret?: string;
}

/**
 * Local storage server plugin for development.
 *
 * Serves storage objects over HTTP so that signed URLs generated by the FileBackend
 * can be consumed by browsers. Mounts routes under `/_storage/`.
 *
 * In production, these requests go to `storage.putnami.cloud` instead.
 *
 * @example
 * ```typescript
 * import { storageServer } from '@putnami/storage';
 *
 * app.use(storageServer({ dataDir: '.data/storage' }));
 * ```
 */
export function storageServer(options?: StorageServerOptions): Plugin {
  const conf = useConfig(StorageConfig);
  const dataDir = options?.dataDir ?? conf.dataDir;
  const secret = resolveTokenSecret(options?.tokenSecret ?? conf.tokenSecret);
  const backend = new FileBackend(dataDir, secret);

  return {
    async warmup(app: Module) {
      const logger = useLogger('storage-server');
      const httpPlugin = await app.ensurePlugin(HttpPlugin);

      // PUT /_storage/* — Handle signed upload requests
      httpPlugin.route('PUT', '/_storage/*', async (ctx) => {
        // ctx.path() returns the path without leading slash (e.g., "_storage/bucket/key").
        // Backends percent-encode each segment, so decode them back to the raw
        // bucket/key the token was signed over.
        const target = parseStorageTarget(ctx.path());
        if (!target) {
          return new HttpResponse(undefined, { status: 400 });
        }
        const { bucket, key } = target;
        const queryParams = ctx.queryParams();
        const token = queryParams['token'];

        // Validate key to prevent path traversal
        try {
          validateKey(key);
        } catch (e) {
          if (e instanceof StorageError && e.code === 'PATH_TRAVERSAL') {
            return new HttpResponse(undefined, { status: 400 });
          }
          throw e;
        }

        // The method is part of the signed payload: only a token minted for
        // PUT (signedUploadUrl) authorizes this route — a download token is rejected.
        if (!token || !backend.validateToken('PUT', token, bucket, key)) {
          return new HttpResponse(undefined, { status: 403 });
        }

        const bucketDef = bucketRegistry.getByName(bucket);
        if (!bucketDef) {
          return new HttpResponse(undefined, { status: 404 });
        }

        const body = await ctx.body<ArrayBuffer>();
        if (!body) {
          return new HttpResponse(undefined, { status: 400 });
        }

        // Validate constraints against actual body size (not content-length header)
        const helper = new BucketHelper(bucketDef);
        const contentType = ctx.headers.get('content-type') ?? undefined;
        const errors = helper.validate({ size: body.byteLength, mimeType: contentType });
        if (errors.length > 0) {
          return new HttpResponse(JSON.stringify({ errors }), {
            status: 413,
            headers: { 'content-type': 'application/json' },
          });
        }

        const result = await backend.put(bucket, key, Buffer.from(body), { contentType });
        return result;
      });

      // GET /_storage/* — Handle signed download requests and public access
      httpPlugin.route('GET', '/_storage/*', async (ctx) => {
        // ctx.path() returns the path without leading slash (e.g., "_storage/bucket/key").
        // Backends percent-encode each segment, so decode them back to the raw
        // bucket/key the token was signed over.
        const target = parseStorageTarget(ctx.path());
        if (!target) {
          return new HttpResponse(undefined, { status: 400 });
        }
        const { bucket, key } = target;
        const queryParams = ctx.queryParams();
        const token = queryParams['token'];

        // Validate key to prevent path traversal
        try {
          validateKey(key);
        } catch (e) {
          if (e instanceof StorageError && e.code === 'PATH_TRAVERSAL') {
            return new HttpResponse(undefined, { status: 400 });
          }
          throw e;
        }

        // Public buckets don't require a token
        const bucketDef = bucketRegistry.getByName(bucket);
        const isPublic = bucketDef?.options.public === true;

        // The method is part of the signed payload: only a token minted for
        // GET (signedDownloadUrl) authorizes this route — an upload token is rejected.
        if (!isPublic && (!token || !backend.validateToken('GET', token, bucket, key))) {
          return new HttpResponse(undefined, { status: 403 });
        }

        const result = await backend.get(bucket, key);
        if (!result) {
          return new HttpResponse(undefined, { status: 404 });
        }

        return new HttpResponse(result.body, {
          headers: {
            ...(result.contentType && { 'content-type': result.contentType }),
            'content-length': String(result.size),
            ...(result.etag && { etag: result.etag }),
          },
        });
      });

      const buckets = bucketRegistry.getAll();
      logger.info(`Storage server ready — serving ${buckets.length} bucket(s) on /_storage/`);

      // Surface the blast radius of `public: true`: each public bucket serves
      // every object unauthenticated. Naming them at startup makes an
      // accidental bucket-wide exposure visible instead of silent.
      const publicBuckets = buckets.filter((b) => b.options.public === true).map((b) => b.bucketName);
      if (publicBuckets.length > 0) {
        logger.warn(
          `Public buckets serve every object unauthenticated over GET /_storage/{bucket}/{key}: ${publicBuckets.join(', ')}. ` +
            'Ensure these buckets hold only objects safe for anonymous read.',
        );
      }
    },

    async stop() {
      await backend.close();
    },
  };
}
