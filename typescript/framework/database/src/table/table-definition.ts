import type { SchemaPrimitive } from '@putnami/runtime';
import type { DatabaseValue } from '../type.type';

const TABLE_MARKER = 'putnami:table' as const;
const COLUMN_MARKER = 'putnami:column' as const;
const KEY_MARKER = 'putnami:key' as const;

// ---- Column Definition ----

export interface ColumnOptions {
  /** Database column name (defaults to property name) */
  readonly columnName?: string;
  /** SQL column type override (e.g., 'VARCHAR(255)', 'JSONB') */
  readonly columnType?: string;
  /** Default value for database inserts */
  readonly default?: DatabaseValue;
  /** Transform from entity value to database value */
  readonly toDatabase?: (value: any) => DatabaseValue;
  /** Transform from database value to entity value */
  readonly fromDatabase?: (value: DatabaseValue) => unknown;
}

export interface ColumnDefinition<P extends SchemaPrimitive = SchemaPrimitive> {
  readonly __column: typeof COLUMN_MARKER;
  readonly type: P;
  readonly options: ColumnOptions;
}

// ---- Key Definition ----

export interface KeyOptions extends ColumnOptions {
  /** Whether the key is auto-generated by the database */
  readonly autoGenerate?: boolean;
}

export interface KeyDefinition<P extends SchemaPrimitive = SchemaPrimitive> {
  readonly __key: typeof KEY_MARKER;
  readonly type: P;
  readonly options: KeyOptions;
}

// ---- Table Schema ----

/** A single field in a table schema: either a Column or a Key */
export type TableField = ColumnDefinition | KeyDefinition;

/** The schema shape passed to Table() */
export type TableSchema = Record<string, TableField>;

// ---- Table Options ----

export interface TableOptions {
  /** Named datasource (e.g., 'auth', 'analytics') */
  readonly db?: string;
  /** Database schema name */
  readonly schema?: string;
}

// ---- Table Definition ----

export interface TableDefinition<S extends TableSchema = TableSchema> {
  readonly __table: typeof TABLE_MARKER;
  readonly tableName: string;
  readonly schema: S;
  readonly options: TableOptions;
  /** @internal Native declaration location for build-time design discovery. */
  readonly __source?: { path: string; line?: number; symbol?: string };
}

// ---- Type Guards ----

export function isColumnDefinition(value: unknown): value is ColumnDefinition {
  return typeof value === 'object' && value !== null && (value as ColumnDefinition).__column === COLUMN_MARKER;
}

export function isKeyDefinition(value: unknown): value is KeyDefinition {
  return typeof value === 'object' && value !== null && (value as KeyDefinition).__key === KEY_MARKER;
}

export function isTableDefinition(value: unknown): value is TableDefinition {
  return typeof value === 'object' && value !== null && (value as TableDefinition).__table === TABLE_MARKER;
}
