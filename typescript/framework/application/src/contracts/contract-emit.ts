/**
 * TypeScript twin of the Go contract emitter (protocols/contracts/jsonschema.go
 * and emit_go.go). It lowers a {@link ContractManifest} into:
 *
 *   - a JSON Schema (Draft 2020-12) over the DTO/enum/union vocabulary, and
 *   - a self-contained TypeScript types module (enums as string-literal unions
 *     plus `as const` objects, tagged unions as discriminated unions, structs as
 *     interfaces).
 *
 * The JSON Schema is the cross-language byte-parity artifact: {@link
 * serializeJSONSchema} reproduces Go's `json.MarshalIndent(x, "", "  ") + "\n"`
 * byte-for-byte by building the identical structure, sorting object keys the way
 * encoding/json sorts map keys, and applying Go's HTML/JS-separator escaping.
 * The generated `.ts` types differ from the Go `.go` types by language and are
 * pinned by their own golden, not compared across languages.
 */

import { Buffer } from 'node:buffer';
import { FIELD_TYPES } from '../config/config-schema.types';
import type {
  ContractEnum,
  ContractField,
  ContractManifest,
  ContractStruct,
  ContractUnion,
  ContractUnionVariant,
} from './contract-ir.types';

/** JSON Schema dialect emitted, matching protocols/config and the Go twin. */
export const JSON_SCHEMA_DRAFT = 'https://json-schema.org/draft/2020-12/schema';

/** DO NOT EDIT banner both language emitters stamp. */
const GENERATED_HEADER = '// Code generated by go.putnami.dev/protocol/contracts. DO NOT EDIT.';

// ---------------------------------------------------------------------------
// JSON Schema
// ---------------------------------------------------------------------------

/**
 * Lower the DTO/enum/union vocabulary of `manifest` into a JSON Schema document.
 * Mirrors the Go RenderJSONSchema exactly; the returned object is plain data,
 * ordered by {@link serializeJSONSchema} (never relied on here for key order).
 */
export function renderJSONSchema(manifest: ContractManifest): Record<string, unknown> {
  const structsByName = new Map<string, ContractStruct>();
  for (const s of manifest.structs ?? []) structsByName.set(s.name, s);
  const defs: Record<string, unknown> = {};
  for (const e of manifest.enums ?? []) defs[e.name] = schemaForEnum(e);
  for (const u of manifest.unions ?? []) defs[u.name] = schemaForUnion(u, structsByName);
  for (const s of manifest.structs ?? []) defs[s.name] = schemaForStruct(s);

  const out: Record<string, unknown> = {
    $schema: JSON_SCHEMA_DRAFT,
    $defs: defs,
  };
  if (manifest.name) out['title'] = `${manifest.name} contracts`;
  return out;
}

/**
 * Render the JSON Schema in the canonical wire form: keys sorted the way
 * encoding/json sorts map keys, two-space indentation, Go HTML/JS-separator
 * escaping, and a trailing newline — byte-identical to the Go emitter's
 * `MarshalJSONSchema`.
 */
export function serializeJSONSchema(manifest: ContractManifest): string {
  const canonical = JSON.stringify(sortKeysDeep(renderJSONSchema(manifest)), null, 2);
  return `${escapeLikeGo(canonical)}\n`;
}

function schemaForEnum(e: ContractEnum): Record<string, unknown> {
  const out: Record<string, unknown> = {
    type: 'string',
    enum: e.values.map((v) => v.value),
  };
  if (e.description) out['description'] = e.description;
  return out;
}

function schemaForStruct(s: ContractStruct): Record<string, unknown> {
  const properties: Record<string, unknown> = {};
  const required: string[] = [];
  for (const f of s.fields ?? []) {
    properties[f.name] = schemaForField(f);
    if (!f.optional) required.push(f.name);
  }
  required.sort(byteCompare);
  const out: Record<string, unknown> = {
    type: 'object',
    properties,
    additionalProperties: false,
  };
  if (s.description) out['description'] = s.description;
  if (required.length > 0) out['required'] = required;
  return out;
}

function schemaForField(f: ContractField): Record<string, unknown> {
  const base = schemaForType(f.type);
  const out: Record<string, unknown> = f.repeated ? { type: 'array', items: base } : base;
  if (f.description) out['description'] = f.description;
  return out;
}

function schemaForType(token: string): Record<string, unknown> {
  switch (token) {
    case FIELD_TYPES.string:
      return { type: 'string' };
    case FIELD_TYPES.int:
      return { type: 'integer' };
    case FIELD_TYPES.float:
      return { type: 'number' };
    case FIELD_TYPES.bool:
      return { type: 'boolean' };
    case FIELD_TYPES.duration:
      return { type: 'string', format: 'duration' };
    default:
      return { $ref: `#/$defs/${token}` };
  }
}

function schemaForUnion(u: ContractUnion, structs: Map<string, ContractStruct>): Record<string, unknown> {
  const out: Record<string, unknown> = {
    oneOf: u.variants.map((v) => schemaForVariant(u.discriminator, v, structs)),
  };
  if (u.description) out['description'] = u.description;
  return out;
}

// Renders one union arm as a single closed object schema that pins the
// discriminator to the variant tag (const) and inlines the variant's fields; a
// struct-ref variant contributes the referenced struct's fields.
//
// The fields are inlined rather than composed with `allOf: [$ref]` on purpose: a
// referenced struct carries additionalProperties:false, and a JSON Schema allOf
// branch evaluates that constraint independently against the whole object, so
// $ref-ing the struct would reject the discriminator this arm adds — making the
// arm (and thus every instance of the variant) unsatisfiable.
function schemaForVariant(
  discriminator: string,
  v: ContractUnionVariant,
  structs: Map<string, ContractStruct>,
): Record<string, unknown> {
  const fields = v.struct ? (structs.get(v.struct)?.fields ?? []) : (v.fields ?? []);
  const out = inlineVariantSchema(discriminator, { const: v.tag }, fields);
  if (v.description) out['description'] = v.description;
  return out;
}

function inlineVariantSchema(
  discriminator: string,
  discSchema: Record<string, unknown>,
  fields: ContractField[],
): Record<string, unknown> {
  const properties: Record<string, unknown> = { [discriminator]: discSchema };
  const required: string[] = [discriminator];
  for (const f of fields) {
    properties[f.name] = schemaForField(f);
    if (!f.optional) required.push(f.name);
  }
  required.sort(byteCompare);
  return { type: 'object', properties, additionalProperties: false, required };
}

// ---------------------------------------------------------------------------
// TypeScript types
// ---------------------------------------------------------------------------

/**
 * Emit a self-contained TypeScript types module for `manifest`: enums as
 * string-literal unions plus `as const` objects, tagged unions as discriminated
 * unions, and structs as interfaces. Deterministic in manifest source order.
 */
export function emitTypeScript(manifest: ContractManifest): string {
  const blocks: string[] = [GENERATED_HEADER];
  for (const e of manifest.enums ?? []) blocks.push(emitTsEnum(e));
  for (const u of manifest.unions ?? []) blocks.push(emitTsUnion(u));
  for (const s of manifest.structs ?? []) blocks.push(emitTsStruct(s));
  return `${blocks.join('\n\n')}\n`;
}

function emitTsEnum(e: ContractEnum): string {
  const lines: string[] = [];
  if (e.description) lines.push(`/** ${e.description} */`);
  lines.push(`export type ${e.name} = ${e.values.map((v) => `'${v.value}'`).join(' | ')};`);
  lines.push('');
  lines.push(`export const ${e.name} = {`);
  for (const v of e.values) lines.push(`  ${v.name}: '${v.value}',`);
  lines.push('} as const;');
  return lines.join('\n');
}

function emitTsUnion(u: ContractUnion): string {
  const lines: string[] = [];
  if (u.description) lines.push(`/** ${u.description} */`);
  lines.push(`export type ${u.name} =`);
  u.variants.forEach((v, i) => {
    const suffix = i === u.variants.length - 1 ? ';' : '';
    lines.push(`  | ${variantArm(u.discriminator, v)}${suffix}`);
  });
  return lines.join('\n');
}

function variantArm(discriminator: string, v: ContractUnionVariant): string {
  if (v.struct) {
    return `({ ${discriminator}: '${v.tag}' } & ${v.struct})`;
  }
  const members = (v.fields ?? []).map(tsMember);
  const body = members.length > 0 ? ` ${members.join(' ')}` : '';
  return `{ ${discriminator}: '${v.tag}';${body} }`;
}

function emitTsStruct(s: ContractStruct): string {
  const lines: string[] = [];
  if (s.description) lines.push(`/** ${s.description} */`);
  lines.push(`export interface ${s.name} {`);
  for (const f of s.fields ?? []) {
    if (f.description) lines.push(`  /** ${f.description} */`);
    lines.push(`  ${tsMember(f)}`);
  }
  lines.push('}');
  return lines.join('\n');
}

function tsMember(f: ContractField): string {
  const optional = f.optional ? '?' : '';
  const base = tsType(f.type);
  const type = f.repeated ? `${base}[]` : base;
  return `${f.name}${optional}: ${type};`;
}

function tsType(token: string): string {
  switch (token) {
    case FIELD_TYPES.string:
    case FIELD_TYPES.duration:
      return 'string';
    case FIELD_TYPES.int:
    case FIELD_TYPES.float:
      return 'number';
    case FIELD_TYPES.bool:
      return 'boolean';
    default:
      return token;
  }
}

// ---------------------------------------------------------------------------
// Canonical serialization helpers
// ---------------------------------------------------------------------------

/**
 * Recursively rebuild `value` with object keys byte-sorted, matching how
 * encoding/json orders map keys. Arrays keep their order; scalars pass through.
 */
function sortKeysDeep(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeysDeep);
  if (value !== null && typeof value === 'object') {
    const src = value as Record<string, unknown>;
    const out: Record<string, unknown> = {};
    for (const key of Object.keys(src).sort(byteCompare)) {
      out[key] = sortKeysDeep(src[key]);
    }
    return out;
  }
  return value;
}

/**
 * Byte-wise string comparison matching Go's `<` on UTF-8 strings. JavaScript
 * sorts by UTF-16 code units, which reverses some BMP/supplementary pairs, so
 * compare encoded bytes explicitly.
 */
function byteCompare(a: string, b: string): number {
  return Buffer.compare(Buffer.from(a, 'utf8'), Buffer.from(b, 'utf8'));
}

/** Match encoding/json's default HTML and JavaScript-separator escaping. */
function escapeLikeGo(json: string): string {
  return json.replace(/[<>&\u2028\u2029]/g, (character) => {
    switch (character) {
      case '<':
        return '\\u003c';
      case '>':
        return '\\u003e';
      case '&':
        return '\\u0026';
      case '\u2028':
        return '\\u2028';
      case '\u2029':
        return '\\u2029';
      default:
        return character;
    }
  });
}
