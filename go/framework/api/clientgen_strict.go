package api

import (
	"encoding/json"
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"go.putnami.dev/errors"
	clientcontract "go.putnami.dev/protocol/clientcontract"
)

type strictClientGen struct {
	spec       SpecIR
	opts       ClientGenOptions
	clientName string
	imports    map[string]bool
	defs       map[string]string
	order      []string
	declaring  map[string]bool
	// omitted is what ClientGenOptions.OmitOperations left out, in contract
	// order. The client's doc comment names each one.
	omitted []MethodIR
	// symbols is the Go method symbol of every emitted operation, keyed by
	// operationId, resolved once by strictMethodSymbols over the whole
	// post-omission contract. Every emitted name derives from it.
	symbols map[string]string
}

func generateStrictClient(spec SpecIR, opts ClientGenOptions) (string, error) {
	clientName := opts.ClientName
	if clientName == "" {
		clientName = "Client"
	}
	spec, omitted, err := omitOperations(spec, opts.OmitOperations)
	if err != nil {
		return "", err
	}
	symbols, err := strictMethodSymbols(spec.Services)
	if err != nil {
		return "", err
	}
	generator := &strictClientGen{
		spec: spec, opts: opts, clientName: clientName, omitted: omitted, symbols: symbols,
		imports: map[string]bool{
			"go.putnami.dev/app": true, "go.putnami.dev/client": true, "go.putnami.dev/inject": true,
		},
		defs: make(map[string]string), declaring: make(map[string]bool),
	}
	if err := generator.validateNames(); err != nil {
		return "", err
	}
	for _, name := range sortedKeys(spec.Schemas) {
		if _, err := generator.declareNamed(exportedFieldName(name), spec.Schemas[name]); err != nil {
			return "", errors.Newf(CodeClientGenConfig, "api: schema %s: %v", name, err)
		}
	}
	return generator.render()
}

func (generator *strictClientGen) render() (string, error) {
	contractJSON, err := json.Marshal(generator.spec.Contract)
	if err != nil {
		return "", err
	}
	schemasJSON, err := json.Marshal(generator.spec.Schemas)
	if err != nil {
		return "", err
	}

	var operationVars []string
	var methods strings.Builder
	var designMethods []methodEmit
	for _, service := range generator.spec.Services {
		for _, method := range service.Methods {
			methodName := generator.symbols[method.OperationID]
			if err := generator.emitMethod(&methods, methodName, method); err != nil {
				return "", err
			}
			operationVars = append(operationVars, lowerFirst(methodName)+"Operation")
			designMethods = append(designMethods, methodEmit{Name: methodName, OperationID: method.OperationID, HTTPMethod: method.HTTPMethod, Path: method.Path})
		}
	}

	var source strings.Builder
	source.WriteString("// Code generated by go.putnami.dev/api. DO NOT EDIT.\n\n")
	fmt.Fprintf(&source, "package %s\n\n", generator.opts.PackageName)
	emitImports(&source, generator.imports)
	fmt.Fprintf(&source, "var serviceDescriptor = client.MustServiceDescriptorWithOperations(%q, %q", string(contractJSON), string(schemasJSON))
	for _, operationVar := range operationVars {
		fmt.Fprintf(&source, ", %s", operationVar)
	}
	source.WriteString(")\n\n")
	if capabilities := specRuntimeCapabilities(generator.spec); len(capabilities) > 0 {
		quoted := make([]string, len(capabilities))
		for i, capability := range capabilities {
			quoted[i] = strconv.Quote(string(capability))
		}
		source.WriteString("// The operations below need these client runtime capabilities. A runtime\n")
		source.WriteString("// that predates one fails to build this package instead of running without it.\n")
		fmt.Fprintf(&source, "var _ = client.RequireRuntimeCapabilities(%s)\n\n", strings.Join(quoted, ", "))
	}
	if generator.opts.Design != nil {
		design := *generator.opts.Design
		if design.SpecHash == "" {
			design.SpecHash = generator.spec.SpecHash
		}
		emitClientDesign(&source, generator.clientName+"Design", generator.clientName, design, designMethods)
	}
	fmt.Fprintf(&source, "// %s is the generated, typed client for service %s.\n", generator.clientName, generator.spec.Contract.Service.ID)
	emitOmittedOperations(&source, generator.omitted)
	fmt.Fprintf(&source, "type %s struct { transport *client.Client }\n\n", generator.clientName)
	fmt.Fprintf(&source, "// New%s retains the explicit low-level constructor for tests and external integrations.\n", generator.clientName)
	fmt.Fprintf(&source, "func New%s(transport *client.Client) *%s { return &%s{transport: client.WithGeneratedServiceDescriptor(transport, serviceDescriptor)} }\n\n", generator.clientName, generator.clientName, generator.clientName)
	bindingName := "New" + generator.clientName + "Binding"
	fmt.Fprintf(&source, "// %s constructs the safe generated client from an explicit binding without DI.\n", bindingName)
	fmt.Fprintf(&source, "func %s(binding client.ServiceBinding) (*%s, error) {\n", bindingName, generator.clientName)
	source.WriteString("\ttransport, err := client.NewServiceClientBinding(binding, serviceDescriptor)\n")
	source.WriteString("\tif err != nil { return nil, err }\n")
	source.WriteString("\treturn New" + generator.clientName + "(transport), nil\n}\n\n")
	fmt.Fprintf(&source, "// Bind%s binds caller-resolved URL, audience and operation paths without a service registry.\n", generator.clientName)
	fmt.Fprintf(&source, "// Reuse the result for this owner; release it with Close%s.\n", generator.clientName)
	fmt.Fprintf(&source, "func Bind%s(binding client.ServiceBinding) (*%s, error) {\n", generator.clientName, generator.clientName)
	source.WriteString("\ttransport, err := client.BindServiceClient(binding, serviceDescriptor)\n\tif err != nil { return nil, err }\n")
	fmt.Fprintf(&source, "\treturn New%s(transport), nil\n}\n\n", generator.clientName)
	fmt.Fprintf(&source, "// Close%s releases a caller-bound client and refuses subsequent calls.\n", generator.clientName)
	fmt.Fprintf(&source, "func Close%s(c *%s) error { return c.transport.Close() }\n\n", generator.clientName, generator.clientName)
	registerName := "Register" + generator.clientName
	fmt.Fprintf(&source, "// %s registers the safe generated client binding. Normal calls resolve client.ServiceBindings from DI; one override is accepted for tests.\n", registerName)
	fmt.Fprintf(&source, "func %s(module *app.Module, override ...client.ServiceBinding) *app.Module {\n", registerName)
	source.WriteString("\tif len(override) > 1 { panic(\"generated client registration accepts at most one binding override\") }\n")
	source.WriteString("\ttoken := inject.TokenOf[*" + generator.clientName + "]()\n")
	source.WriteString("\tif len(override) == 1 {\n")
	source.WriteString("\t\tbinding := override[0]\n")
	source.WriteString("\t\treturn module.Provide(inject.Provide(token, func(inject.Resolver) (any, error) {\n")
	source.WriteString("\t\t\treturn " + bindingName + "(binding)\n")
	source.WriteString("\t\t}))\n\t}\n")
	source.WriteString("\tbindingsToken := inject.TokenOf[*client.ServiceBindings]()\n")
	source.WriteString("\treturn module.Provide(inject.Provide(token, func(resolver inject.Resolver) (any, error) {\n")
	source.WriteString("\t\tbindings, err := inject.ResolveAs[*client.ServiceBindings](resolver, bindingsToken)\n")
	source.WriteString("\t\tif err != nil { return nil, err }\n")
	source.WriteString("\t\ttransport, err := client.NewServiceClient(bindings, serviceDescriptor)\n")
	source.WriteString("\t\tif err != nil { return nil, err }\n")
	source.WriteString("\t\treturn New" + generator.clientName + "(transport), nil\n")
	source.WriteString("\t}, inject.WithDeps(bindingsToken)))\n}\n\n")

	for _, name := range generator.order {
		source.WriteString(generator.defs[name])
		source.WriteString("\n")
	}
	source.WriteString(methods.String())
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return "", errors.Newf(CodeClientGenFormat, "api: format strict generated client: %v\n%s", err, source.String())
	}
	return string(formatted), nil
}

// specRuntimeCapabilities derives the runtime capabilities a first-party
// contract's operations require, exactly as the generated manifest lists them.
func specRuntimeCapabilities(spec SpecIR) []clientcontract.RuntimeCapability {
	var operations []clientcontract.GeneratedOperation
	for _, service := range spec.Services {
		for _, method := range service.Methods {
			if method.Client == nil {
				continue
			}
			operation := clientcontract.GeneratedOperation{Transports: method.Client.Transports}
			if method.Client.Resilience != nil {
				operation.Cache = method.Client.Resilience.Cache
			}
			operations = append(operations, operation)
		}
	}
	return clientcontract.RequiredRuntimeCapabilities(operations)
}

func (generator *strictClientGen) emitMethod(output *strings.Builder, methodName string, method MethodIR) error {
	generator.imports["context"] = true
	generator.imports["net/http"] = true
	generator.imports["net/url"] = true
	if method.Client == nil {
		return errors.Newf(CodeClientGenConfig, "api: strict operation %s has no client contract", method.OperationID)
	}
	if err := refuseUnhonorableTransports(method); err != nil {
		return err
	}
	if err := refuseBinaryStream(method); err != nil {
		return err
	}
	if method.Client.Stream != clientcontract.StreamUnary {
		return generator.emitStreamMethod(output, methodName, method)
	}
	if operationCarriesBinary(method) {
		return generator.emitBinaryMethod(output, methodName, method)
	}
	transport, err := generator.selectUnaryTransport(method)
	if err != nil {
		return err
	}
	inputName := methodName + "Input"
	groups := map[string][]ParameterIR{"path": {}, "query": {}, "header": {}}
	for _, parameter := range method.Parameters {
		if err := generator.refuseOpaqueParameter(method, parameter); err != nil {
			return err
		}
		if parameter.Schema.Type == "object" || parameter.Schema.Ref != "" || len(parameter.Schema.OneOf) > 0 {
			return errors.Newf(CodeClientGenConfig, "api: operation %s parameter %s has unsupported object serialization", method.OperationID, parameter.Name)
		}
		if generator.schemaNullable(parameter.Schema, map[string]bool{}) {
			return errors.Newf(CodeClientGenConfig, "api: operation %s parameter %s is nullable and has no lossless default wire serialization", method.OperationID, parameter.Name)
		}
		groups[parameter.Location] = append(groups[parameter.Location], parameter)
	}

	var bodySchema *clientcontract.Schema
	bodyRequired := false
	if method.Request != nil {
		if bodylessHTTPMethod(method.HTTPMethod) {
			// A GET or HEAD request body has no interoperable meaning: proxies,
			// caches and browsers are free to drop it. Emitting one would produce
			// a client whose calls silently lose their payload.
			return errors.Newf(CodeClientGenUnsupportedSemantic,
				"api: operation %s declares a request body on %s; GET and HEAD carry no body",
				method.OperationID, method.HTTPMethod)
		}
		bodyRequired = method.Request.Required
		for i := range method.Request.Content {
			if method.Request.Content[i].MediaType == "application/json" {
				bodySchema = method.Request.Content[i].Schema
			}
		}
		if bodySchema == nil {
			return errors.Newf(CodeClientGenConfig, "api: operation %s has no application/json request representation", method.OperationID)
		}
		if len(method.Request.Content) != 1 {
			return errors.Newf(CodeClientGenConfig, "api: operation %s has multiple request media types; explicit generated representation selection is required", method.OperationID)
		}
	}
	var input strings.Builder
	fmt.Fprintf(&input, "// %s is the complete typed input for %s.\ntype %s struct {\n", inputName, method.OperationID, inputName)
	for _, location := range []string{"path", "query", "header"} {
		parameters := groups[location]
		if len(parameters) == 0 {
			continue
		}
		groupName := methodName + exportedFieldName(location)
		if err := generator.declareParameterGroup(groupName, parameters); err != nil {
			return errors.Newf(CodeClientGenConfig, "api: operation %s: %v", method.OperationID, err)
		}
		fmt.Fprintf(&input, "\t%s %s `json:%q`\n", exportedFieldName(location), groupName, location)
	}
	if bodySchema != nil {
		bodyType, err := generator.schemaType(*bodySchema, methodName+"Body")
		if err != nil {
			return errors.Newf(CodeClientGenConfig, "api: operation %s request body: %v", method.OperationID, err)
		}
		bodyType, tag := generator.presenceType(bodyType, *bodySchema, bodyRequired, "body")
		fmt.Fprintf(&input, "\tBody %s `json:%q`\n", bodyType, tag)
	}
	input.WriteString("}\n")
	generator.addDef(inputName, input.String())

	// outputType is what client.Call decodes; returnType is what the method hands
	// back. A declared success body is always returned by pointer so the caller
	// can tell "no value" from a zero struct, matching the reflect-route emitter.
	// An operation declaring several success statuses returns its result type
	// instead, which carries the answered status beside the body.
	outputType := ""
	returnType := ""
	var result *successResult
	switch {
	case len(method.Successes) == 0:
		return errors.Newf(CodeClientGenConfig, "api: operation %s declares no success status", method.OperationID)
	case returnsSuccessResult(method):
		result, err = generator.declareSuccessResult(methodName, method)
		if err != nil {
			return err
		}
		outputType = "*" + result.typeName
		returnType = outputType
	default:
		success := method.Successes[0]
		if len(success.Headers) > 0 {
			return errors.Newf(CodeClientGenConfig, "api: operation %s has typed response headers; result-union emission is required", method.OperationID)
		}
		if len(success.Content) > 1 {
			return errors.Newf(CodeClientGenConfig, "api: operation %s has multiple success media types; result-union emission is required", method.OperationID)
		}
		if len(success.Content) == 1 {
			if success.Content[0].MediaType != "application/json" || success.Content[0].Schema == nil {
				return errors.Newf(CodeClientGenConfig, "api: operation %s success representation %s is unsupported by REST JSON emission", method.OperationID, success.Content[0].MediaType)
			}
			outputType, err = generator.schemaType(*success.Content[0].Schema, methodName+"Output")
			if err != nil {
				return errors.Newf(CodeClientGenConfig, "api: operation %s success body: %v", method.OperationID, err)
			}
			if generator.schemaNullable(*success.Content[0].Schema, map[string]bool{}) {
				outputType = "*" + outputType
			}
			returnType = outputType
			if !strings.HasPrefix(returnType, "*") {
				returnType = "*" + returnType
			}
		}
	}

	operationJSON, err := json.Marshal(method.Client)
	if err != nil {
		return errors.New(CodeClientGenConfig, "api: encode generated operation contract")
	}
	successes := make([]operationSuccessJSON, len(method.Successes))
	for i := range method.Successes {
		successes[i] = operationSuccessJSON{Status: method.Successes[i].Status}
		for _, content := range method.Successes[i].Content {
			successes[i].Content = append(successes[i].Content, operationContent(content))
		}
	}
	successJSON, err := json.Marshal(successes)
	if err != nil {
		return errors.New(CodeClientGenConfig, "api: encode generated success contract")
	}
	operationVar := lowerFirst(methodName) + "Operation"
	if method.Request == nil {
		fmt.Fprintf(output, "var %s = client.MustOperation(%q, %q, %q)\n\n", operationVar, method.OperationID, string(operationJSON), string(successJSON))
	} else {
		requestJSON, requestErr := json.Marshal(method.Request)
		if requestErr != nil {
			return errors.New(CodeClientGenConfig, "api: encode generated request contract")
		}
		fmt.Fprintf(output, "var %s = client.MustOperation(%q, %q, %q, %q)\n\n", operationVar, method.OperationID, string(operationJSON), string(successJSON), string(requestJSON))
	}

	decoderName, err := generator.declareTypedErrors(methodName, method)
	if err != nil {
		return err
	}
	fmt.Fprintf(output, "// %s calls %s through its generated service binding.\n", methodName, method.OperationID)
	if outputType == "" {
		fmt.Fprintf(output, "func (c *%s) %s(ctx context.Context, in %s) error {\n", generator.clientName, methodName, inputName)
	} else {
		fmt.Fprintf(output, "func (c *%s) %s(ctx context.Context, in %s) (%s, error) {\n", generator.clientName, methodName, inputName, returnType)
	}
	fmt.Fprintf(output, "\tpath := %q\n", transport.Path)
	if err := generator.emitPathParams(output, groups["path"]); err != nil {
		return err
	}
	callLiteral := "\tcall := &client.OperationCall{Request: request}\n"
	if len(groups["path"]) > 0 {
		callLiteral = "\tcall := &client.OperationCall{Request: request, PathParams: params}\n"
	}
	output.WriteString("\tquery := url.Values{}\n\theaders := make(http.Header)\n")
	for _, parameter := range groups["query"] {
		if err := generator.emitParameter(output, "query", "in.Query."+exportedFieldName(parameter.Name), parameter); err != nil {
			return err
		}
	}
	for _, parameter := range groups["header"] {
		if err := generator.emitParameter(output, "headers", "in.Header."+exportedFieldName(parameter.Name), parameter); err != nil {
			return err
		}
	}
	output.WriteString("\tvar body []byte\n\tvar err error\n")
	if bodySchema != nil {
		switch {
		case bodyRequired:
			output.WriteString("\tbody, err = client.EncodeJSON(in.Body)\n")
		case generator.schemaNullable(*bodySchema, map[string]bool{}):
			output.WriteString("\tif value, present := in.Body.Value(); present { body, err = client.EncodeJSON(value) } else if in.Body.IsNull() { body = []byte(\"null\") }\n")
		default:
			output.WriteString("\tif in.Body != nil { body, err = client.EncodeJSON(in.Body) }\n")
		}
		output.WriteString("\tif err != nil { ")
		if outputType != "" {
			output.WriteString("return nil, err")
		} else {
			output.WriteString("return err")
		}
		output.WriteString(" }\n\theaders.Set(\"Content-Type\", \"application/json\")\n")
	}
	fmt.Fprintf(output, "\trequest := &client.Request{Method: %q, Path: path, QueryValues: query, Headers: headers, Body: body", method.HTTPMethod)
	if generator.opts.Design != nil {
		fmt.Fprintf(output, ", FeatureTrace: %sDesign.Trace(%q)", generator.clientName, method.OperationID)
	}
	output.WriteString("}\n")
	output.WriteString(callLiteral)
	switch {
	case result != nil:
		generator.emitSuccessResultDispatch(output, result, operationVar, decoderName)
	case outputType == "":
		fmt.Fprintf(output, "\terr = client.CallOperationVoid(ctx, c.transport, call, %s)\n", operationVar)
		if decoderName != "" {
			fmt.Fprintf(output, "\tif err != nil { return %s(err) }\n\treturn nil\n", decoderName)
		} else {
			output.WriteString("\treturn err\n")
		}
	default:
		fmt.Fprintf(output, "\tresult, err := client.CallOperation[%s](ctx, c.transport, call, %s)\n", outputType, operationVar)
		if decoderName != "" {
			fmt.Fprintf(output, "\tif err != nil { return nil, %s(err) }\n", decoderName)
		} else {
			output.WriteString("\tif err != nil { return nil, err }\n")
		}
		if returnType == outputType {
			output.WriteString("\treturn result, nil\n")
		} else {
			output.WriteString("\treturn &result, nil\n")
		}
	}
	output.WriteString("}\n\n")
	return nil
}

func (generator *strictClientGen) emitServerStreamMethod(output *strings.Builder, methodName string, method MethodIR) error {
	transport, err := generator.selectServerStreamTransport(method)
	if err != nil {
		return err
	}
	if method.Client.Messages == nil || method.Client.Messages.Output == nil || method.Client.Messages.Input != nil {
		return errors.Newf(CodeClientGenConfig, "api: server stream operation %s has invalid logical message schemas", method.OperationID)
	}
	if method.Request != nil {
		return errors.Newf(CodeClientGenConfig, "api: server stream operation %s has an unsupported HTTP request body", method.OperationID)
	}

	groups, inputName, err := generator.declareStreamInput(methodName, method)
	if err != nil {
		return err
	}
	outputType, err := generator.streamMessageType(*method.Client.Messages.Output, methodName+"Message")
	if err != nil {
		return err
	}
	operationVar, decoderName, err := generator.declareStreamOperation(output, methodName, method)
	if err != nil {
		return err
	}

	// One entrypoint for every declared order. client.OpenOperationServerStream
	// walks the declared transports at call time — Connect, SSE or the
	// first-party WebSocket wire — opens the first it can carry, and falls back
	// to the next only when the provider says that wire is not served at this
	// path. Moving an operation between transports therefore never reaches the
	// consuming application, never regenerates this method, and neither does a
	// fallback: a fallback is a second opening of this same method.
	fmt.Fprintf(output, "// %s opens %s through its generated service binding.\n", methodName, method.OperationID)
	fmt.Fprintf(output, "func (c *%s) %s(ctx context.Context, in %s) (*client.Stream[%s], error) {\n", generator.clientName, methodName, inputName, outputType)
	fmt.Fprintf(output, "\tpath := %q\n", transport.Path)
	if err := generator.emitPathParams(output, groups["path"]); err != nil {
		return err
	}
	// A Connect envelope carries the path parameters as a message section, so
	// the call hands the runtime both projections of the same declaration.
	callLiteral := "\tcall := &client.OperationCall{Request: request}\n"
	if len(groups["path"]) > 0 {
		callLiteral = "\tcall := &client.OperationCall{Request: request, PathParams: params}\n"
	}
	output.WriteString("\tquery := url.Values{}\n\theaders := make(http.Header)\n")
	for _, parameter := range groups["query"] {
		if err := generator.emitParameter(output, "query", "in.Query."+exportedFieldName(parameter.Name), parameter); err != nil {
			return err
		}
	}
	for _, parameter := range groups["header"] {
		if err := generator.emitParameter(output, "headers", "in.Header."+exportedFieldName(parameter.Name), parameter); err != nil {
			return err
		}
	}
	fmt.Fprintf(output, "\trequest := &client.Request{Method: http.MethodGet, Path: path, QueryValues: query, Headers: headers")
	if generator.opts.Design != nil {
		fmt.Fprintf(output, ", FeatureTrace: %sDesign.Trace(%q)", generator.clientName, method.OperationID)
	}
	output.WriteString("}\n")
	output.WriteString(callLiteral)
	if decoderName == "" {
		fmt.Fprintf(output, "\treturn client.OpenOperationServerStream[%s](ctx, c.transport, call, %s)\n", outputType, operationVar)
	} else {
		fmt.Fprintf(output, "\treturn client.OpenOperationServerStream[%s](ctx, c.transport, call, %s, %s)\n", outputType, operationVar, decoderName)
	}
	output.WriteString("}\n\n")
	return nil
}

type operationSuccessJSON struct {
	Status  int                    `json:"status"`
	Content []operationContentJSON `json:"content"`
}

type operationContentJSON struct {
	MediaType string                 `json:"mediaType"`
	Schema    *clientcontract.Schema `json:"schema,omitempty"`
	// MaxBytes carries the declared byte bound of a raw octet representation to
	// the runtime, which caps the response read on it.
	MaxBytes int64 `json:"maxBytes,omitempty"`
	Streamed bool  `json:"streamed,omitempty"`
}

// operationContent projects one IR representation into the runtime metadata a
// generated method embeds. The two shapes are field-identical on purpose: the
// runtime reads exactly what the IR carried, media type, schema and declared
// octet bound included.
func operationContent(content ContentIR) operationContentJSON {
	return operationContentJSON(content)
}

func (generator *strictClientGen) declareParameterGroup(name string, parameters []ParameterIR) error {
	var definition strings.Builder
	fmt.Fprintf(&definition, "type %s struct {\n", name)
	for _, parameter := range parameters {
		base, err := generator.schemaType(parameter.Schema, name+exportedFieldName(parameter.Name))
		if err != nil {
			return fmt.Errorf("parameter %s: %w", parameter.Name, err)
		}
		fieldType, tag := generator.presenceType(base, parameter.Schema, parameter.Required, parameter.Name)
		fmt.Fprintf(&definition, "\t%s %s `json:%q`\n", exportedFieldName(parameter.Name), fieldType, tag)
	}
	definition.WriteString("}\n")
	generator.addDef(name, definition.String())
	return nil
}

func (generator *strictClientGen) schemaType(schema clientcontract.Schema, hint string) (string, error) {
	if schema.Ref != "" {
		return exportedFieldName(strings.TrimPrefix(schema.Ref, "#/components/schemas/")), nil
	}
	// An opaque value is carried as the provider's own bytes. Decoding it into
	// `any` would turn every number into a float64 and reorder every object.
	if schema.IsOpaqueJSON() {
		generator.imports["encoding/json"] = true
		return "json.RawMessage", nil
	}
	if len(schema.OneOf) > 0 {
		name := exportedFieldName(hint)
		if _, err := generator.declareUnion(name, schema); err != nil {
			return "", err
		}
		return name, nil
	}
	if len(schema.Enum) > 0 {
		name := exportedFieldName(hint)
		if _, err := generator.declareEnum(name, schema); err != nil {
			return "", err
		}
		return name, nil
	}
	switch schema.Type {
	case "string":
		switch schema.Format {
		case "byte", "binary":
			return "[]byte", nil
		case "date-time":
			generator.imports["time"] = true
			return "time.Time", nil
		default:
			return "string", nil
		}
	case "integer":
		// D0.2: the declared format carries the width. Inferring int64 from an
		// absent format silently disagrees with the TypeScript emitter and with
		// the proto descriptors, so an unformatted integer never emits.
		switch schema.Format {
		case "int32":
			return "int32", nil
		case "int64":
			return "int64", nil
		case "uint32":
			return "uint32", nil
		case "uint64":
			return "uint64", nil
		case "":
			return "", fmt.Errorf("integer schema has no format; declare int32, int64, uint32 or uint64")
		default:
			return "", fmt.Errorf("integer format %q is not one of int32, int64, uint32, uint64", schema.Format)
		}
	case "number":
		if schema.Format == "float" {
			return "float32", nil
		}
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "array":
		if schema.Items == nil {
			return "", fmt.Errorf("array schema has no items")
		}
		itemType, err := generator.schemaValueType(*schema.Items, hint+"Item")
		if err != nil {
			return "", err
		}
		return "[]" + itemType, nil
	case "object":
		if schema.IsFreeFormObject() {
			generator.imports["encoding/json"] = true
			return "map[string]json.RawMessage", nil
		}
		if schema.AdditionalProperties != nil && schema.AdditionalProperties.Schema != nil {
			if len(schema.Properties) != 0 {
				return "", fmt.Errorf("object mixes named properties and additionalProperties")
			}
			valueType, err := generator.schemaValueType(*schema.AdditionalProperties.Schema, hint+"Value")
			if err != nil {
				return "", err
			}
			return "map[string]" + valueType, nil
		}
		if schema.AdditionalProperties == nil || schema.AdditionalProperties.Allowed == nil || *schema.AdditionalProperties.Allowed {
			return "", fmt.Errorf("open object cannot be emitted without an untyped value")
		}
		name := exportedFieldName(hint)
		if _, err := generator.declareObject(name, schema); err != nil {
			return "", err
		}
		return name, nil
	default:
		return "", fmt.Errorf("schema has unsupported or missing type %q", schema.Type)
	}
}

func (generator *strictClientGen) schemaValueType(schema clientcontract.Schema, hint string) (string, error) {
	base, err := generator.schemaType(schema, hint)
	if err != nil {
		return "", err
	}
	if generator.schemaNullable(schema, map[string]bool{}) {
		return "*" + base, nil
	}
	return base, nil
}

func (generator *strictClientGen) schemaNullable(schema clientcontract.Schema, visiting map[string]bool) bool {
	if schema.Nullable != nil && *schema.Nullable {
		return true
	}
	if schema.Ref == "" {
		return false
	}
	name := strings.TrimPrefix(schema.Ref, "#/components/schemas/")
	if visiting[name] {
		return false
	}
	resolved, ok := generator.spec.Schemas[name]
	if !ok {
		return false
	}
	visiting[name] = true
	defer delete(visiting, name)
	return generator.schemaNullable(resolved, visiting)
}

func (generator *strictClientGen) declareNamed(name string, schema clientcontract.Schema) (string, error) {
	if _, exists := generator.defs[name]; exists || generator.declaring[name] {
		return name, nil
	}
	generator.declaring[name] = true
	defer delete(generator.declaring, name)
	if len(schema.Enum) > 0 {
		return generator.declareEnum(name, schema)
	}
	if len(schema.OneOf) > 0 {
		return generator.declareUnion(name, schema)
	}
	if schema.Type == "object" && schema.AdditionalProperties != nil && schema.AdditionalProperties.Allowed != nil && !*schema.AdditionalProperties.Allowed {
		return generator.declareObject(name, schema)
	}
	if schema.IsOpaqueJSON() {
		// An alias, not a defined type: a defined type would drop
		// json.RawMessage's methods and marshal the bytes as base64.
		generator.imports["encoding/json"] = true
		generator.addDef(name, fmt.Sprintf("type %s = json.RawMessage\n", name))
		return name, nil
	}
	base, err := generator.schemaType(schema, name+"Value")
	if err != nil {
		return "", err
	}
	generator.addDef(name, fmt.Sprintf("type %s %s\n", name, base))
	return name, nil
}

func (generator *strictClientGen) declareObject(name string, schema clientcontract.Schema) (string, error) {
	if _, exists := generator.defs[name]; exists {
		return name, nil
	}
	required := make(map[string]bool, len(schema.Required))
	for _, field := range schema.Required {
		required[field] = true
	}
	var definition strings.Builder
	fmt.Fprintf(&definition, "type %s struct {\n", name)
	for _, fieldName := range sortedKeys(schema.Properties) {
		fieldSchema := schema.Properties[fieldName]
		base, err := generator.schemaType(fieldSchema, name+exportedFieldName(fieldName))
		if err != nil {
			return "", err
		}
		fieldType, tag := generator.presenceType(base, fieldSchema, required[fieldName], fieldName)
		fmt.Fprintf(&definition, "\t%s %s `json:%q`\n", exportedFieldName(fieldName), fieldType, tag)
	}
	definition.WriteString("}\n")
	generator.addDef(name, definition.String())
	return name, nil
}

func (generator *strictClientGen) declareEnum(name string, schema clientcontract.Schema) (string, error) {
	if _, exists := generator.defs[name]; exists {
		return name, nil
	}
	base := "string"
	if schema.Type == "integer" {
		var err error
		base, err = generator.schemaType(clientcontract.Schema{Type: "integer", Format: schema.Format}, name)
		if err != nil {
			return "", err
		}
	} else if schema.Type != "string" {
		return "", fmt.Errorf("enum type %q is unsupported", schema.Type)
	}
	var definition strings.Builder
	fmt.Fprintf(&definition, "type %s %s\n\nconst (\n", name, base)
	used := map[string]bool{}
	for index, raw := range schema.Enum {
		literal := string(raw)
		memberPart := strings.Trim(string(raw), "\"")
		member := name + exportedFieldName(memberPart)
		if member == name+"Field" || used[member] {
			member = name + "Value" + strconv.Itoa(index+1)
		}
		used[member] = true
		fmt.Fprintf(&definition, "\t%s %s = %s\n", member, name, literal)
	}
	definition.WriteString(")\n")
	generator.addDef(name, definition.String())
	return name, nil
}

func (generator *strictClientGen) declareUnion(name string, schema clientcontract.Schema) (string, error) {
	if _, exists := generator.defs[name]; exists {
		return name, nil
	}
	if schema.Discriminator == nil || len(schema.Discriminator.Mapping) == 0 {
		return "", fmt.Errorf("oneOf schema has no discriminator mapping")
	}
	generator.imports["encoding/json"] = true
	generator.imports["errors"] = true
	kindName := name + "Kind"
	tags := sortedKeys(schema.Discriminator.Mapping)
	var definition strings.Builder
	fmt.Fprintf(&definition, "type %s string\n\nconst (\n", kindName)
	for index, tag := range tags {
		member := kindName + exportedFieldName(tag)
		if member == kindName+"Field" {
			member += strconv.Itoa(index + 1)
		}
		fmt.Fprintf(&definition, "\t%s %s = %q\n", member, kindName, tag)
	}
	definition.WriteString(")\n\n")
	fmt.Fprintf(&definition, "type %s struct {\n", name)
	for _, tag := range tags {
		variantName := exportedFieldName(strings.TrimPrefix(schema.Discriminator.Mapping[tag], "#/components/schemas/"))
		fmt.Fprintf(&definition, "\t%s *%s `json:\"-\"`\n", exportedFieldName(tag), variantName)
	}
	definition.WriteString("}\n\n")
	fmt.Fprintf(&definition, "func (value %s) MarshalJSON() ([]byte, error) {\n", name)
	definition.WriteString("\tselected := 0\n")
	for _, tag := range tags {
		fmt.Fprintf(&definition, "\tif value.%s != nil { selected++ }\n", exportedFieldName(tag))
	}
	definition.WriteString("\tif selected != 1 { return nil, errors.New(\"union must have exactly one selected variant\") }\n")
	for _, tag := range tags {
		field := exportedFieldName(tag)
		fmt.Fprintf(&definition, "\tif value.%s != nil { payload, err := json.Marshal(value.%s); if err != nil { return nil, err }; var object map[string]json.RawMessage; if err := json.Unmarshal(payload, &object); err != nil { return nil, err }; object[%q] = json.RawMessage(%q); return json.Marshal(object) }\n", field, field, schema.Discriminator.PropertyName, strconv.Quote(tag))
	}
	definition.WriteString("\treturn nil, errors.New(\"union has no selected variant\")\n}\n\n")
	fmt.Fprintf(&definition, "func (value *%s) UnmarshalJSON(data []byte) error {\n", name)
	fmt.Fprintf(&definition, "\tvar discriminator struct { Kind string `json:%q` }; if err := json.Unmarshal(data, &discriminator); err != nil { return err }\n", schema.Discriminator.PropertyName)
	fmt.Fprintf(&definition, "\t*value = %s{}\n", name)
	definition.WriteString("\tswitch discriminator.Kind {\n")
	for _, tag := range tags {
		field := exportedFieldName(tag)
		variantName := exportedFieldName(strings.TrimPrefix(schema.Discriminator.Mapping[tag], "#/components/schemas/"))
		fmt.Fprintf(&definition, "\tcase %q: var variant %s; if err := json.Unmarshal(data, &variant); err != nil { return err }; value.%s = &variant; return nil\n", tag, variantName, field)
	}
	definition.WriteString("\tdefault: return fmt.Errorf(\"unknown union discriminator %q\", discriminator.Kind)\n\t}\n}\n")
	generator.addDef(name, definition.String())
	return name, nil
}

func (generator *strictClientGen) validateNames() error {
	claimed := map[string]string{
		generator.clientName:                     "generated client",
		"New" + generator.clientName:             "generated low-level constructor",
		"New" + generator.clientName + "Binding": "generated explicit binding constructor",
		"Register" + generator.clientName:        "generated binding registration",
		"Bind" + generator.clientName:            "generated caller binding",
		"Close" + generator.clientName:           "generated binding cleanup",
	}
	claim := func(name, origin string) error {
		if previous := claimed[name]; previous != "" {
			return errors.Newf(CodeClientGenCollision, "api: %s and %s derive Go symbol %q", previous, origin, name)
		}
		claimed[name] = origin
		return nil
	}
	componentNames := make(map[string]string, len(generator.spec.Schemas))
	for _, sourceName := range sortedKeys(generator.spec.Schemas) {
		name := exportedFieldName(sourceName)
		if previous := componentNames[name]; previous != "" {
			return errors.Newf(CodeClientGenCollision, "api: schemas %s and %s derive Go type %q", previous, sourceName, name)
		}
		componentNames[name] = sourceName
		if err := claim(name, "schema "+sourceName); err != nil {
			return err
		}
		if err := validateSchemaPropertyNames(generator.spec.Schemas[sourceName], "schema "+sourceName, generator.spec.Schemas, map[string]bool{}); err != nil {
			return err
		}
	}
	for _, service := range generator.spec.Services {
		for _, method := range service.Methods {
			methodName := exportedFieldName(method.Name)
			for _, symbol := range []struct{ name, origin string }{
				{methodName + "Input", "operation " + method.OperationID + " input"},
				{lowerFirst(methodName) + "Operation", "operation " + method.OperationID + " descriptor"},
			} {
				if err := claim(symbol.name, symbol.origin); err != nil {
					return err
				}
			}
			if returnsSuccessResult(method) {
				if err := claim(successResultName(generator.symbols[method.OperationID]), "operation "+method.OperationID+" result"); err != nil {
					return err
				}
			}
			for _, location := range []string{"path", "query", "header"} {
				for _, parameter := range method.Parameters {
					if parameter.Location == location {
						if err := claim(methodName+exportedFieldName(location), "operation "+method.OperationID+" "+location+" parameters"); err != nil {
							return err
						}
						break
					}
				}
			}
			if method.Client != nil {
				for _, declared := range method.Client.Errors {
					typeName := methodName + exportedFieldName(declared.Code) + "Error"
					if err := claim(typeName, "operation "+method.OperationID+" error "+declared.Code); err != nil {
						return err
					}
				}
			}
		}
	}
	return nil
}

func validateSchemaPropertyNames(schema clientcontract.Schema, origin string, schemas map[string]clientcontract.Schema, visiting map[string]bool) error {
	if schema.Ref != "" {
		name := strings.TrimPrefix(schema.Ref, "#/components/schemas/")
		if visiting[name] {
			return nil
		}
		if resolved, ok := schemas[name]; ok {
			visiting[name] = true
			defer delete(visiting, name)
			return validateSchemaPropertyNames(resolved, origin, schemas, visiting)
		}
	}
	fields := map[string]string{}
	for _, property := range sortedKeys(schema.Properties) {
		field := exportedFieldName(property)
		if previous := fields[field]; previous != "" {
			return errors.Newf(CodeClientGenCollision, "api: %s properties %s and %s derive Go field %q", origin, previous, property, field)
		}
		fields[field] = property
		if err := validateSchemaPropertyNames(schema.Properties[property], origin+"."+property, schemas, visiting); err != nil {
			return err
		}
	}
	if schema.Items != nil {
		return validateSchemaPropertyNames(*schema.Items, origin+"[]", schemas, visiting)
	}
	return nil
}

func (generator *strictClientGen) presenceType(base string, schema clientcontract.Schema, required bool, jsonName string) (string, string) {
	if generator.opaqueJSON(schema) {
		if required {
			return base, jsonName
		}
		// json.RawMessage already has three states: absent is empty, an
		// explicit null is the bytes `null`, and anything else is the value.
		// A pointer would fold null into absent when it decodes.
		return base, jsonName + ",omitempty"
	}
	nullable := generator.schemaNullable(schema, map[string]bool{})
	if required {
		if nullable {
			return "*" + base, jsonName
		}
		return base, jsonName
	}
	if nullable {
		return "client.Optional[" + base + "]", jsonName + ",omitzero"
	}
	return "*" + base, jsonName + ",omitempty"
}

// errOpaqueParameter is the one refusal for an opaque JSON parameter, whether
// the parameter declares the value inline or reaches it through a reference.
var errOpaqueParameter = fmt.Errorf("an opaque JSON value is not representable as a parameter; carry it in a JSON body")

// refuseOpaqueParameter refuses a parameter that is, or is an array of, an
// opaque JSON value. A parameter travels as text, and an opaque value has no
// text form the two runtimes agree on. The check reads through component
// references and runs before the general parameter rules, so a referenced
// opaque value gets the same refusal as an inline one.
func (generator *strictClientGen) refuseOpaqueParameter(method MethodIR, parameter ParameterIR) error {
	resolved := generator.resolveReference(parameter.Schema)
	if resolved.IsOpaqueJSON() || (resolved.Type == "array" && resolved.Items != nil && generator.opaqueJSON(*resolved.Items)) {
		return errors.Newf(CodeClientGenUnsupportedSemantic, "api: operation %s parameter %s: %v",
			method.OperationID, parameter.Name, errOpaqueParameter)
	}
	return nil
}

func (generator *strictClientGen) parameterExpression(expression string, schema clientcontract.Schema) (string, error) {
	if generator.opaqueJSON(schema) {
		return "", errOpaqueParameter
	}
	switch schema.Type {
	case "string":
		if schema.Format == "date-time" {
			generator.imports["time"] = true
			return expression + ".Format(time.RFC3339Nano)", nil
		}
		if schema.Format == "byte" || schema.Format == "binary" {
			generator.imports["encoding/base64"] = true
			return "base64.StdEncoding.EncodeToString(" + expression + ")", nil
		}
		return expression, nil
	case "integer", "number", "boolean":
		generator.imports["fmt"] = true
		return "fmt.Sprint(" + expression + ")", nil
	default:
		return "", fmt.Errorf("parameter schema type %q is unsupported", schema.Type)
	}
}

func (generator *strictClientGen) emitParameter(output *strings.Builder, target, expression string, parameter ParameterIR) error {
	name := parameter.Name
	setter := target + ".Add"
	if target == "headers" {
		setter = target + ".Add"
	}
	if parameter.Schema.Type == "array" {
		if parameter.Schema.Items == nil {
			return fmt.Errorf("array parameter %s has no items", name)
		}
		if !parameter.Required {
			fmt.Fprintf(output, "\tif %s != nil {\n", expression)
			expression = "*" + expression
		}
		fmt.Fprintf(output, "\tfor _, value := range %s {\n", expression)
		encoded, err := generator.parameterExpression("value", *parameter.Schema.Items)
		if err != nil {
			return err
		}
		indent := "\t\t"
		if !parameter.Required {
			indent = "\t\t\t"
		}
		fmt.Fprintf(output, "%s%s(%q, %s)\n\t}\n", indent, setter, name, encoded)
		if !parameter.Required {
			output.WriteString("\t}\n")
		}
		return nil
	}
	valueExpression := expression
	if !parameter.Required {
		fmt.Fprintf(output, "\tif %s != nil {\n", expression)
		valueExpression = "*" + expression
	}
	encoded, err := generator.parameterExpression(valueExpression, parameter.Schema)
	if err != nil {
		return err
	}
	indent := "\t"
	if !parameter.Required {
		indent = "\t\t"
	}
	fmt.Fprintf(output, "%s%s(%q, %s)\n", indent, setter, name, encoded)
	if !parameter.Required {
		output.WriteString("\t}\n")
	}
	return nil
}

func (generator *strictClientGen) declareTypedErrors(methodName string, method MethodIR) (string, error) {
	var cases []string
	needsJSON := false
	for _, declared := range method.Client.Errors {
		if strings.TrimSpace(declared.Code) == "" {
			// D0.1: selectDeclaredError matches on the wire code. A blank code
			// collapses every typed error sharing the status back to a generic
			// remote error, so the declaration is refused at generation instead.
			return "", errors.Newf(CodeClientGenConfig,
				"api: operation %s declares HTTP %d with no stable error code; add .MayThrow(<code>) for status %d",
				method.OperationID, declared.Status, declared.Status)
		}
		typeName := methodName + exportedFieldName(declared.Code) + "Error"
		if declared.Schema == nil {
			var definition strings.Builder
			fmt.Fprintf(&definition, "// %s is the %q error declared by %s. It carries no details body, so\n", typeName, declared.Code, method.OperationID)
			definition.WriteString("// the stable code and the HTTP status are read from Remote.\n")
			fmt.Fprintf(&definition, "type %s struct { Remote *client.RemoteError }\n", typeName)
			fmt.Fprintf(&definition, "func (typed *%s) Error() string { return typed.Remote.Error() }\n", typeName)
			fmt.Fprintf(&definition, "func (typed *%s) Unwrap() error { return typed.Remote }\n", typeName)
			generator.addDef(typeName, definition.String())
			cases = append(cases, fmt.Sprintf("case %q: return &%s{Remote: remote}", declared.Code, typeName))
			continue
		}
		payloadType, err := generator.schemaType(*declared.Schema, typeName+"Payload")
		if err != nil {
			return "", err
		}
		needsJSON = true
		var definition strings.Builder
		// ADR 0006: errors[].schema describes the envelope's `details` member, so
		// the generated payload type is that details body. The envelope's own
		// fields reach the caller through Remote and are never duplicated here.
		fmt.Fprintf(&definition, "// %s is the %q error declared by %s. Payload is the\n", typeName, declared.Code, method.OperationID)
		definition.WriteString("// provider-declared details body; the stable code and the HTTP status are\n")
		definition.WriteString("// read from Remote.\n")
		fmt.Fprintf(&definition, "type %s struct { Remote *client.RemoteError; Payload *%s }\n", typeName, payloadType)
		fmt.Fprintf(&definition, "func (typed *%s) Error() string { return typed.Remote.Error() }\n", typeName)
		fmt.Fprintf(&definition, "func (typed *%s) Unwrap() error { return typed.Remote }\n", typeName)
		generator.addDef(typeName, definition.String())
		cases = append(cases, fmt.Sprintf("case %q: var payload *%s; if len(remote.Payload) != 0 { value := new(%s); if json.Unmarshal(remote.Payload, value) == nil { payload = value } }; return &%s{Remote: remote, Payload: payload}", declared.Code, payloadType, payloadType, typeName))
	}
	if len(cases) == 0 {
		return "", nil
	}
	generator.imports["errors"] = true
	if needsJSON {
		generator.imports["encoding/json"] = true
	}
	name := "decode" + methodName + "Error"
	var helper strings.Builder
	fmt.Fprintf(&helper, "func %s(err error) error { var remote *client.RemoteError; if !errors.As(err, &remote) { return err }; switch remote.Code() {\n", name)
	for _, item := range cases {
		helper.WriteString("\t" + item + "\n")
	}
	helper.WriteString("\tdefault: return remote\n\t}\n}\n")
	generator.addDef(name, helper.String())
	return name, nil
}

func (generator *strictClientGen) addDef(name, source string) {
	if _, exists := generator.defs[name]; exists {
		return
	}
	generator.defs[name] = source
	generator.order = append(generator.order, name)
}

func lowerFirst(value string) string {
	if value == "" {
		return value
	}
	return strings.ToLower(value[:1]) + value[1:]
}

// strictMethodSymbols is the single source of the Go symbol every first-party
// operation gets, keyed by operationId. The emitter and the generated ownership
// manifest both call it on the same post-omission contract, so the two can
// never disagree (ADR 0003).
//
// Each operation starts from strictMethodSymbol. That derivation drops path
// parameters, so routes that differ only by one — GET /x/{a}/deploy and
// GET /x/{a}/deploy/{b} — reduce to the same symbol. Within such a group one
// operation keeps the symbol, and every other synthesized member takes
// strictDistinctMethodSymbol, which keeps its path parameters. The keeper is an
// authored operationId when the group has one, because author intent is never
// renamed; otherwise it is the synthesized member with the fewest path
// parameters, then the smallest canonical operationId. The choice reads only
// the operations themselves, never their position, so registration order
// cannot change a symbol, and an operation without a sibling keeps the symbol
// it has always had. Two operations that still share a symbol are a collision
// the provider resolves by renaming a route or authoring a distinct operationId.
func strictMethodSymbols(services []ServiceIR) (map[string]string, error) {
	count := 0
	for _, service := range services {
		count += len(service.Methods)
	}
	methods := make([]MethodIR, 0, count)
	for _, service := range services {
		methods = append(methods, service.Methods...)
	}
	keepers := make(map[string]MethodIR, len(methods))
	for _, method := range methods {
		symbol := strictMethodSymbol(method)
		if keeper, found := keepers[symbol]; !found || keepsSymbolBefore(method, keeper) {
			keepers[symbol] = method
		}
	}
	symbols := make(map[string]string, len(methods))
	owners := make(map[string]string, len(methods))
	for _, method := range methods {
		symbol := strictMethodSymbol(method)
		keeper := keepers[symbol]
		if isSynthesizedOperationID(method.OperationID, method.HTTPMethod, method.Path) &&
			(keeper.HTTPMethod != method.HTTPMethod || keeper.Path != method.Path) {
			symbol = strictDistinctMethodSymbol(method)
		}
		if previous, taken := owners[symbol]; taken {
			return nil, errors.Newf(CodeClientGenCollision,
				"api: operations %s and %s derive Go method %q; rename one route path or author a distinct operationId",
				previous, method.OperationID, symbol)
		}
		owners[symbol] = method.OperationID
		symbols[method.OperationID] = symbol
	}
	return symbols, nil
}

// keepsSymbolBefore orders the operations that share one strictMethodSymbol:
// an authored operationId first, then fewer path parameters, then the smaller
// canonical operationId, then the smaller path and method. Two distinct routes
// can share a canonical operationId (/{a}/a and /a/{a}), so the last key is
// what makes the order total over distinct routes: exactly one operation keeps
// the shared symbol whatever order they arrive in.
func keepsSymbolBefore(candidate, keeper MethodIR) bool {
	candidateAuthored := !isSynthesizedOperationID(candidate.OperationID, candidate.HTTPMethod, candidate.Path)
	keeperAuthored := !isSynthesizedOperationID(keeper.OperationID, keeper.HTTPMethod, keeper.Path)
	if candidateAuthored != keeperAuthored {
		return candidateAuthored
	}
	if candidateParams, keeperParams := strings.Count(candidate.Path, "{"), strings.Count(keeper.Path, "{"); candidateParams != keeperParams {
		return candidateParams < keeperParams
	}
	if candidateID, keeperID := CanonicalOperationID(candidate.HTTPMethod, candidate.Path), CanonicalOperationID(keeper.HTTPMethod, keeper.Path); candidateID != keeperID {
		return candidateID < keeperID
	}
	if candidate.Path != keeper.Path {
		return candidate.Path < keeper.Path
	}
	return candidate.HTTPMethod < keeper.HTTPMethod
}

// strictMethodSymbol is the Go symbol a first-party operation gets before
// strictMethodSymbols resolves collisions.
//
// A provider-authored operationId is author intent and wins: a TypeScript
// provider that declares "replaceUser" gets ReplaceUser, not UpdateUsers. An
// operationId that is only the framework's own synthesis from method and path
// carries no intent, so the symbol falls back to clientcontract.RPCName, the
// derivation the reflect-route emitter and the proto/gRPC bridge share, which
// keeps one Go symbol per operation across REST and Connect. The
// operationId stays the wire identity either way; only the Go surface changes.
func strictMethodSymbol(method MethodIR) string {
	if isSynthesizedOperationID(method.OperationID, method.HTTPMethod, method.Path) {
		return clientcontract.RPCName(method.HTTPMethod, method.Path)
	}
	return exportedFieldName(toCamelCase(method.OperationID))
}

// strictDistinctMethodSymbol is the Go symbol a synthesized operation takes
// when it shares its strictMethodSymbol with a sibling that keeps it: the
// exported form of its operationId, which keeps every path parameter in path
// order (getX_A_Deploy_B → GetXADeployB). It is the symbol an authored
// operationId gets and the name the TypeScript emitter derives from the same
// id, so the rule adds no third naming scheme. The proto/gRPC bridge has its
// own collision rule (uniqueRPCName), so a renamed operation's Go symbol and
// its RPC name may differ; the operationId stays the identity both carry.
func strictDistinctMethodSymbol(method MethodIR) string {
	operationID := method.OperationID
	if operationID == "" {
		operationID = CanonicalOperationID(method.HTTPMethod, method.Path)
	}
	return exportedFieldName(toCamelCase(operationID))
}

// isSynthesizedOperationID reports whether an operationId is one this framework
// produces mechanically: CanonicalOperationID is what the Go provider publishes,
// buildOperationID is what the reader fills in when a document declares none.
func isSynthesizedOperationID(operationID, httpMethod, path string) bool {
	if operationID == "" {
		return true
	}
	return operationID == CanonicalOperationID(httpMethod, path) ||
		operationID == buildOperationID(httpMethod, path)
}

// bodylessHTTPMethod reports the request methods whose body no first-party
// runtime may send. RFC 9110 leaves a GET/HEAD payload undefined, and every
// intermediary is entitled to drop it.
func bodylessHTTPMethod(httpMethod string) bool {
	switch strings.ToUpper(httpMethod) {
	case "GET", "HEAD":
		return true
	default:
		return false
	}
}

// refuseUnhonorableTransports rejects declared transports that no first-party
// runtime can honor yet. D0.8 keeps wire v1 whole — the proto WebSocket payload
// stays in the contract — and closes the gap at generation instead, so a client
// never compiles against a message codec it does not have.
func refuseUnhonorableTransports(method MethodIR) error {
	for _, transport := range method.Client.Transports {
		if transport.Protocol == clientcontract.TransportWebSocket && transport.Encoding == clientcontract.EncodingProto {
			return errors.Newf(CodeClientGenUnsupportedSemantic,
				"api: operation %s declares a %s transport with %s encoding; the Go client has no protobuf message codec yet",
				method.OperationID, transport.Protocol, transport.Encoding)
		}
	}
	return nil
}

// emitPathParams declares the path parameters twice over: once as the map a
// Connect request message carries them in, and once substituted into the REST
// URL. One expression produces both, so the two projections of a declared
// parameter can never disagree.
func (generator *strictClientGen) emitPathParams(output *strings.Builder, parameters []ParameterIR) error {
	if len(parameters) == 0 {
		return nil
	}
	generator.imports["strings"] = true
	output.WriteString("\tparams := map[string]string{}\n")
	for _, parameter := range parameters {
		field := "in.Path." + exportedFieldName(parameter.Name)
		expression, err := generator.parameterExpression(field, parameter.Schema)
		if err != nil {
			return err
		}
		fmt.Fprintf(output, "\tparams[%q] = %s\n", parameter.Name, expression)
		fmt.Fprintf(output, "\tpath = strings.ReplaceAll(path, %q, url.PathEscape(params[%q]))\n", "{"+parameter.Name+"}", parameter.Name)
	}
	return nil
}

// honorableUnaryTransport reports the unary transports the Go runtime drives.
func honorableUnaryTransport(transport clientcontract.Transport) bool {
	switch transport.Protocol {
	case clientcontract.TransportRESTJSON:
		return transport.Encoding == clientcontract.EncodingJSON
	case clientcontract.TransportConnect:
		return transport.Encoding == clientcontract.EncodingJSON || transport.Encoding == clientcontract.EncodingProto
	default:
		return false
	}
}

// honorableServerStreamTransport reports the server-stream transports the Go
// runtime drives, in the order the runtime dispatcher understands.
func honorableServerStreamTransport(transport clientcontract.Transport) bool {
	switch transport.Protocol {
	case clientcontract.TransportSSE, clientcontract.TransportWebSocket:
		return transport.Encoding == clientcontract.EncodingJSON
	case clientcontract.TransportConnect:
		return transport.Encoding == clientcontract.EncodingJSON || transport.Encoding == clientcontract.EncodingProto
	default:
		return false
	}
}

// selectServerStreamTransport returns the transport whose URL the emitted stream
// method builds, after checking the transport the runtime will dispatch on.
// SSE, WebSocket and Connect all resolve to one call shape, because all three
// drive the same StreamSession behind it.
func (generator *strictClientGen) selectServerStreamTransport(method MethodIR) (clientcontract.Transport, error) {
	var dispatched *clientcontract.Transport
	var addressable *clientcontract.Transport
	for i := range method.Client.Transports {
		candidate := &method.Client.Transports[i]
		if dispatched == nil && honorableServerStreamTransport(*candidate) {
			dispatched = candidate
		}
		if addressable == nil && (candidate.Protocol == clientcontract.TransportSSE || candidate.Protocol == clientcontract.TransportWebSocket) {
			addressable = candidate
		}
	}
	if dispatched == nil {
		return clientcontract.Transport{}, errors.Newf(CodeClientGenConfig,
			"api: server stream operation %s declares no transport the Go client can drive", method.OperationID)
	}
	projection := *dispatched
	if addressable != nil {
		projection = *addressable
	}
	if err := generator.refuseUnprojectableConnect(method, *dispatched); err != nil {
		return clientcontract.Transport{}, err
	}
	return projection, nil
}

// selectUnaryTransport returns the transport whose URL the emitted REST
// projection is built from, after checking the transport the runtime will
// actually dispatch on — the first declared one this runtime can drive.
//
// The two differ only for a provider that declares Connect ahead of REST: the
// emitted method still needs a path to build, and there is none but the REST
// one. When no REST transport is declared at all, the Connect method identity is
// the path, and the dispatcher replaces it with the same value.
func (generator *strictClientGen) selectUnaryTransport(method MethodIR) (clientcontract.Transport, error) {
	var dispatched *clientcontract.Transport
	var rest *clientcontract.Transport
	for i := range method.Client.Transports {
		candidate := &method.Client.Transports[i]
		if dispatched == nil && honorableUnaryTransport(*candidate) {
			dispatched = candidate
		}
		if rest == nil && candidate.Protocol == clientcontract.TransportRESTJSON && candidate.Encoding == clientcontract.EncodingJSON {
			rest = candidate
		}
	}
	if dispatched == nil {
		return clientcontract.Transport{}, errors.Newf(CodeClientGenConfig,
			"api: unary operation %s declares no transport the Go client can drive", method.OperationID)
	}
	projection := *dispatched
	if rest != nil {
		projection = *rest
	}
	if err := generator.refuseUnprojectableConnect(method, *dispatched); err != nil {
		return clientcontract.Transport{}, err
	}
	return projection, nil
}

// refuseUnprojectableConnect rejects an operation the Connect request envelope
// cannot carry, when Connect is the transport the runtime will dispatch on.
//
// The envelope names one value per query parameter and carries the request body
// as an object, because that is the shape the bridged endpoint pipeline reads.
// A declaration outside that shape has no Connect projection, and emitting one
// anyway would produce a client whose calls silently lose a value. The check is
// scoped to the dispatched transport on purpose: a contract that declares REST
// first never reaches Connect, and refusing it would reject a call that works.
func (generator *strictClientGen) refuseUnprojectableConnect(method MethodIR, dispatched clientcontract.Transport) error {
	if dispatched.Protocol != clientcontract.TransportConnect {
		return nil
	}
	if method.Client.Stream == clientcontract.StreamUnary && len(method.Successes) > 1 {
		// Connect answers every successful call with HTTP 200, so the status
		// that tells the variants apart never reaches the caller. The
		// TypeScript emitter refuses the same declaration.
		return errors.Newf(CodeClientGenUnsupportedSemantic,
			"api: operation %s dispatches on %s and declares %d success statuses; a Connect response carries one success status",
			method.OperationID, dispatched.Protocol, len(method.Successes))
	}
	for _, parameter := range method.Parameters {
		if parameter.Location == "query" && parameter.Schema.Type == "array" {
			return errors.Newf(CodeClientGenUnsupportedSemantic,
				"api: operation %s dispatches on %s and declares repeated query parameter %s; a Connect request envelope carries one value per parameter",
				method.OperationID, dispatched.Protocol, parameter.Name)
		}
	}
	for _, schema := range connectObservableSchemas(method) {
		if generator.carriesOpaqueJSON(schema, map[string]bool{}) {
			return errors.Newf(CodeClientGenUnsupportedSemantic,
				"api: operation %s dispatches on %s and declares an opaque JSON value; protobuf has no lossless form for it, so the operation must travel on REST",
				method.OperationID, dispatched.Protocol)
		}
	}
	if dispatched.Encoding == clientcontract.EncodingProto {
		// proto3 has one absence. The descriptor's `optional` flag covers a
		// member the schema lets be absent *or* null, so a declared null and a
		// declared absence are the same state on this encoding — and a Go
		// caller reading Optional.IsNull() can tell them apart. Refusing here
		// is the alternative to letting the two encodings of one operation
		// disagree about a value the caller can observe.
		for _, schema := range connectObservableSchemas(method) {
			if generator.carriesNullable(schema, map[string]bool{}) {
				return errors.Newf(CodeClientGenUnsupportedSemantic,
					"api: operation %s dispatches on %s over %s and declares a nullable member; proto3 carries no null, so absent and null would be one value here",
					method.OperationID, dispatched.Protocol, dispatched.Encoding)
			}
		}
	}
	if method.Request == nil {
		return nil
	}
	for i := range method.Request.Content {
		content := method.Request.Content[i]
		if content.MediaType != "application/json" || content.Schema == nil {
			continue
		}
		if content.Schema.Ref != "" || content.Schema.Type == "object" || len(content.Schema.OneOf) > 0 {
			continue
		}
		return errors.Newf(CodeClientGenUnsupportedSemantic,
			"api: operation %s dispatches on %s and declares a non-object request body; a Connect request envelope carries the body as an object",
			method.OperationID, dispatched.Protocol)
	}
	return nil
}

// carriesNullable reports whether a declared shape lets any member be null, at
// any depth. schemaNullable answers the question for one schema; the proto
// refusal needs the whole reachable shape, because a null anywhere inside a
// message is a null proto3 cannot carry.
func (generator *strictClientGen) carriesNullable(schema clientcontract.Schema, visiting map[string]bool) bool {
	if schema.Nullable != nil && *schema.Nullable {
		return true
	}
	if schema.Ref != "" {
		name := strings.TrimPrefix(schema.Ref, "#/components/schemas/")
		if visiting[name] {
			return false
		}
		resolved, declared := generator.spec.Schemas[name]
		if !declared {
			return false
		}
		visiting[name] = true
		defer delete(visiting, name)
		return generator.carriesNullable(resolved, visiting)
	}
	for _, property := range schema.Properties {
		if generator.carriesNullable(property, visiting) {
			return true
		}
	}
	for _, member := range schema.OneOf {
		if generator.carriesNullable(member, visiting) {
			return true
		}
	}
	if schema.Items != nil && generator.carriesNullable(*schema.Items, visiting) {
		return true
	}
	if schema.AdditionalProperties != nil && schema.AdditionalProperties.Schema != nil {
		return generator.carriesNullable(*schema.AdditionalProperties.Schema, visiting)
	}
	return false
}

// opaqueJSON reports whether a schema, through its references, declares an
// opaque JSON value.
func (generator *strictClientGen) opaqueJSON(schema clientcontract.Schema) bool {
	return generator.resolveReference(schema).IsOpaqueJSON()
}

// resolveReference follows local component references to the schema they
// name. A missing or cyclic reference resolves to the last schema reached; the
// reader has already refused both.
func (generator *strictClientGen) resolveReference(schema clientcontract.Schema) clientcontract.Schema {
	seen := map[string]bool{}
	for schema.Ref != "" {
		name := strings.TrimPrefix(schema.Ref, "#/components/schemas/")
		resolved, declared := generator.spec.Schemas[name]
		if !declared || seen[name] {
			return schema
		}
		seen[name] = true
		schema = resolved
	}
	return schema
}

// carriesOpaqueJSON reports whether any member of a declared shape, at any
// depth, is an opaque JSON value or a free-form object.
func (generator *strictClientGen) carriesOpaqueJSON(schema clientcontract.Schema, visiting map[string]bool) bool {
	if schema.IsOpaqueJSON() || schema.IsFreeFormObject() {
		return true
	}
	if schema.Ref != "" {
		name := strings.TrimPrefix(schema.Ref, "#/components/schemas/")
		if visiting[name] {
			return false
		}
		resolved, declared := generator.spec.Schemas[name]
		if !declared {
			return false
		}
		visiting[name] = true
		defer delete(visiting, name)
		return generator.carriesOpaqueJSON(resolved, visiting)
	}
	for _, property := range schema.Properties {
		if generator.carriesOpaqueJSON(property, visiting) {
			return true
		}
	}
	for _, member := range schema.OneOf {
		if generator.carriesOpaqueJSON(member, visiting) {
			return true
		}
	}
	if schema.Items != nil && generator.carriesOpaqueJSON(*schema.Items, visiting) {
		return true
	}
	return schema.AdditionalProperties != nil && schema.AdditionalProperties.Schema != nil &&
		generator.carriesOpaqueJSON(*schema.AdditionalProperties.Schema, visiting)
}

// connectObservableSchemas lists every schema a caller sees the values of: the
// request body, the success bodies, and a stream's message shape.
func connectObservableSchemas(method MethodIR) []clientcontract.Schema {
	var schemas []clientcontract.Schema
	for _, parameter := range method.Parameters {
		schemas = append(schemas, parameter.Schema)
	}
	if method.Request != nil {
		for i := range method.Request.Content {
			if schema := method.Request.Content[i].Schema; schema != nil {
				schemas = append(schemas, *schema)
			}
		}
	}
	for i := range method.Successes {
		for _, content := range method.Successes[i].Content {
			if content.Schema != nil {
				schemas = append(schemas, *content.Schema)
			}
		}
	}
	if method.Client != nil && method.Client.Messages != nil && method.Client.Messages.Output != nil {
		schemas = append(schemas, *method.Client.Messages.Output)
	}
	return schemas
}
