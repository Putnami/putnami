func collect(t *testing.T, dir string, now time.Time) payload.Result {
	t.Helper()
	result, err := payload.Collect(context.Background(), payload.Options{
		Dir: dir, CollectorVersion: "0.1.0", Now: now, Salt: bytes.Repeat([]byte{7}, 32),
	})
	if err != nil {
		t.Fatalf("collect: %v", err)
	}
	return result
}

func find(t *testing.T, p contract.Payload, id, area string) contract.Marker {
	t.Helper()
	for _, marker := range p.Markers {
		if marker.ID == id && marker.Area == area {
			return marker
		}
	}
	t.Fatalf("no marker %s for area %q", id, area)
	return contract.Marker{}
}

func value(t *testing.T, marker contract.Marker) float64 {
	t.Helper()
	if marker.Value == nil {
		t.Fatalf("%s %s has no value", marker.ID, marker.Area)
	}
	return *marker.Value
}

func TestCollectValidatesAgainstSchemaV1(t *testing.T) {
	a := newAcme(t)
	result := collect(t, a.repo.Dir, a.now)
	encoded, err := json.Marshal(result.Payload)
	if err != nil {
		t.Fatal(err)
	}
	var instance any
	if err := json.Unmarshal(encoded, &instance); err != nil {
		t.Fatal(err)
	}
	compiler := jsonschema.NewCompiler()
	compiler.Draft = jsonschema.Draft2020
	compiler.AssertFormat = true
	url := schema.IDBase + schema.PayloadFile
	if err := compiler.AddResource(url, bytes.NewReader(schema.PayloadV1)); err != nil {
		t.Fatal(err)
	}
	compiled, err := compiler.Compile(url)
	if err != nil {
		t.Fatal(err)
	}
	if err := compiled.Validate(instance); err != nil {
		t.Fatalf("payload does not validate: %#v\n%s", err, encoded)
	}
	if result.Elapsed <= 0 {
		t.Fatal("elapsed time is not reported")
	}
}

