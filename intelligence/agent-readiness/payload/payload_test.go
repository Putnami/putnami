func TestCollectDescribesTheRepository(t *testing.T) {
	a := newAcme(t)
	p := collect(t, a.repo.Dir, a.now).Payload
	if p.Meta.MethodVersion != contract.MethodVersion || p.Meta.CollectorVersion != "0.1.0" || len(p.Meta.HeadCommit) != 40 {
		t.Fatalf("meta = %+v", p.Meta)
	}
	if p.AgentProbe != nil {
		t.Fatal("agentProbe must be null in method 0.1")
	}
	names := map[string]contract.Area{}
	for _, area := range p.Areas {
		names[area.Name] = area
	}
	for name, path := range map[string]string{"root": ".", "checkout": "packages/checkout", "ui": "packages/ui", "billing": "services/billing"} {
		if names[name].Path != path {
			t.Fatalf("area %s = %+v, want path %s (areas %+v)", name, names[name], path, p.Areas)
		}
	}
	if names["checkout"].Source != contract.AreaFromManifest || names["root"].Source != contract.AreaInferred {
		t.Fatalf("area sources: %+v", p.Areas)
	}
	checkout := names["checkout"]
	// cart.ts, cart.test.ts, index.ts, package.json and README.md; gen.ts is generated.
	if checkout.Files != 5 || checkout.Language != "TypeScript" || checkout.Commits90d != 4 || len(checkout.Authors90d) != 2 {
		t.Fatalf("checkout = %+v", checkout)
	}
	if names["ui"].Files != 2 {
		t.Fatalf("ui counts its dist bundle: %+v", names["ui"])
	}
	inv := p.Inventory
	if inv.Commits90d != 8 || inv.ActiveContributors90d != 3 || inv.CommitsTotal != 9 || inv.RepoAgeDays != 400 {
		t.Fatalf("history counts = %+v", inv)
	}
	want := map[string][]contract.Tool{
		"packageManagers": {{Name: "Go modules", Version: "1.23.4"}, {Name: "pnpm", Version: "9.12.1"}},
		"monorepoTools":   {{Name: "Go workspaces"}, {Name: "Turborepo", Version: "2.1.3"}, {Name: "pnpm workspaces"}},
		"frameworks":      {{Name: "React", Version: "19.0.0"}, {Name: "chi", Version: "5.1.0"}},
		"testFrameworks":  {{Name: "Vitest", Version: "2.1.1"}, {Name: "go test"}},
		"databases":       {{Name: "PostgreSQL", Version: "16"}},
		"containers":      {{Name: "Docker Compose"}},
		"ciProviders":     {{Name: "GitHub Actions"}},
	}
	got := map[string][]contract.Tool{
		"packageManagers": inv.PackageManagers, "monorepoTools": inv.MonorepoTools, "frameworks": inv.Frameworks,
		"testFrameworks": inv.TestFrameworks, "databases": inv.Databases, "containers": inv.Containers, "ciProviders": inv.CIProviders,
	}
	for field, tools := range want {
		gotJSON, _ := json.Marshal(got[field])
		wantJSON, _ := json.Marshal(tools)
		if !bytes.Equal(gotJSON, wantJSON) {
			t.Fatalf("%s = %s, want %s", field, gotJSON, wantJSON)
		}
	}
	if len(inv.InstructionFiles) != 1 || inv.InstructionFiles[0].Path != "AGENTS.md" || inv.InstructionFiles[0].AgeDays != 20 {
		t.Fatalf("instruction files = %+v", inv.InstructionFiles)
	}
}

func TestCollectReadsEveryMarker(t *testing.T) {
	a := newAcme(t)
	p := collect(t, a.repo.Dir, a.now).Payload
	for i, definition := range contract.MarkerCatalog {
		if p.Markers[i].ID != definition.ID || p.Markers[i].Area != "" {
			t.Fatalf("marker %d = %s/%s, want repository-wide %s", i, p.Markers[i].ID, p.Markers[i].Area, definition.ID)
		}
	}
	for _, tc := range []struct {
		id, area string
		state    contract.MarkerState
	}{
		{"understand.instructions", "", contract.MarkerEnforced},
		{"understand.commands", "", contract.MarkerEnforced},
		{"understand.area-docs", "", contract.MarkerExists},
		{"understand.area-docs", "ui", contract.MarkerAbsent},
		{"bound.declared-areas", "", contract.MarkerEnforced},
		{"bound.boundary-rules", "", contract.MarkerEnforced},
		// 0.25 is under the bar, but the CI runs every test rather than the
		// areas a change affects.
		{"bound.cross-area-changes", "checkout", contract.MarkerExists},
		{"verify.tests", "", contract.MarkerEnforced},
		{"verify.tests", "ui", contract.MarkerAbsent},
		{"verify.static-checks", "", contract.MarkerEnforced},
		{"verify.reliable-signal", "", contract.MarkerExists},
		{"verify.reliable-signal", "checkout", contract.MarkerEnforced},
		{"verify.pinned-toolchain", "", contract.MarkerEnforced},
		{"recover.ownership", "", contract.MarkerExists},
		{"recover.ownership", "checkout", contract.MarkerEnforced},
		{"recover.small-changes", "", contract.MarkerExists},
	} {
		if got := find(t, p, tc.id, tc.area); got.State != tc.state {
			t.Errorf("%s/%s state = %s, want %s (%+v)", tc.id, tc.area, got.State, tc.state, got)
		}
	}
	if got := value(t, find(t, p, "understand.instructions", "")); got != 17 {
		t.Errorf("instructions lag = %v, want 17 days", got)
	}
	if got := value(t, find(t, p, "verify.pinned-toolchain", "")); got != 400 {
		t.Errorf("pinned-toolchain = %v, want 400 days", got)
	}
	if got := value(t, find(t, p, "recover.ownership", "checkout")); got != 2 {
		t.Errorf("checkout authors = %v, want 2", got)
	}
	if got := value(t, find(t, p, "verify.tests", "")); got != 0.2857 {
		t.Errorf("verify.tests = %v, want 0.2857", got)
	}
	if got := value(t, find(t, p, "bound.cross-area-changes", "checkout")); got != 0.25 {
		t.Errorf("checkout cross-area share = %v, want 0.25", got)
	}
}

// TestEvidenceCommandsReproduceTheMarkers runs the evidence commands from a
// shell in the repository, the way a reader would, and recomputes the marker
// from their output.
func TestEvidenceCommandsReproduceTheMarkers(t *testing.T) {
	a := newAcme(t)
	p := collect(t, a.repo.Dir, a.now).Payload

	t.Run("understand.instructions", func(t *testing.T) {
		m := find(t, p, "understand.instructions", "")
		changed, err := time.Parse("2006-01-02", strings.TrimSpace(a.repo.Shell(m.Evidence.Command)))
		if err != nil {
			t.Fatal(err)
		}
		if want := a.agentsAt.Format("2006-01-02"); changed.Format("2006-01-02") != want {
			t.Fatalf("%s printed %s, want %s", m.Evidence.Command, changed, want)
		}
		lag := math.Floor(a.lastCode.Sub(a.agentsAt).Hours() / 24)
		if value(t, m) != lag {
			t.Fatalf("value %v, the evidence says %v", value(t, m), lag)
		}
	})

	t.Run("recover.small-changes", func(t *testing.T) {
		m := find(t, p, "recover.small-changes", "")
		var lines []int
		for _, line := range strings.Split(a.repo.Shell(m.Evidence.Command), "\n") {
			if strings.Contains(line, "changed") {
				lines = append(lines, shortstat(line))
			}
		}
		if len(lines) != 8 {
			t.Fatalf("%s printed %d changes, want 8", m.Evidence.Command, len(lines))
		}
		if got := median(lines); value(t, m) != got {
			t.Fatalf("value %v, the evidence says %v", value(t, m), got)
		}
	})

	t.Run("bound.cross-area-changes", func(t *testing.T) {
		m := find(t, p, "bound.cross-area-changes", "checkout")
		commits, cross := 0, 0
		counted := true
		for _, line := range strings.Split(a.repo.Shell(m.Evidence.Command), "\n") {
			switch {
			case commitID.MatchString(line):
				commits++
				counted = false
			case !counted && strings.HasPrefix(line, "packages/ui/"), !counted && strings.HasPrefix(line, "services/"):
				cross++
				counted = true
			}
		}
		if commits != 4 {
			t.Fatalf("%s listed %d commits, want 4", m.Evidence.Command, commits)
		}
		if want := math.Round(float64(cross)/float64(commits)*10000) / 10000; value(t, m) != want {
			t.Fatalf("value %v, the evidence says %v", value(t, m), want)
		}
	})

	t.Run("verify.reliable-signal", func(t *testing.T) {
		m := find(t, p, "verify.reliable-signal", "")
		printed := a.repo.Shell(m.Evidence.Command)
		// The fixture guards none of its skips, so every printed match counts.
		if added := addedSignals(printed); added == 0 || value(t, m) != float64(added) || len(m.Evidence.Sample) != 1 {
			t.Fatalf("value %v, sample %v, the evidence printed %q", value(t, m), m.Evidence.Sample, printed)
		}
	})

	t.Run("recover.ownership", func(t *testing.T) {
		m := find(t, p, "recover.ownership", "")
		if got := strings.TrimSpace(a.repo.Shell(m.Evidence.Command)); got != m.Evidence.Sample[0] {
			t.Fatalf("%s printed %q, sample says %v", m.Evidence.Command, got, m.Evidence.Sample)
		}
	})
}

var commitID = regexp.MustCompile(`^[0-9a-f]{40}$`)

// addedSignals counts the added lines the reliable-signal evidence printed
// that match the signal pattern. The command prints each with the lines
// around it, so a reader can apply the guard rule by hand.
func addedSignals(printed string) int {
	pattern := regexp.MustCompile(`^\+.*(` + markers.SignalPattern + `)`)
	count := 0
	for _, line := range strings.Split(printed, "\n") {
		if pattern.MatchString(line) {
			count++
		}
	}
	return count
}

func shortstat(line string) int {
	total := 0
	fields := strings.Fields(strings.ReplaceAll(line, ",", ""))
	for i := 1; i < len(fields); i++ {
		if strings.HasPrefix(fields[i], "insertion") || strings.HasPrefix(fields[i], "deletion") {
			n, _ := strconv.Atoi(fields[i-1])
			total += n
		}
	}
	return total
}

func median(values []int) float64 {
	sorted := append([]int{}, values...)
	sort.Ints(sorted)
	middle := len(sorted) / 2
	if len(sorted)%2 == 1 {
		return float64(sorted[middle])
	}
	return float64(sorted[middle-1]+sorted[middle]) / 2
}

