// TestCollectCountsAgentCommits pins method 0.3's agent outcome counts on a
// repository born 30 days ago: one commit credits Claude in a trailer and a
// later commit reverts it. The ownership value counts the agent beside the
// two people, and recover.small-changes, whose every change landed through
// a pull request, has held since the repository was born.
func TestCollectCountsAgentCommits(t *testing.T) {
	now := time.Now().UTC().Truncate(time.Second)
	r := gittest.New(t)
	r.Write("go.mod", "module acme\n\ngo 1.23.4\n")
	r.Write("main.go", "package main\n")
	r.Commit("chore: bootstrap (#1)", authors[0], day(now, -30))
	r.Write("main.go", "package main\n\nfunc main() {}\n")
	agent := r.Commit("feat: main (#2)\n\nCo-authored-by: Claude <noreply@anthropic.com>", authors[0], day(now, -20))
	r.Write("main.go", "package main\n")
	r.Commit("Revert \"feat: main (#2)\" (#3)\n\nThis reverts commit "+agent+".", authors[0], day(now, -10))
	r.Write("util.go", "package main\n")
	r.Commit("feat: util (#4)", authors[1], day(now, -5))

	p := collect(t, r.Dir, now).Payload
	inv := p.Inventory
	if inv.AgentCommits90d == nil || *inv.AgentCommits90d != 1 || inv.AgentCommitsReverted90d == nil || *inv.AgentCommitsReverted90d != 1 {
		t.Fatalf("agent counts = %v, %v, want 1 agent commit, reverted", inv.AgentCommits90d, inv.AgentCommitsReverted90d)
	}
	if inv.ActiveContributors90d != 2 {
		t.Fatalf("active contributors = %d, want the two people", inv.ActiveContributors90d)
	}
	if m := find(t, p, "recover.ownership", ""); value(t, m) != 3 {
		t.Fatalf("ownership = %+v, want two people and one agent", m)
	}
	if m := find(t, p, "recover.small-changes", ""); m.State != contract.MarkerEnforced || m.EnforcedDays == nil || *m.EnforcedDays != 30 {
		t.Fatalf("small changes = %+v, want enforced since the repository was born", m)
	}
	encoded, _ := json.Marshal(p)
	if strings.Contains(string(encoded), "anthropic") {
		t.Fatal("payload carries the agent's address")
	}
}
