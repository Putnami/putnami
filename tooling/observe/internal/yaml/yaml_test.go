func TestAPubspecReads(t *testing.T) {
	doc, err := Parse([]byte(`# The mobile app.
name: mobile
description: >-
  The shop's mobile app,
  for iOS and Android.
publish_to: 'none' # never published
version: 1.0.0+1

environment:
  sdk: ^3.6.0
  flutter: ">=3.27.0"

resolution: workspace

dependencies:
  flutter:
    sdk: flutter
  pricing:
    path: ../../packages/pricing
  ui: {path: "../../packages/ui"}
  http: ^1.2.2
  intl:
  shared_preferences: &prefs
    hosted: https://pub.dev
    version: ^2.3.0

dev_dependencies:
  flutter_test: {sdk: flutter}

flutter:
  uses-material-design: true
  assets:
  - assets/logo.png
  - "assets/fonts/"
`))
	if err != nil {
		t.Fatal(err)
	}
	want := Map{
		"name":        "mobile",
		"description": "The shop's mobile app, for iOS and Android.",
		"publish_to":  "none",
		"version":     "1.0.0+1",
		"environment": Map{"sdk": "^3.6.0", "flutter": ">=3.27.0"},
		"resolution":  "workspace",
		"dependencies": Map{
			"flutter":            Map{"sdk": "flutter"},
			"pricing":            Map{"path": "../../packages/pricing"},
			"ui":                 Map{"path": "../../packages/ui"},
			"http":               "^1.2.2",
			"intl":               nil,
			"shared_preferences": Map{"hosted": "https://pub.dev", "version": "^2.3.0"},
		},
		"dev_dependencies": Map{"flutter_test": Map{"sdk": "flutter"}},
		"flutter":          Map{"uses-material-design": "true", "assets": []any{"assets/logo.png", "assets/fonts/"}},
	}
	if !reflect.DeepEqual(doc, want) {
		t.Errorf("doc = %#v\nwant %#v", doc, want)
	}
	if got := String(doc, "dependencies", "pricing", "path"); got != "../../packages/pricing" {
		t.Errorf("String = %q", got)
	}
}

func TestAPubspecLockReads(t *testing.T) {
	doc, err := Parse([]byte(`# Generated by pub
# See https://dart.dev/tools/pub/glossary#lockfile
packages:
  async:
    dependency: transitive
    description:
      name: async
      sha256: "758e6d74e971c3e5aceb4110bfd6698efc7f501675bcfe0c775459a8140750eb"
      url: "https://pub.dev"
    source: hosted
    version: "2.13.0"
  pricing:
    dependency: "direct main"
    description:
      path: "../../packages/pricing"
      relative: true
    source: path
    version: "1.0.0"
sdks:
  dart: ">=3.6.0 <4.0.0"
`))
	if err != nil {
		t.Fatal(err)
	}
	if got := String(doc, "packages", "async", "version"); got != "2.13.0" {
		t.Errorf("async version %q", got)
	}
	if got := String(doc, "packages", "async", "description", "url"); got != "https://pub.dev" {
		t.Errorf("async url %q", got)
	}
	if got := String(doc, "packages", "pricing", "dependency"); got != "direct main" {
		t.Errorf("pricing dependency %q", got)
	}
}

func TestSequencesOfMappingsAndNestedSequencesRead(t *testing.T) {
	doc, err := Parse([]byte(`---
packages:
  - apps/*
  -   packages/**
ignore: ["packages/**/example", 'tools']
scripts:
  - name: test
    run: |
      melos exec -- flutter test
      echo done
  -
    name: lint
  - - a
    - b
  - []
  - {}
...
ignored: after the document end
`))
	if err != nil {
		t.Fatal(err)
	}
	want := Map{
		"packages": []any{"apps/*", "packages/**"},
		"ignore":   []any{"packages/**/example", "tools"},
		"scripts": []any{
			Map{"name": "test", "run": "melos exec -- flutter test\necho done\n"},
			Map{"name": "lint"},
			[]any{"a", "b"},
			[]any{},
			Map{},
		},
	}
	if !reflect.DeepEqual(doc, want) {
		t.Errorf("doc = %#v\nwant %#v", doc, want)
	}
	if list, ok := Strings(Get(doc, "packages")); !ok || !reflect.DeepEqual(list, []string{"apps/*", "packages/**"}) {
		t.Errorf("Strings = %v, %v", list, ok)
	}
	if _, ok := Strings(Get(doc, "scripts")); ok {
		t.Error("a sequence of mappings reads as strings")
	}
}

func TestScalarsRead(t *testing.T) {
	doc, err := Parse([]byte(`plain: a b # c
hash: a#b
single: 'it''s # here'
double: "tab\there \u00e9 \x41 \"q\""
null1: ~
null2: null
tagged: !!str 1.0
literal: |-
  one
    two

  three
keep: |+
  x

folded: >
  a
  b

  c
multi: a long
  plain value
"quoted key": v
url: https://pub.dev
flow: [a, "b, c", {k: v, e: }]
`))
	if err != nil {
		t.Fatal(err)
	}
	want := Map{
		"plain":      "a b",
		"hash":       "a#b",
		"single":     "it's # here",
		"double":     "tab\there \u00e9 A \"q\"",
		"null1":      nil,
		"null2":      nil,
		"tagged":     "1.0",
		"literal":    "one\n  two\n\nthree",
		"keep":       "x\n\n",
		"folded":     "a b\nc\n",
		"multi":      "a long plain value",
		"quoted key": "v",
		"url":        "https://pub.dev",
		"flow":       []any{"a", "b, c", Map{"k": "v", "e": nil}},
	}
	if !reflect.DeepEqual(doc, want) {
		for k, v := range want {
			if got := doc.(Map)[k]; !reflect.DeepEqual(got, v) {
				t.Errorf("%s = %#v, want %#v", k, got, v)
			}
		}
	}
}

func TestEmptyDocumentsAreNil(t *testing.T) {
	for _, text := range []string{"", "# only a comment\n", "---\n", "\n\n"} {
		doc, err := Parse([]byte(text))
		if err != nil || doc != nil {
			t.Errorf("Parse(%q) = %v, %v", text, doc, err)
		}
	}
}

func TestUnsupportedOrMalformedDocumentsAreErrorsThatNameTheirLine(t *testing.T) {
	for text, want := range map[string]string{
		"a: &x 1\nb: *x\n":       "line 2: an alias is not supported",
		"a:\n\tb: 1\n":           "line 2: a tab indents the line",
		"? a\n: b\n":             "line 1: a complex mapping key is not supported",
		"a: 1\n  b: 2\n":         "line 2:",
		"a: [1, 2\n":             "line 1: an unterminated flow collection",
		"a: \"open\n":            "line 1: an unterminated double-quoted scalar",
		"a:\n  - x\n  y: 1\n":    "line 3:",
		"a: 1\nplain text\n":     "line 2: a mapping key is expected",
		"a: \"\\q\"\n":           "line 1: an unknown escape",
		"a: [1] x\n":             "line 1: unexpected text after a flow collection",
		"\xff: x\n":              "not UTF-8",
		"a: 1\n- b\n":            "line 2: a sequence item where a mapping key is expected",
		"a: |x\n  b\n":           "line 1: an invalid block scalar header",
		"a: |\n    b\n  c\n":     "line 3: a block scalar line is less indented",
		"--- a\n":                "line 1: content on the document start line",
		"- a\nb: 1\n":            "line 2: unexpected content",
		"a: 1\n- b\n  c: 2\n":    "line 2:",
		"a: {b: [1, 2}, c: 3}\n": "line 1:",
		"a: {b: \"x}\n":          "line 1:",
		"a:\n  - 1\n - 2\n":      "line 3:",
		"a:\n  b: 1\n c: 2\n":    "line 3:",
		"a:\n  - |\n    x\n y\n": "line 4:",
	} {
		_, err := Parse([]byte(text))
		if err == nil || !strings.Contains(err.Error(), want) {
			t.Errorf("Parse(%q) error = %v, want %q", text, err, want)
		}
	}
}

func TestGetAndStringReadThroughMappingsOnly(t *testing.T) {
	doc := Map{"a": Map{"b": "c"}, "l": []any{"x"}}
	if Get(doc, "a", "b", "c") != nil || Get(doc, "l", "x") != nil || Get(doc, "missing") != nil {
		t.Error("Get reached through a non-mapping")
	}
	if String(doc, "a") != "" || String(doc, "a", "b") != "c" {
		t.Error("String")
	}
	if list, ok := Strings(nil); !ok || list != nil {
		t.Error("Strings(nil)")
	}
	if _, ok := Strings("x"); ok {
		t.Error("Strings of a scalar")
	}
}
