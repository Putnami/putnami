package attribution

import (
	"slices"
	"testing"
)

func TestKindRecognizesTheThreeForms(t *testing.T) {
	cases := []struct {
		line string
		kind string
	}{
		{"_Generated by [Claude Code](https://claude.ai/code/session_01abc)_", GeneratedFooter},
		{"🤖 Generated with [Claude Code](https://claude.com/claude-code)", GeneratedFooter},
		{"Generated by Codex", GeneratedFooter},
		{"Co-Authored-By: Claude <noreply@anthropic.com>", CoAuthorTrailer},
		{"co-authored-by: Bot <bot@openai.com>", CoAuthorTrailer},
		{"Co-authored-by: GPT-5 Assistant <x@example.com>", CoAuthorTrailer},
		{"See https://claude.ai/code/session_01XYZ for the run", SessionLink},
		{"https://chatgpt.com/codex/tasks/task_e_1", SessionLink},
		{"Claude-Session: https://example.com/s/1", SessionLink},
	}
	for _, c := range cases {
		kind, ok := Kind(c.line)
		if !ok || kind != c.kind {
			t.Errorf("Kind(%q) = %q, %v; want %q", c.line, kind, ok, c.kind)
		}
	}
}

func TestKindLeavesPathsAndHumansAlone(t *testing.T) {
	for _, line := range []string{
		"The skill moves under .claude/skills and .agents/skills.",
		"Co-Authored-By: Ada Lovelace <ada@example.com>",
		"Generated by the release script",
		"The cursor moves to the next line.",
		"",
	} {
		if kind, ok := Kind(line); ok {
			t.Errorf("Kind(%q) = %q; want none", line, kind)
		}
	}
	if Names("feat: move skills under .claude/\n\nA plain body.") {
		t.Error("Names reported a signature in a plain text")
	}
}

func TestFindNumbersLinesAndReadsCRLF(t *testing.T) {
	text := "feat: x\r\n\r\nBody.\r\n\r\nCo-Authored-By: Claude <noreply@anthropic.com>\r\n"
	got := Find(text)
	want := []Line{{Line: 5, Kind: CoAuthorTrailer, Text: "Co-Authored-By: Claude <noreply@anthropic.com>"}}
	if !slices.Equal(got, want) {
		t.Fatalf("Find = %+v; want %+v", got, want)
	}
	if !Names(text) {
		t.Fatal("Names missed the trailer")
	}
}

func TestStripRemovesSignaturesAndTheBlankLinesTheyLeave(t *testing.T) {
	body := "The change does this.\n\nAnd that.\n\n_Generated by [Claude Code](https://claude.ai/code/session_01abc)_\n\nclaude-session: https://claude.ai/code/session_01abc\n"
	got, removed := Strip(body)
	if want := "The change does this.\n\nAnd that."; got != want {
		t.Fatalf("Strip = %q; want %q", got, want)
	}
	if len(removed) != 2 || removed[0].Line != 5 || removed[0].Kind != GeneratedFooter || removed[1].Line != 7 || removed[1].Kind != SessionLink {
		t.Fatalf("removed = %+v", removed)
	}
}

func TestStripInTheMiddleKeepsOneParagraphBreak(t *testing.T) {
	cases := map[string]string{
		"a\n\nGenerated by Codex\n\nb": "a\n\nb",
		"a\nGenerated by Codex\n\nb":   "a\n\nb",
		"Generated by Codex\n\nb":      "b",
		"Generated by Codex":           "",
	}
	for in, want := range cases {
		if got, _ := Strip(in); got != want {
			t.Errorf("Strip(%q) = %q; want %q", in, got, want)
		}
	}
}

func TestStripLeavesASignatureFreeTextUnchanged(t *testing.T) {
	text := "a\r\n\r\n\r\nb\r\n\r\n"
	got, removed := Strip(text)
	if got != text || removed != nil {
		t.Fatalf("Strip = %q, %+v; want the text unchanged", got, removed)
	}
}
