package sdd

import (
	"strings"
	"testing"

	protocolcli "go.putnami.dev/protocol/cli"
	"go.putnami.dev/protocol/features/spectest"
)

const agentAttributionRequirement = "squash-names-no-agent"

// forbid is the options.sdd block of a workspace that forbids agent
// attribution.
var forbid = map[string]any{AgentAttributionOption: AgentAttributionForbid}

// Each form an agent's signature takes fails the step, which names the line,
// its number and its form.
func TestAgentAttributionFailsEachSignatureNamingTheLine(t *testing.T) {
	spectest.Proves(t, breakingMarkerFeature, agentAttributionRequirement, "a-signature-fails-naming-the-line")
	for kind, line := range map[string]string{
		"generated-footer":  "_Generated by [Claude Code](https://claude.ai/code)_",
		"co-author-trailer": "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
		"session-link":      "Claude-Session: https://claude.ai/code/session_01KQXQrTtCUmiYBX78aBHq1E",
	} {
		message := "fix(cli): stop the leak\n\nThe scheduler releases the lock.\n\n" + line + "\n"
		report, err := BuildAgentAttributionResult(message, forbid)
		if err == nil {
			t.Errorf("%s: the step passed a message that names an agent", kind)
			continue
		}
		if code := protocolcli.ExitCodeForError(err); code != protocolcli.ExitUsage {
			t.Errorf("%s: exit code = %d, want %d, the code of every validate-workspace finding", kind, code, protocolcli.ExitUsage)
		}
		if want := "line 5 (" + kind + "): " + line; !strings.Contains(err.Error(), want) {
			t.Errorf("%s: error = %q, want it to name %q", kind, err.Error(), want)
		}
		if len(report.Lines) != 1 || report.Lines[0].Kind != kind || report.Lines[0].Line != 5 {
			t.Errorf("%s: lines = %+v, want line 5 of kind %s", kind, report.Lines, kind)
		}
		if len(report.Diagnostics) != 1 || report.Diagnostics[0].Code != ErrorCodeAgentAttribution {
			t.Errorf("%s: diagnostics = %+v, want one %s", kind, report.Diagnostics, ErrorCodeAgentAttribution)
		}
	}
}

// The other spellings of the same signatures fail too: another markup, another
// agent, another vendor address, a session link inside prose.
func TestAgentAttributionFailsOtherSpellings(t *testing.T) {
	spectest.Proves(t, breakingMarkerFeature, agentAttributionRequirement, "a-signature-fails-naming-the-line")
	for _, line := range []string{
		"\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)",
		"Generated by Codex",
		"*generated with `copilot`*",
		"co-authored-by: GPT-6 Astra <noreply@openai.com>",
		"Co-authored-by: Helper Bot <bot@anthropic.com>",
		"See https://claude.ai/code/session_012hURJ5SRvzZrxxzWyRUEY9 for the run.",
		"Task: https://chatgpt.com/codex/tasks/task_e_123",
	} {
		if _, err := BuildAgentAttributionResult("fix(cli): stop the leak\n\n"+line, forbid); err == nil {
			t.Errorf("the step passed %q", line)
		}
	}
}

// A path under an agent host's directory, a human co-author, and a generator
// that is not an agent are technical text: the step passes them.
func TestAgentAttributionPassesTechnicalText(t *testing.T) {
	spectest.Proves(t, breakingMarkerFeature, agentAttributionRequirement, "technical-text-passes")
	message := strings.Join([]string{
		"chore(workspace): materialize the skills",
		"",
		"The skills land in `.agents/`, `.claude/` and `.codex/`, and",
		"`.claude/settings.json` keeps attribution empty.",
		"Clients are generated by clientgen, and a page is generated with a cursor.",
		"The session reporter reads PUTNAMI_SESSION_REPORTER_TOKEN.",
		"",
		"Co-Authored-By: Ada Lovelace <ada@example.com>",
	}, "\n")
	report, err := BuildAgentAttributionResult(message, forbid)
	if err != nil {
		t.Fatalf("the step failed technical text: %v", err)
	}
	if !report.Proposal || len(report.Lines) != 0 || report.Subject != "chore(workspace): materialize the skills" {
		t.Errorf("report = %+v, want a read message with no line", report)
	}
}

// The policy is the workspace's: unset or "allow" reads nothing, so a
// workspace that never opted in is never blocked.
func TestAgentAttributionPassesWithANoteUnlessTheWorkspaceForbidsIt(t *testing.T) {
	spectest.Proves(t, breakingMarkerFeature, agentAttributionRequirement, "an-allowing-workspace-passes-with-a-note")
	message := "fix(cli): stop the leak\n\n_Generated by [Claude Code](https://claude.ai/code)_"
	for name, options := range map[string]map[string]any{
		"no options": nil,
		"unset":      {"owners": []any{"@owner"}},
		"allow":      {AgentAttributionOption: AgentAttributionAllow},
	} {
		report, err := BuildAgentAttributionResult(message, options)
		if err != nil {
			t.Errorf("%s: the step failed a workspace that allows attribution: %v", name, err)
		}
		if report.Policy != AgentAttributionAllow || report.Proposal || !strings.Contains(report.Note, "allows agent attribution") {
			t.Errorf("%s: report = %+v, want an allow policy with a note", name, report)
		}
	}
}

// Outside a proposal there is no squash message: the step passes and says it
// read nothing.
func TestAgentAttributionPassesWithANoteWithoutAMessage(t *testing.T) {
	spectest.Proves(t, breakingMarkerFeature, agentAttributionRequirement, "an-unset-message-passes-with-a-note")
	for _, message := range []string{"", " \n\t"} {
		report, err := BuildAgentAttributionResult(message, forbid)
		if err != nil || report.Proposal || !strings.Contains(report.Note, "no proposal message to read") {
			t.Errorf("message %q: report = %+v, err = %v, want a pass with a note", message, report, err)
		}
	}
}

// An option value the step does not know fails closed: a typo must not turn
// the gate off.
func TestAgentAttributionRefusesAnInvalidOption(t *testing.T) {
	spectest.Proves(t, breakingMarkerFeature, agentAttributionRequirement, "an-invalid-option-fails")
	for _, value := range []any{"Forbid", "deny", true, 1} {
		report, err := BuildAgentAttributionResult("fix(cli): stop the leak", map[string]any{AgentAttributionOption: value})
		if err == nil {
			t.Errorf("value %v: the step accepted an invalid option", value)
			continue
		}
		if code := protocolcli.ExitCodeForError(err); code != protocolcli.ExitUsage {
			t.Errorf("value %v: exit code = %d, want %d", value, code, protocolcli.ExitUsage)
		}
		if len(report.Diagnostics) != 1 || report.Diagnostics[0].Code != ErrorCodeInvalidAgentAttribution {
			t.Errorf("value %v: diagnostics = %+v, want one %s", value, report.Diagnostics, ErrorCodeInvalidAgentAttribution)
		}
	}
}
