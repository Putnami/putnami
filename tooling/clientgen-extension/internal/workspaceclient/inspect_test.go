// TestATrackedGeneratedFileIsAFinding pins the one rule the guard keeps about
// generated clients: Git holds none. A Git candidate that opens with an
// emitter's marker is a clientgen.committed-generated-client finding. When an
// ignore rule excludes it, Git tracks it, and the finding names the git rm
// --cached that untracks it. Otherwise it names the ignore rule to add too. A
// generated file Git ignores and does not track is no finding.
func TestATrackedGeneratedFileIsAFinding(t *testing.T) {
	spectest.Proves(t, clientgenFeature, "no-committed-client", "a-tracked-generated-file-is-a-finding")
	root, members := committedCatalogWorkspace(t)
	const (
		goClient = "services/catalog/clients/go/client.gen.go"
		tsClient = "services/catalog/clients/ts/src/catalog-client.ts"
	)
	messages := func() map[string]string {
		got := map[string]string{}
		for _, finding := range InspectCommitted(root, members).Findings {
			if finding.Code == committedGeneratedClientCode {
				got[finding.Path] = finding.Message
			}
		}
		return got
	}
	if got := messages(); len(got) != 0 {
		t.Fatalf("an ignored, untracked generated client produced findings: %v", got)
	}

	writeWorkspaceFile(t, root, tsClient, "// Auto-generated by @putnami/client — do not edit\nexport class CatalogClient {}\n")
	gitIn(t, root, "add", "-f", goClient)
	got := messages()
	want := map[string]string{
		goClient: goClient + " carries the generated-client marker and Git tracks it; client-generate writes it, " +
			"so run git rm --cached " + goClient + ", and the ignore rule that matches it keeps it out",
		tsClient: tsClient + " carries the generated-client marker and no ignore rule excludes it; client-generate writes it, " +
			"so add the rule /" + tsClient + " to .gitignore, and if Git tracks it, run git rm --cached " + tsClient,
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("findings = %v\nwant %v", got, want)
	}

	// The remedies close the findings.
	gitIn(t, root, "rm", "-q", "--cached", goClient)
	writeWorkspaceFile(t, root, ".gitignore", ".putnami/\n.gen/\n*.local.go\nclient.gen.go\n/"+tsClient+"\n")
	if got := messages(); len(got) != 0 {
		t.Fatalf("findings after the remedies = %v", got)
	}
}

// TestOnlyTheFirstLineMarksAGeneratedFile: a source that quotes a marker
// further down, such as the guard's own, is no generated file, while a marker
// behind a byte order mark or before a CRLF still is.
func TestOnlyTheFirstLineMarksAGeneratedFile(t *testing.T) {
	for content, want := range map[string]bool{
		"// Code generated by go.putnami.dev/api. DO NOT EDIT.\npackage x\n":         true,
		"\ufeff// Code generated by go.putnami.dev/api. DO NOT EDIT.\r\npackage x\n": true,
		"// Auto-generated by @putnami/client — do not edit\nexport {};\n":           true,
		"package x\n// Code generated by go.putnami.dev/api. DO NOT EDIT.\n":         false,
		"// Code generated by another tool. DO NOT EDIT.\npackage x\n":               false,
		"": false,
	} {
		if got := carriesGeneratedMarker([]byte(content)); got != want {
			t.Errorf("carriesGeneratedMarker(%q) = %v, want %v", content, got, want)
		}
	}
	for rel, want := range map[string]string{
		"clients/catalog/client.gen.go":        "client.gen.go",
		"clients/catalog-ts/src/catalog.ts":    "/clients/catalog-ts/src/catalog.ts",
		"services/catalog/clients/go/extra.go": "/services/catalog/clients/go/extra.go",
	} {
		if got := generatedClientIgnoreRule(rel); got != want {
			t.Errorf("ignore rule for %s = %q, want %q", rel, got, want)
		}
	}
}

// TestTheGuardNamesEachClientFromCommittedFiles pins how the guard spells a
// client's binding without reading generated bytes, which Git ignores: a Go
// client project's import path is its go.mod module and its binding
// Register<ClientName>; an in-module Go client adds the provider's go.output
// to the provider's module; a TypeScript client project's import path is its
// package name, with one binding per service the emitter groups the
// contract's routes into. A client of a service no provider declares, and one
// whose import path cannot be read, are left out.
func TestTheGuardNamesEachClientFromCommittedFiles(t *testing.T) {
	root := t.TempDir()
	writeWorkspaceFile(t, root, ".putnami/workspace-index.json", `{"version":4,"projects":[`+
		`{"path":"clients/catalog-go"},{"path":"clients/catalog-ts"},{"path":"clients/no-module"},`+
		`{"path":"clients/orphan"},{"path":"services/catalog"}]}`)
	writeWorkspaceFile(t, root, "services/catalog/putnami.json", `{"name":"catalog"}`)
	writeWorkspaceFile(t, root, "services/catalog/go.mod", "module example.dev/catalog // the provider\n")
	writeWorkspaceFile(t, root, "services/catalog/clientgen.json", `{"targets":["go"],"go":{"output":"client"}}`)
	writeWorkspaceFile(t, root, "services/catalog/schema/openapi.json", string(catalogContractForFixture(t)))
	writeWorkspaceFile(t, root, "clients/catalog-go/putnami.json",
		`{"name":"catalog-go","generatedFrom":{"service":"catalog","language":"go","packageName":"catalogclient","clientName":"CatalogClient"}}`)
	writeWorkspaceFile(t, root, "clients/catalog-go/go.mod", "module \"example.dev/catalog-go\"\n\ngo 1.24\n")
	writeWorkspaceFile(t, root, "clients/catalog-ts/putnami.json",
		`{"name":"catalog-ts","generatedFrom":{"service":"catalog","language":"ts"}}`)
	writeWorkspaceFile(t, root, "clients/catalog-ts/package.json", `{"name":"@example/catalog-client"}`)
	writeWorkspaceFile(t, root, "clients/no-module/putnami.json",
		`{"name":"no-module","generatedFrom":{"service":"catalog","language":"go"}}`)
	writeWorkspaceFile(t, root, "clients/orphan/putnami.json",
		`{"name":"orphan","generatedFrom":{"service":"billing","language":"go"}}`)
	writeWorkspaceFile(t, root, "clients/orphan/go.mod", "module example.dev/orphan\n")

	report := InspectCommitted(root, fixtureMembers(t, root))
	if !report.Clean() {
		t.Fatalf("findings = %+v", report.Findings)
	}
	if len(report.Providers) != 1 {
		t.Fatalf("providers = %+v, want the catalog provider", report.Providers)
	}
	want := []ClientReport{
		{Project: "clients/catalog-go", Language: clientcontract.GeneratedLanguageGo, ImportPath: "example.dev/catalog-go",
			Bindings: []ClientBinding{{Service: "catalog", ClientSymbol: "CatalogClient", BindingSymbol: "RegisterCatalogClient"}}},
		{Project: "clients/catalog-ts", Language: clientcontract.GeneratedLanguageTypeScript, ImportPath: "@example/catalog-client",
			Bindings: []ClientBinding{{Service: "CatalogService", ClientSymbol: "CatalogClient", BindingSymbol: "registerCatalogClient"}}},
		{Project: "services/catalog", Language: clientcontract.GeneratedLanguageGo, ImportPath: "example.dev/catalog/client",
			Bindings: []ClientBinding{{Service: "catalog", ClientSymbol: "Client", BindingSymbol: "RegisterClient"}}},
	}
	if got := report.Providers[0].Clients; !reflect.DeepEqual(got, want) {
		t.Fatalf("clients = %+v\nwant %+v", got, want)
	}
}

// TestTheTypeScriptServiceNameMirrorsTheEmitter pins typeScriptServiceName to
// inferServiceName in typescript/framework/client/src/generator/openapi-reader.ts.
func TestTheTypeScriptServiceNameMirrorsTheEmitter(t *testing.T) {
	for route, want := range map[string]string{
		"/catalog/items":            "CatalogService",
		"/{tenant}/catalog-admin/x": "CatalogAdminService",
		"/.well-known/jwks.json":    "WellKnownService",
		"/v1_items":                 "V1ItemsService",
		"/2fa/verify":               "_2faService",
		"/{id}":                     "ApiService",
		"/":                         "ApiService",
	} {
		if got := typeScriptServiceName(route); got != want {
			t.Errorf("typeScriptServiceName(%q) = %q, want %q", route, got, want)
		}
	}
}
