func contractHashOf(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func assertFindingCodes(t *testing.T, report Report, codes ...string) {
	t.Helper()
	found := map[string]bool{}
	for _, finding := range report.Findings {
		found[finding.Code] = true
	}
	for _, code := range codes {
		if !found[code] {
			t.Errorf("missing finding %q in %+v", code, report.Findings)
		}
	}
}

func TestReportCleanReflectsActionableFindings(t *testing.T) {
	if !(Report{}).Clean() {
		t.Fatal("empty report must be clean")
	}
	if (Report{Findings: []Finding{{Code: "clientgen.drift", Message: "drift"}}}).Clean() {
		t.Fatal("report with a finding must not be clean")
	}
}

// TestAnUnparseableCommittedManifestIsAFinding: a generated closure whose
// client.putnami.json does not parse names no files, so nothing about it can be
// judged. It is reported, never read as an empty and therefore clean closure.
func TestAnUnparseableCommittedManifestIsAFinding(t *testing.T) {
	spectest.Proves(t, clientgenFeature, "drift-closure", "an-unparseable-committed-manifest-is-a-finding")
	_, expected := analyzerFixture(t)
	root := t.TempDir()
	writeWorkspaceFile(t, root, ".putnami/workspace-index.json", `{"version":4,"projects":[{"path":"services/catalog"}]}`)
	writeWorkspaceFile(t, root, "services/catalog/putnami.json", `{"name":"catalog","extensions":["@putnami/clientgen"]}`)
	writeWorkspaceFile(t, root, "services/catalog/schema/openapi.json", string(catalogContractForFixture(t)))
	for path, content := range expected {
		writeWorkspaceFile(t, root, path, string(content))
	}
	manifestPath := "services/catalog/clients/go/client.putnami.json"
	writeWorkspaceFile(t, root, manifestPath, "{ this is not a generated client manifest")

	report := InspectCommitted(root, fixtureMembers(t, root))
	assertFindingCodes(t, report, "clientgen.invalid-manifest")
	if report.Clean() {
		t.Fatal("a report carrying an invalid manifest must not be clean")
	}
}

// TestForgedManifestHashAndInvalidManifestFail pins the two ways a generated
// manifest can lie: a hash that does not match the bytes beside it, and a
// document that does not satisfy the published schema.
func TestForgedManifestHashAndInvalidManifestFail(t *testing.T) {
	spectest.Proves(t, clientgenFeature, "drift-closure", "forged-missing-and-extra-generated-artifacts-fail")
	item, expected := analyzerFixture(t)
	manifestPath := "services/catalog/clients/go/client.putnami.json"

	forged := memoryReader{}
	for path, content := range expected {
		forged[path] = append([]byte(nil), content...)
	}
	var manifest map[string]any
	if err := json.Unmarshal(forged[manifestPath], &manifest); err != nil {
		t.Fatal(err)
	}
	files := manifest["files"].([]any)
	files[0].(map[string]any)["sha256"] = "ff" + hex.EncodeToString(make([]byte, 31))
	rewritten, err := json.Marshal(manifest)
	if err != nil {
		t.Fatal(err)
	}
	forged[manifestPath] = rewritten
	report := inspectWithReader("/workspace", ModeCheck, []provider{item}, nil, forged, forged)
	assertFindingCodes(t, report, "clientgen.forged-generated-hash")

	invalid := memoryReader{}
	for path, content := range expected {
		invalid[path] = append([]byte(nil), content...)
	}
	invalid[manifestPath] = []byte(`{"protocolVersion":1}`)
	report = inspectWithReader("/workspace", ModeCheck, []provider{item}, nil, invalid, invalid)
	assertFindingCodes(t, report, "clientgen.invalid-manifest")
}

// TestDeletedTargetOperationAndContractAreDetected pins the three deletions a
// generated client can survive silently: the whole target directory, one
// provider operation, and the provider contract the manifest claims to descend
// from.
func TestDeletedTargetOperationAndContractAreDetected(t *testing.T) {
	spectest.Proves(t, clientgenFeature, "drift-closure", "a-deleted-target-operation-or-contract-is-detected")
	item, expected := analyzerFixture(t)

	// The whole configured target is gone from the fresh render.
	report := inspectWithReader("/workspace", ModeSync, []provider{item}, nil, expected, memoryReader{})
	assertFindingCodes(t, report, "clientgen.missing-manifest")
	if report.Coverage.Covered != 0 {
		t.Fatalf("coverage covered = %d with no rendered target, want 0", report.Coverage.Covered)
	}

	// One provider operation disappears from the contract the manifest was cut
	// from; the committed client still claims it.
	shrunk := item
	shrunk.operations = item.operations[:1]
	report = inspectWithReader("/workspace", ModeCheck, []provider{shrunk}, nil, expected, expected)
	assertFindingCodes(t, report, "clientgen.operation-coverage-drift")

	// The provider rebuilt a different contract; the generated lineage is stale.
	moved := item
	moved.contractHash = "beef" + item.contractHash[4:]
	report = inspectWithReader("/workspace", ModeCheck, []provider{moved}, nil, expected, expected)
	assertFindingCodes(t, report, "clientgen.contract-drift")
}

// TestAnOperationTheManifestLeavesOutIsAccountedAndNeverCovered: a Go target
// may leave an operation out (go.omitOperations), and its committed manifest
// names it, so the check judges it from committed bytes alone — the same way on
// a cold clone as on a built tree. The omission is not drift and not coverage:
// the operation still counts as required and never as covered. A manifest that
// names an operation the provider does not declare, or that drops one without
// naming it, fails.
func TestAnOperationTheManifestLeavesOutIsAccountedAndNeverCovered(t *testing.T) {
	spectest.Proves(t, clientgenFeature, "named-omissions", "an-operation-the-manifest-leaves-out-is-accounted-and-never-covered")
	item, expected := analyzerFixture(t)
	manifestPath := "services/catalog/clients/go/client.putnami.json"
	withManifest := func(edit func(*clientcontract.GeneratedClientManifestV1)) memoryReader {
		t.Helper()
		var manifest clientcontract.GeneratedClientManifestV1
		if err := json.Unmarshal(expected[manifestPath], &manifest); err != nil {
			t.Fatal(err)
		}
		edit(&manifest)
		data, err := json.Marshal(&manifest)
		if err != nil {
			t.Fatal(err)
		}
		tree := memoryReader{}
		for path, content := range expected {
			tree[path] = content
		}
		tree[manifestPath] = data
		return tree
	}

	leftOut := withManifest(func(manifest *clientcontract.GeneratedClientManifestV1) {
		manifest.Operations = manifest.Operations[:1]
		manifest.OmittedOperations = []string{"catalog.watch"}
	})
	report := inspectWithReader("/workspace", ModeCheck, []provider{item}, nil, leftOut, leftOut)
	if len(report.Findings) != 0 {
		t.Fatalf("a named omission produced findings: %+v", report.Findings)
	}
	if report.Coverage.Required != 2 || report.Coverage.Covered != 1 {
		t.Fatalf("coverage = %+v, want 1 of 2: an omitted operation is never covered", report.Coverage)
	}
	target := report.Providers[0].Targets[0]
	if len(target.Omitted) != 1 || target.Omitted[0] != "catalog.watch" || target.Operations != 2 || target.Covered != 1 {
		t.Fatalf("target report = %+v, want catalog.watch named as omitted", target)
	}

	unknown := withManifest(func(manifest *clientcontract.GeneratedClientManifestV1) {
		manifest.OmittedOperations = []string{"catalog.zzz"}
	})
	report = inspectWithReader("/workspace", ModeCheck, []provider{item}, nil, unknown, unknown)
	assertFindingCodes(t, report, "clientgen.omitted-operation-drift")

	dropped := withManifest(func(manifest *clientcontract.GeneratedClientManifestV1) {
		manifest.Operations = manifest.Operations[:1]
	})
	report = inspectWithReader("/workspace", ModeCheck, []provider{item}, nil, dropped, dropped)
	assertFindingCodes(t, report, "clientgen.operation-coverage-drift")
}

// TestMissingAndExtraGeneratedOutputsFail pins both halves of output closure: a
// manifest-listed file absent from the tree, and a generated-marked file the
// manifest does not list.
