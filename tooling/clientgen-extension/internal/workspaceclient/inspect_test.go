type memoryReader map[string][]byte

func (r memoryReader) Read(path string) ([]byte, error) {
	data, ok := r[path]
	if !ok {
		return nil, errors.New("missing")
	}
	return append([]byte(nil), data...), nil
}

func (r memoryReader) List(prefix string) ([]string, error) {
	var paths []string
	for path := range r {
		if path == prefix || len(path) > len(prefix) && path[:len(prefix)+1] == prefix+"/" {
			paths = append(paths, path)
		}
	}
	sort.Strings(paths)
	return paths, nil
}

// TestAFreshRenderIsComparedWithTheWorktree is the sync path: after an in-place
// regeneration the worktree must equal a fresh render byte for byte.
func TestAFreshRenderIsComparedWithTheWorktree(t *testing.T) {
	spectest.Proves(t, clientgenFeature, "drift-closure", "sync-compares-a-fresh-render-with-the-worktree")
	spectest.Proves(t, clientgenFeature, "drift-closure", "forged-missing-and-extra-generated-artifacts-fail")
	item, expected := analyzerFixture(t)
	manifestPath := "services/catalog/clients/go/client.putnami.json"
	filePath := "services/catalog/clients/go/client.gen.go"
	worktree := memoryReader{
		manifestPath: expected[manifestPath],
		filePath:     []byte("// stale emitter output\n"),
		"services/catalog/clients/go/extra.gen.go": []byte("// Code generated by go.putnami.dev/api. DO NOT EDIT.\n"),
	}
	report := inspectWithReader("/workspace", ModeSync, []provider{item}, nil, worktree, expected)
	assertFindingCodes(t, report,
		"clientgen.generated-file-drift",
		"clientgen.uninventoried-generated-file",
	)
}

// TestTheCommittedTreeIsJudgedAgainstItsOwnManifest is the check path: no
// render, so the committed manifest is the expectation and every committed byte
// is compared with the hash the manifest recorded for it. A hand edit of a
// generated file is a forged hash; a file the manifest lists and the tree lacks
// is missing; a generated-marked file the manifest does not list is
// uninventoried.
func TestTheCommittedTreeIsJudgedAgainstItsOwnManifest(t *testing.T) {
	spectest.Proves(t, clientgenFeature, "drift-closure", "the-check-judges-committed-bytes-against-the-committed-manifest-and-contract")
	spectest.Proves(t, clientgenFeature, "drift-closure", "forged-missing-and-extra-generated-artifacts-fail")
	item, expected := analyzerFixture(t)
	filePath := "services/catalog/clients/go/client.gen.go"
	edited := memoryReader{}
	for path, content := range expected {
		edited[path] = append([]byte(nil), content...)
	}
	edited[filePath] = []byte("// hand edit of a generated file\n")
	edited["services/catalog/clients/go/extra.gen.go"] = []byte("// Code generated by go.putnami.dev/api. DO NOT EDIT.\n")
	report := inspectWithReader("/workspace", ModeCheck, []provider{item}, nil, edited, edited)
	assertFindingCodes(t, report, "clientgen.forged-generated-hash", "clientgen.uninventoried-generated-file")

	// A clean committed tree is clean from committed inputs alone.
	report = inspectWithReader("/workspace", ModeCheck, []provider{item}, nil, expected, expected)
	if len(report.Findings) != 0 {
		t.Fatalf("a consistent committed closure produced findings: %+v", report.Findings)
	}
}

