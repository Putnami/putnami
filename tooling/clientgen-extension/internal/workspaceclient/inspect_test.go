// TestAnIntentionalSyncPassesBeforeCommit: a developer who regenerated and has
// not committed yet holds a worktree whose manifests, bytes and contract agree;
// the check reads that worktree and passes without HEAD having moved.
func TestAnIntentionalSyncPassesBeforeCommit(t *testing.T) {
	spectest.Proves(t, clientgenFeature, "drift-closure", "intentional-sync-can-be-checked-before-commit")
	_, expected := analyzerFixture(t)
	root := t.TempDir()
	writeWorkspaceFile(t, root, ".putnami/workspace-index.json", `{"version":4,"projects":[{"path":"services/catalog"}]}`)
	writeWorkspaceFile(t, root, "services/catalog/putnami.json", `{"name":"catalog","extensions":["@putnami/clientgen"]}`)
	for path, content := range expected {
		writeWorkspaceFile(t, root, path, string(content))
	}
	// The committed contract the manifest was cut from.
	writeWorkspaceFile(t, root, "services/catalog/schema/openapi.json", string(catalogContractForFixture(t)))

	report := InspectCommitted(root, fixtureMembers(t, root))
	if !report.Clean() {
		t.Fatalf("a synced, uncommitted worktree produced findings: %+v", report.Findings)
	}
	if len(report.Providers) != 1 || len(report.Providers[0].Targets) != 1 || report.Providers[0].Targets[0].Output != "clients/go" {
		t.Fatalf("the committed target was not discovered from its manifest: %+v", report.Providers)
	}
	if report.Coverage.Covered != 2 || report.Coverage.Required != 2 {
		t.Fatalf("coverage = %+v, want 2/2", report.Coverage)
	}
}

func analyzerFixture(t *testing.T) (provider, memoryReader) {
	t.Helper()
	operations := []clientcontract.GeneratedOperation{
		{OperationID: "catalog.chat", Service: "Catalog", MethodSymbol: "Chat", Stream: clientcontract.StreamBidirectional, Transports: []clientcontract.Transport{{
			Protocol: clientcontract.TransportWebSocket, Path: "/catalog/chat", Encoding: clientcontract.EncodingJSON,
			WebSocket: &clientcontract.WebSocketTransport{Subprotocol: clientcontract.WebSocketSubprotocolV1},
		}}},
		{OperationID: "catalog.watch", Service: "Catalog", MethodSymbol: "Watch", Stream: clientcontract.StreamServer, Transports: []clientcontract.Transport{{
			Protocol: clientcontract.TransportSSE, Path: "/catalog/watch", Encoding: clientcontract.EncodingJSON,
		}}},
	}
	config := &clientGenConfig{Targets: []string{"go"}}
	config.Go.Output = "clients/go"
	item := provider{
		rel: "services/catalog", root: "/workspace/services/catalog", config: config,
		classification: ClassificationFirstParty,
		document: &clientcontract.DocumentV1{
			ProtocolVersion: clientcontract.ProtocolVersion,
			Service:         clientcontract.Service{ID: "catalog", Audience: "catalog"},
			Credentials:     map[string]clientcontract.CredentialProfile{},
		},
		contractHash: contractHashOf(catalogContractForFixture(t)),
		operations:   operations,
	}
	content := []byte("// fresh generator output\n")
	sum := sha256.Sum256(content)
	manifest := clientcontract.GeneratedClientManifestV1{
		ProtocolVersion: clientcontract.ProtocolVersion,
		GeneratedBy:     clientcontract.GeneratedBy,
		Language:        clientcontract.GeneratedLanguageGo,
		Service:         item.document.Service,
		Binding: clientcontract.GeneratedBinding{ImportPath: "example.dev/catalog/client", Clients: []clientcontract.GeneratedBindingClient{{
			Service: "Catalog", ClientSymbol: "CatalogClient", BindingSymbol: "RegisterCatalogClient",
		}}},
		ContractSHA256: item.contractHash,
		Operations:     operations,
		Files: []clientcontract.GeneratedFile{{
			Path: "client.gen.go", SHA256: hex.EncodeToString(sum[:]),
		}},
	}
	manifestData, err := json.Marshal(&manifest)
	if err != nil {
		t.Fatal(err)
	}
	return item, memoryReader{
		"services/catalog/clients/go/client.putnami.json": manifestData,
		"services/catalog/clients/go/client.gen.go":       content,
	}
}

