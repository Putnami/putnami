// InspectCommitted is the guard's inspection (`clientgen-check`, and the
// `validate` contribution). members are the workspace-relative directories of
// the projects the orchestrator resolved as workspace members. Inside a Git
// work tree every file it reads is read through the repository's candidate
// cut — the tracked files and the untracked files no ignore rule excludes —
// which is exactly what its cache input `git:**` holds: each provider's
// contract sidecar, the generation contract a provider commits, each client
// project's putnami.json, go.mod and package.json, the inventories, the census
// and every production source the scan reads. What Git ignores, the project
// index, a build's .gen output and every generated client included, is
// absent, as it is from a clone, so a cold clone and a tree the session has
// just built reach the same verdict and nothing is built or generated to reach
// it. Outside a Git work tree it reads the disk, and no `git:` key exists to
// serve its verdict from.
//
// It judges what Git can show: provider discovery, the inventories, a contract
// committed inside a build-written tree, a generated client file in the cut,
// and the handwritten transports the consumer scan finds. Git holds no
// generated client, so no generated byte is compared with anything
// (ADR 0007).
func InspectCommitted(workspaceRoot string, members []string) Report {
	view, err := committedView(workspaceRoot, members)
	if err != nil {
		report := Report{ProtocolVersion: 1, Mode: ModeCheck,
			Findings: []Finding{{Code: "clientgen.discovery", Path: ".", Message: workspaceErrorMessage(workspaceRoot, err)}}}
		canonicalizeReport(&report)
		return report
	}
	return inspect(view)
}

func inspect(view workspaceView) (report Report) {
	inspectStarted := time.Now()
	workspaceRoot := view.root
	providers, findings := discoverCommitted(view)
	report = Report{ProtocolVersion: 1, Mode: ModeCheck, Findings: findings,
		Providers: providerReports(providers, discoverClients(view, providers))}
	report.ExternalContracts, findings = loadAndValidateExternalInventory(view, providers)
	report.Findings = append(report.Findings, findings...)
	report.FrameworkTransports, findings = loadAndValidateFrameworkInventory(view)
	report.Findings = append(report.Findings, findings...)
	report.recordTiming(PhaseInspect, time.Since(inspectStarted))
	// The scan is timed on every exit below, including the failed-scan return,
	// because a scan that failed still cost what it cost.
	scanStarted := time.Now()
	defer func() { report.recordTiming(PhaseScan, time.Since(scanStarted)) }()
	// ONE workspace source scan reads and parses every member project's
	// production sources. It also sets aside each source that carries the
	// generated-client marker: such a file is no consumer source, and its
	// presence in the cut is a finding of its own.
	records, generated, scanErr := workspaceSourceRecords(view)
	if scanErr != nil {
		// A scan that failed read NO source, which is not the same fact as a
		// workspace that contains no transport. Every verdict below is about what
		// the scan saw, so classifying against an empty record set would turn one
		// unreadable tree into one finding per inventory entry. Both scanners are
		// skipped; the only verdict that survives is the one needing no
		// observation: whether the census document itself is valid.
		report.Findings = append(report.Findings, Finding{Code: "clientgen.source-scan",
			Path: ".", Message: workspaceErrorMessage(workspaceRoot, scanErr)})
		report.Findings = append(report.Findings, loadPendingCensus(view.workspaceFiles).invalid...)
		canonicalizeReport(&report)
		return report
	}
	report.Findings = append(report.Findings, committedGeneratedClients(view, generated)...)
	manual, manualFindings := scanManualClients(view.workspaceFiles, providers, records, report)
	report.AdaptationQueue = manual
	// The census splits handwritten-transport verdicts into the ones this
	// workspace already carried when the guard landed and the ones this change
	// introduced. Only the second kind fails; the first is reported so the
	// remaining debt stays visible and countable (see pending.go).
	blocking, pending := classifyPendingTransports(manualFindings, callsiteIndex(manual), loadPendingCensus(view.workspaceFiles))
	report.Findings = append(report.Findings, blocking...)
	report.PendingTransports = pending
	canonicalizeReport(&report)
	return report
}

// providerReports reports every discovered provider with the clients
// discoverClients found for its service.
func providerReports(providers []provider, clients map[string][]ClientReport) []ProviderReport {
	reports := make([]ProviderReport, 0, len(providers))
	for _, item := range providers {
		providerReport := ProviderReport{
			Project: item.rel, Classification: item.classification, ContractSHA256: item.contractHash,
			EmptyContract: item.emptyFirstPartyContract(),
		}
		if item.document != nil {
			providerReport.ServiceID = item.document.Service.ID
			providerReport.Audience = item.document.Service.Audience
			if item.classification == ClassificationFirstParty {
				providerReport.Clients = clients[item.rel]
			}
		}
		reports = append(reports, providerReport)
	}
	return reports
}

// committedGeneratedClientCode is the finding for a generated client file in
// the Git candidate cut.
const committedGeneratedClientCode = "clientgen.committed-generated-client"

// committedGeneratedClients reports each candidate that carries the
// generated-client marker. client-generate writes every such file, and Git
// holds none of them (ADR 0007).
//
// Like committedGeneratedContracts, the message depends on whether an ignore
// rule excludes the candidate, never on whether Git tracks it, because the
// guard's key holds the bytes and not the index. An excluded candidate is in
// the cut only because Git tracks it, so the message names the git rm --cached
// that untracks it. Any other candidate also needs the ignore rule.
func committedGeneratedClients(view workspaceView, generated []string) []Finding {
	if len(generated) == 0 {
		return nil
	}
	ignored, ignoreErr := ignoredByRules(view.root, generated)
	findings := make([]Finding, 0, len(generated))
	for _, rel := range generated {
		untrack := "git rm --cached " + rel
		rule := generatedClientIgnoreRule(rel)
		var message string
		switch {
		case ignoreErr != nil:
			message = fmt.Sprintf("%s carries the generated-client marker and cannot be told apart from a generated output: %v; "+
				"client-generate writes it, so run %s and ignore it with the rule %s", rel, ignoreErr, untrack, rule)
		case ignored[rel]:
			message = fmt.Sprintf("%s carries the generated-client marker and Git tracks it; client-generate writes it, "+
				"so run %s, and the ignore rule that matches it keeps it out", rel, untrack)
		default:
			message = fmt.Sprintf("%s carries the generated-client marker and no ignore rule excludes it; client-generate writes it, "+
				"so add the rule %s to .gitignore, and if Git tracks it, run %s", rel, rule, untrack)
		}
		findings = append(findings, Finding{Code: committedGeneratedClientCode, Path: rel, Message: message})
	}
	return findings
}

// generatedClientIgnoreRule is the .gitignore rule that excludes the generated
// file rel: client.gen.go by its name, which every Go client shares, and any
// other file by its anchored path.
func generatedClientIgnoreRule(rel string) string {
	if path.Base(rel) == generatedGoClientFile {
		return generatedGoClientFile
	}
	return "/" + rel
}

// generatedGoClientFile is the one file the Go emitter writes.
const generatedGoClientFile = "client.gen.go"

// generatedClientMarkers are the first lines the emitters write: the Go
// emitter of go.putnami.dev/api and the TypeScript emitter of
// @putnami/client.
var generatedClientMarkers = []string{
	"// Code generated by go.putnami.dev/api. DO NOT EDIT.",
	"// Auto-generated by @putnami/client — do not edit",
}

// carriesGeneratedMarker reports whether content opens with a marker an
// emitter writes. Only the first line counts, so a source that quotes a
// marker, such as this one, is not a generated file.
func carriesGeneratedMarker(content []byte) bool {
	content = bytes.TrimPrefix(content, []byte("\uFEFF"))
	firstLine, _, _ := bytes.Cut(content, []byte("\n"))
	firstLine = bytes.TrimRight(firstLine, "\r")
	for _, marker := range generatedClientMarkers {
		if string(firstLine) == marker {
			return true
		}
	}
	return false
}

func safeWorkspacePath(value string) (string, error) {
	clean := filepath.ToSlash(filepath.Clean(filepath.FromSlash(value)))
	if clean == "." || clean == ".." || filepath.IsAbs(filepath.FromSlash(value)) || strings.HasPrefix(clean, "../") {
		return "", fmt.Errorf("path %q is outside the workspace", value)
	}
	return clean, nil
}

func joinRel(parts ...string) string {
	joined := filepath.Join(parts...)
	return filepath.ToSlash(joined)
}

// workspaceErrorMessage returns the message of an error a finding reports
// about the workspace as a whole. A file system error names its file relative
// to workspaceRoot, so the finding names no absolute checkout directory and
// reads the same on every machine.
func workspaceErrorMessage(workspaceRoot string, err error) string {
	var pathErr *fs.PathError
	if errors.As(err, &pathErr) && filepath.IsAbs(pathErr.Path) {
		if rel, relErr := filepath.Rel(workspaceRoot, pathErr.Path); relErr == nil && filepath.IsLocal(rel) {
			pathErr.Path = filepath.ToSlash(rel)
		}
	}
	return err.Error()
}

func canonicalizeReport(report *Report) {
	sort.Slice(report.Providers, func(i, j int) bool { return report.Providers[i].Project < report.Providers[j].Project })
	sort.Slice(report.AdaptationQueue, func(i, j int) bool {
		return adaptationSortKey(report.AdaptationQueue[i]) < adaptationSortKey(report.AdaptationQueue[j])
	})
	sort.Slice(report.ExternalContracts, func(i, j int) bool {
		return report.ExternalContracts[i].Project+"\x00"+report.ExternalContracts[i].Adapter <
			report.ExternalContracts[j].Project+"\x00"+report.ExternalContracts[j].Adapter
	})
	sort.Slice(report.FrameworkTransports, func(i, j int) bool {
		return report.FrameworkTransports[i].Project+"\x00"+report.FrameworkTransports[i].Adapter <
			report.FrameworkTransports[j].Project+"\x00"+report.FrameworkTransports[j].Adapter
	})
	sort.Slice(report.Findings, func(i, j int) bool {
		a, b := report.Findings[i], report.Findings[j]
		return findingSortKey(a) < findingSortKey(b)
	})
	sort.Slice(report.PendingTransports, func(i, j int) bool {
		return findingSortKey(report.PendingTransports[i]) < findingSortKey(report.PendingTransports[j])
	})
}

func adaptationSortKey(value Adaptation) string {
	if value.Callsite == nil {
		return fmt.Sprintf("%s\x00%s", value.Path, value.ServiceID)
	}
	return fmt.Sprintf("%s\x00%09d\x00%09d\x00%s\x00%s", value.Path, value.Callsite.Line,
		value.Callsite.Column, value.Callsite.Transport, value.ServiceID)
}

func findingSortKey(value Finding) string {
	return fmt.Sprintf("%s\x00%s\x00%09d\x00%09d\x00%s\x00%s", value.Code, value.Path,
		value.Line, value.Column, value.ServiceID, value.Message)
}
