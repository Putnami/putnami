// signedBody ends with the footer a hosted agent's tool appends and the
// session trailer it asks for.
const signedBody = "Explain the reason\nfor the change.\n\n_Generated by [Claude Code](https://claude.ai/code/session_01abc)_\nClaude-Session: https://claude.ai/code/session_01abc\n"

func TestASignedBodyIsPublishedWithoutItsSignature(t *testing.T) {
	spectest.Proves(t, "tooling/contributor-executable", "squash-ready-publication", "a-signed-body-is-published-without-its-signature")
	f, _, provider, opts := finalizerFixture(t)
	if err := os.WriteFile(opts.BodyFile, []byte(signedBody), 0600); err != nil {
		t.Fatal(err)
	}
	result, err := f.Run(context.Background(), opts)
	if err != nil {
		t.Fatal(err)
	}
	if got, want := provider.proposal.Body, "Explain the reason for the change."; got != want {
		t.Fatalf("published body %q, want %q", got, want)
	}
	want := []StrippedLine{
		{Field: "body", Line: 4, Kind: "generated-footer", Text: "_Generated by [Claude Code](https://claude.ai/code/session_01abc)_"},
		{Field: "body", Line: 5, Kind: "session-link", Text: "Claude-Session: https://claude.ai/code/session_01abc"},
	}
	if len(result.Stripped) != len(want) || result.Stripped[0] != want[0] || result.Stripped[1] != want[1] {
		t.Fatalf("stripped %+v, want %+v", result.Stripped, want)
	}
	// The body file stays as written: the frozen check reads it again.
	if data, err := os.ReadFile(opts.BodyFile); err != nil || string(data) != signedBody {
		t.Fatalf("body file %q, %v", data, err)
	}
}

func TestWhatCannotBeStrippedStillStopsTheRun(t *testing.T) {
	spectest.Proves(t, "tooling/contributor-executable", "squash-ready-publication", "no-publication-names-an-agent")
	f, git, provider, opts := finalizerFixture(t)
	titled := opts
	titled.Title = "fix: publish, generated by Codex"
	if _, err := f.Run(context.Background(), titled); err == nil || !strings.Contains(err.Error(), "title names an agent") {
		t.Fatalf("a title that names an agent: %v", err)
	}
	if err := os.WriteFile(opts.BodyFile, []byte("Co-Authored-By: Claude <noreply@anthropic.com>\n"), 0600); err != nil {
		t.Fatal(err)
	}
	if _, err := f.Run(context.Background(), opts); err == nil || !strings.Contains(err.Error(), "nothing but lines that name an agent") {
		t.Fatalf("a body made of signatures: %v", err)
	}
	if err := os.WriteFile(opts.BodyFile, []byte("Explain the change."), 0600); err != nil {
		t.Fatal(err)
	}
	git.commits = []CommitMessage{{Text: "fix: x\n\nCo-Authored-By: GPT-5 <bot@example.com>"}}
	if _, err := f.Run(context.Background(), opts); err == nil || !strings.Contains(err.Error(), "branch commit names an agent") {
		t.Fatalf("a branch commit that names an agent: %v", err)
	}
	if provider.proposal.Title != "" {
		t.Fatalf("a refused run wrote a proposal: %+v", provider.proposal)
	}
	if err := ValidatePublicationText(opts.Title, "Explain the change.", "Proof by https://chatgpt.com/codex/tasks/1", Policy{}); err == nil {
		t.Fatal("a proof that names an agent passed")
	}
}

func TestTheCommandReportsEachStrippedLine(t *testing.T) {
	t.Parallel()
	for _, machine := range []bool{false, true} {
		contextFile := ""
		if machine {
			contextFile = writeContext(t, map[string]any{"output": "json"}, map[string]any{"mode": "all", "scoped": false, "projects": []string{}})
		}
		command, _, stdout, stderr, args := draftCommand(t, contextFile)
		if err := os.WriteFile(args[7], []byte(signedBody), 0600); err != nil {
			t.Fatal(err)
		}
		if code := command.Run(context.Background(), args); code != 0 {
			t.Fatalf("exit %d, stderr %q", code, stderr)
		}
		wantStderr := "change finalize: removed line 4 of the body, which names an agent (generated-footer): _Generated by [Claude Code](https://claude.ai/code/session_01abc)_\n" +
			"change finalize: removed line 5 of the body, which names an agent (session-link): Claude-Session: https://claude.ai/code/session_01abc\n"
		if stderr.String() != wantStderr {
			t.Errorf("stderr %q, want %q", stderr, wantStderr)
		}
		if !machine {
			continue
		}
		var result struct {
			Stripped []StrippedLine `json:"stripped"`
		}
		if err := json.Unmarshal(bytes.TrimSpace(stdout.Bytes()), &result); err != nil || len(result.Stripped) != 2 || result.Stripped[1].Kind != "session-link" {
			t.Errorf("stdout %q: %v", stdout, err)
		}
	}
}
