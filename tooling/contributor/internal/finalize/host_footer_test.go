package finalize

import (
	"context"
	"strings"
	"testing"

	collab "go.putnami.dev/protocol/collaboration"
	"go.putnami.dev/protocol/features/spectest"
)

// A host such as a Claude Code cloud session appends an attribution footer to
// the proposal body after each write. The readback stays strict, and its error
// names the footer and where to publish instead.
func TestAReadbackThatCarriesAHostFooterNamesItAndSaysToPublishLocally(t *testing.T) {
	spectest.Proves(t, "tooling/contributor-executable", "squash-ready-publication", "no-publication-names-an-agent")
	t.Parallel()
	const footer = "\n\n---\n\n_Generated by [Claude Code](https://claude.ai/code/session_01abc)_"
	f, _, provider, opts := finalizerFixture(t)
	opts.Draft, opts.VerificationFile = true, ""
	provider.statusHook = func(p *collab.Proposal) { p.Body += footer }
	_, err := f.Run(context.Background(), opts)
	if err == nil {
		t.Fatal("a body with a host footer passed the readback")
	}
	for _, want := range []string{"Generated by [Claude Code]", "names an agent", "publish from a local session"} {
		if !strings.Contains(err.Error(), want) {
			t.Fatalf("readback error %q does not contain %q", err, want)
		}
	}
	if provider.upserts != 1 {
		t.Fatalf("the readback failure wrote the body again: upserts=%d", provider.upserts)
	}
}

func TestAReadbackThatAppendsTextNamingNoAgentNamesIt(t *testing.T) {
	t.Parallel()
	f, _, provider, opts := finalizerFixture(t)
	opts.Draft, opts.VerificationFile = true, ""
	provider.statusHook = func(p *collab.Proposal) { p.Body += "\n\nEdited by a bot." }
	_, err := f.Run(context.Background(), opts)
	if err == nil || !strings.Contains(err.Error(), "Edited by a bot.") || strings.Contains(err.Error(), "names an agent") {
		t.Fatalf("readback error does not name the appended text alone: %v", err)
	}
}
