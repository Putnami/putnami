package mapgen

import (
	"encoding/json"
	"fmt"
	"strings"
)

// RenderJSON encodes the map as the repo-map.json bytes: two-space indented
// JSON with a trailing newline. It is the byte form both the on-disk document
// and the MCP `workspace_map` freshness comparison use.
func RenderJSON(m *RepoMap) ([]byte, error) {
	data, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("serialize repo map: %w", err)
	}
	return append(data, '\n'), nil
}

// RenderMarkdown renders the map as the repo-map.md bytes. The
// layout follows the questions an agent asks before it starts shelling around:
// which projects exist, who owns a path, what depends on what, where the APIs,
// the config keys, and the docs are.
func RenderMarkdown(m *RepoMap) []byte {
	var b strings.Builder

	title := "Repo Map"
	if m.Workspace != "" {
		title += " — " + m.Workspace
	}
	fmt.Fprintf(&b, "# %s\n\n", title)
	b.WriteString("Generated orientation map for agents and humans. Read this before shell exploration:\n")
	b.WriteString("it answers \"which project owns path X\", \"what depends on Y\", and \"where are the APIs/config/docs\".\n\n")
	fmt.Fprintf(&b, "- **Generated by**: `%s` — do not hand-edit; `putnami build` refreshes it.\n", m.GeneratedBy)
	fmt.Fprintf(&b, "- **Regenerate**: `%s`\n", m.Regenerate)
	b.WriteString("- **Path ownership**: projects are listed by path; the longest path prefix that matches a file owns it.\n\n")

	renderProjects(&b, m)
	renderDependencies(&b, m)
	renderIntercalls(&b, m)
	renderEndpoints(&b, m)
	renderConfigKeys(&b, m)
	renderSchemas(&b, m)
	renderDocs(&b, m)

	return []byte(b.String())
}

func renderProjects(b *strings.Builder, m *RepoMap) {
	b.WriteString("## Projects\n\n")
	if len(m.Projects) == 0 {
		b.WriteString("_No projects._\n\n")
		return
	}
	b.WriteString("| Path | Name | Type | Tags | Description |\n|---|---|---|---|---|\n")
	for _, p := range m.Projects {
		fmt.Fprintf(b, "| `%s` | `%s` | %s | %s | %s |\n",
			p.Path, p.Name, dash(p.Type), dash(strings.Join(p.Tags, ", ")), cell(describe(p)))
	}
	b.WriteString("\n")
}

// describe prefers the authored putnami.json description and falls back to the
// README's first prose line, so a project that documents itself in only one of
// the two still says something.
func describe(p ProjectEntry) string {
	if p.Description != "" {
		return p.Description
	}
	return p.Summary
}

func renderDependencies(b *strings.Builder, m *RepoMap) {
	b.WriteString("## Dependencies\n\n")
	b.WriteString("`depends on` comes from each project's declared dependencies, resolved to workspace projects; `dependents` is the reverse edge.\n\n")
	wrote := false
	for _, p := range m.Projects {
		if len(p.DependsOn) == 0 && len(p.Dependents) == 0 {
			continue
		}
		wrote = true
		fmt.Fprintf(b, "### `%s`\n\n", p.Path)
		if len(p.DependsOn) > 0 {
			fmt.Fprintf(b, "- depends on: %s\n", codeList(p.DependsOn))
		}
		if len(p.Dependents) > 0 {
			fmt.Fprintf(b, "- dependents: %s\n", codeList(p.Dependents))
		}
		b.WriteString("\n")
	}
	if !wrote {
		b.WriteString("_No workspace-internal dependency edges._\n\n")
	}
}

func renderIntercalls(b *strings.Builder, m *RepoMap) {
	b.WriteString("## Intercalls\n\n")
	b.WriteString("Runtime topology, not build order: `calls` is derived from URL-shaped config keys " +
		"(a key whose leaf names a URL, endpoint, address, or JWKS document) resolved against the live project set; " +
		"`called by` is the reverse edge. Use it for \"who talks to X at runtime\" — the Dependencies section above is the BUILD graph and answers a different question.\n\n")
	b.WriteString("These edges are HEURISTIC. A key whose target does not resolve to exactly one workspace project " +
		"is skipped rather than guessed at, so an absent edge means \"not derivable from config\", not \"no call\". " +
		"The evidence key(s) are shown on every edge so you can judge it yourself.\n\n")
	wrote := false
	for _, p := range m.Projects {
		if len(p.Intercalls) == 0 && len(p.CalledBy) == 0 {
			continue
		}
		wrote = true
		fmt.Fprintf(b, "### `%s`\n\n", p.Path)
		for _, call := range p.Intercalls {
			fmt.Fprintf(b, "- calls: `%s` (via %s)\n", call.To, codeList(call.ConfigKeys))
		}
		if len(p.CalledBy) > 0 {
			fmt.Fprintf(b, "- called by: %s\n", codeList(p.CalledBy))
		}
		b.WriteString("\n")
	}
	if !wrote {
		b.WriteString("_No intercall edges derived from config keys._\n\n")
	}
}

func renderEndpoints(b *strings.Builder, m *RepoMap) {
	b.WriteString("## APIs\n\n")
	b.WriteString("Endpoints from committed `schema/openapi.json` artifacts (`putnami describe`).\n\n")
	wrote := false
	for _, p := range m.Projects {
		if len(p.Endpoints) == 0 {
			continue
		}
		wrote = true
		fmt.Fprintf(b, "### `%s`\n\n", p.Path)
		b.WriteString("| Method | Path | Operation |\n|---|---|---|\n")
		for _, e := range p.Endpoints {
			operation := e.Summary
			if operation == "" {
				operation = e.OperationID
			}
			fmt.Fprintf(b, "| %s | `%s` | %s |\n", e.Method, e.Path, cell(operation))
		}
		b.WriteString("\n")
	}
	if !wrote {
		b.WriteString("_No committed OpenAPI artifacts._\n\n")
	}
}

func renderConfigKeys(b *strings.Builder, m *RepoMap) {
	b.WriteString("## Config keys\n\n")
	b.WriteString("Flattened keys from committed `schema/config.jsonschema.json` artifacts.\n\n")
	wrote := false
	for _, p := range m.Projects {
		if len(p.ConfigKeys) == 0 {
			continue
		}
		wrote = true
		fmt.Fprintf(b, "### `%s`\n\n", p.Path)
		for _, k := range p.ConfigKeys {
			fmt.Fprintf(b, "- `%s` (%s)\n", k.Key, dash(k.Type))
		}
		b.WriteString("\n")
	}
	if !wrote {
		b.WriteString("_No committed config schemas._\n\n")
	}
}

func renderSchemas(b *strings.Builder, m *RepoMap) {
	b.WriteString("## Schemas\n\n")
	b.WriteString("JSON artifacts committed under each project's `schema/` directory.\n\n")
	wrote := false
	for _, p := range m.Projects {
		if len(p.Schemas) == 0 {
			continue
		}
		wrote = true
		fmt.Fprintf(b, "### `%s`\n\n", p.Path)
		for _, s := range p.Schemas {
			fmt.Fprintf(b, "- `%s`\n", s)
		}
		b.WriteString("\n")
	}
	if !wrote {
		b.WriteString("_No committed schema artifacts._\n\n")
	}
}

func renderDocs(b *strings.Builder, m *RepoMap) {
	b.WriteString("## Docs\n\n")
	b.WriteString("The workspace `docs/` tree plus every README that is not a project root's " +
		"(a project's own README is in the Projects table above).\n\n")
	if len(m.Docs) == 0 {
		b.WriteString("_No workspace documents._\n")
		return
	}
	b.WriteString("| Doc | Title |\n|---|---|\n")
	for _, d := range m.Docs {
		fmt.Fprintf(b, "| `%s` | %s |\n", d.Path, cell(d.Title))
	}
}

// cell makes free-form text safe for a one-line markdown table cell.
func cell(s string) string {
	s = oneLine(s)
	s = strings.ReplaceAll(s, "|", "\\|")
	return dash(s)
}

// dash renders an empty value as an em dash, so a table never has a blank cell.
func dash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

// codeList renders a list of identifiers as comma-separated inline code.
func codeList(items []string) string {
	quoted := make([]string, len(items))
	for i, it := range items {
		quoted[i] = "`" + it + "`"
	}
	return strings.Join(quoted, ", ")
}
