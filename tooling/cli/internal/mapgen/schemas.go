package mapgen

import (
	"encoding/json"
	"sort"
	"strings"
)

// openAPIMethods is the closed set of path-item keys that name an operation.
// Everything else a path item may hold (parameters, servers, summary, `x-`
// extensions) is not an endpoint and is skipped rather than guessed at.
var openAPIMethods = map[string]bool{
	"GET": true, "PUT": true, "POST": true, "DELETE": true,
	"OPTIONS": true, "HEAD": true, "PATCH": true, "TRACE": true,
}

// parseOpenAPI extracts the endpoint table from a committed schema/openapi.json.
// The result is sorted by (path, method) so JSON object iteration order — which
// Go randomizes — can never reach the emitted bytes.
//
// A malformed document is an error: the artifact is generated by
// `putnami describe`, so malformed means a broken input, not an absent one.
func parseOpenAPI(data []byte) ([]Endpoint, error) {
	// Path items hold heterogeneous values (operations, but also a parameters
	// array and a summary string), so operations are decoded lazily.
	var doc struct {
		Paths map[string]map[string]json.RawMessage `json:"paths"`
	}
	if err := json.Unmarshal(data, &doc); err != nil {
		return nil, err
	}

	var endpoints []Endpoint
	for p, item := range doc.Paths {
		for key, raw := range item {
			method := strings.ToUpper(key)
			if !openAPIMethods[method] {
				continue
			}
			var op struct {
				OperationID string `json:"operationId"`
				Summary     string `json:"summary"`
			}
			if err := json.Unmarshal(raw, &op); err != nil {
				return nil, err
			}
			endpoints = append(endpoints, Endpoint{
				Method:      method,
				Path:        p,
				OperationID: strings.TrimSpace(op.OperationID),
				Summary:     oneLine(op.Summary),
			})
		}
	}
	sort.Slice(endpoints, func(i, j int) bool {
		if endpoints[i].Path != endpoints[j].Path {
			return endpoints[i].Path < endpoints[j].Path
		}
		return endpoints[i].Method < endpoints[j].Method
	})
	return endpoints, nil
}

// jsonSchemaNode is the subset of JSON Schema the config-key flattener walks.
// $ref/allOf/oneOf composition is deliberately not resolved: the committed
// schema/config.jsonschema.json artifacts are emitted by `putnami describe` with
// inline properties only, and resolving composition would mean following
// references out of the project — which would break the fragment's
// project-scoped input contract.
type jsonSchemaNode struct {
	Type       string                     `json:"type"`
	Properties map[string]*jsonSchemaNode `json:"properties"`
	Items      *jsonSchemaNode            `json:"items"`
}

// parseConfigSchema flattens a committed config JSON Schema into sorted dotted
// keys with their leaf types.
func parseConfigSchema(data []byte) ([]ConfigKey, error) {
	var root jsonSchemaNode
	if err := json.Unmarshal(data, &root); err != nil {
		return nil, err
	}
	var keys []ConfigKey
	flattenSchema("", &root, &keys)
	sort.Slice(keys, func(i, j int) bool { return keys[i].Key < keys[j].Key })
	return keys, nil
}

// flattenSchema walks properties depth-first in SORTED name order, appending one
// ConfigKey per leaf. The caller re-sorts anyway; walking sorted keeps the
// recursion itself free of map-order dependence.
func flattenSchema(prefix string, node *jsonSchemaNode, out *[]ConfigKey) {
	if node == nil {
		return
	}
	if len(node.Properties) == 0 {
		if prefix != "" {
			typ := node.Type
			if node.Items != nil && typ == "array" {
				typ = "array<" + node.Items.Type + ">"
			}
			*out = append(*out, ConfigKey{Key: prefix, Type: typ})
		}
		return
	}
	names := make([]string, 0, len(node.Properties))
	for name := range node.Properties {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		key := name
		if prefix != "" {
			key = prefix + "." + name
		}
		flattenSchema(key, node.Properties[name], out)
	}
}
