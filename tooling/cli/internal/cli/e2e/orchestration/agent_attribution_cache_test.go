package orchestration

import (
	"slices"
	"strings"
	"testing"

	"go.putnami.dev/tooling/cli/internal/cli/clitest"
	"go.putnami.dev/tooling/cli/internal/repotest"
	"go.putnami.dev/tooling/cli/internal/workspace"
)

// attributionTask is the key of the agent-attribution step in the sdd case.
const attributionTask = "counts:validate-workspace~agent-attribution"

// TestAgentAttributionIsServedFromTheCacheUnderItsMessageAndOption holds that
// the agent-attribution step of @putnami/sdd is keyed by what its verdict
// reads: the proposed squash message, which its env input hashes, and the
// workspace option options.sdd.agentAttribution, which its workspace input
// holds. A run that reads the same message and the same option is served from
// the cache; a changed message or a changed option runs the step again, and a
// message that signs for an agent fails the gate whatever the cache holds for
// the messages before it.
func TestAgentAttributionIsServedFromTheCacheUnderItsMessageAndOption(t *testing.T) {
	repotest.Require(t)
	clitest.RequireShell(t)
	var tc extensionCase
	for _, candidate := range extensionCases {
		if candidate.name == "sdd" {
			tc = candidate
		}
	}
	if tc.name == "" {
		t.Fatal("the extension cases hold no sdd case")
	}
	root := prepareExtensionCase(t, t.TempDir(), tc)
	// A message in the environment makes the breaking-marker step need a baseline:
	// the run selects the project a commit changes against its parent, and reads
	// the commits since it.
	clitest.WriteFile(t, root+"/lib/notes.txt", "notes\n")
	clitest.RunGit(t, root, "add", "-A")
	clitest.RunGit(t, root, "commit", "-m", "chore: notes")
	command := append(slices.Clone(tc.command[:1]), "--impacted", "--baseline", "HEAD~1", "--max-parallel", "1")
	t.Setenv("PUTNAMI_PROPOSAL_MESSAGE", "test: first message\n\nbody")
	// The first run prepares the extension runtime and fills the cache for the
	// message and the option the workspace holds.
	if code, out := clitest.RunGateArgs(t, root, everyWorker(command)...); code != 0 {
		t.Fatalf("putnami %v exit %d:\n%s", command, code, out)
	}
	ran := func() bool {
		t.Helper()
		executed, _ := clitest.ExecutedTasks(t, root, command...)
		return slices.Contains(executed, attributionTask)
	}

	if ran() {
		t.Error("a run of the unchanged message and option executed the step, want it served from the cache")
	}

	t.Setenv("PUTNAMI_PROPOSAL_MESSAGE", "test: another message\n\nbody")
	if !ran() {
		t.Error("a run with a changed message was served from the cache, want the step to run again")
	}
	if ran() {
		t.Error("a second run with the changed message executed the step, want it served from the cache")
	}

	forbid := strings.Replace(tc.files["putnami.workspace.json"], `"includes"`,
		`"options": {"sdd": {"agentAttribution": "forbid"}}, "includes"`, 1)
	if forbid == tc.files["putnami.workspace.json"] {
		t.Fatal("the sdd case's workspace file has no includes member to put the option before")
	}
	clitest.WriteFile(t, root+"/putnami.workspace.json", forbid)
	// The runs of this test share one process, which loads a workspace once;
	// a run of the CLI in a new process loads the file it finds.
	workspace.InvalidateLoadCache(root)
	if !ran() {
		t.Error("a run with a changed option was served from the cache, want the step to run again")
	}
	if ran() {
		t.Error("a second run with the changed option executed the step, want it served from the cache")
	}

	// A message that signs for an agent fails, though the cache holds a pass for
	// the message before it.
	t.Setenv("PUTNAMI_PROPOSAL_MESSAGE", "test: signed\n\nGenerated by Claude Code")
	code, out := clitest.RunGateArgs(t, root, command...)
	if code == 0 {
		t.Errorf("a run whose message signs for an agent exited 0, want a failure:\n%s", out)
	}
	if !strings.Contains(out, "names an agent") {
		t.Errorf("a run whose message signs for an agent did not name the line:\n%s", out)
	}

	// The pass the cache holds for the earlier message is still the pass for it.
	t.Setenv("PUTNAMI_PROPOSAL_MESSAGE", "test: another message\n\nbody")
	if ran() {
		t.Error("a run with the earlier message and option executed the step, want it served from the cache")
	}
}
