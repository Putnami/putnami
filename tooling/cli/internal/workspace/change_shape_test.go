// changeShapeWorkspace is a git workspace with three projects: app depends on
// lib, tool depends on nothing. Its main branch is also origin/main.
func changeShapeWorkspace(t *testing.T, config *wsproto.Config) *Workspace {
	t.Helper()
	tmp := t.TempDir()
	gitInitWithBaseline(t, tmp)
	for _, rel := range []string{"app/main.go", "lib/lib.go", "tool/tool.go"} {
		path := filepath.Join(tmp, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte("package x\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	runGitForImpact(t, tmp, "add", "-A")
	runGitForImpact(t, tmp, "commit", "-m", "projects")
	runGitForImpact(t, tmp, "update-ref", "refs/remotes/origin/main", "HEAD")
	runGitForImpact(t, tmp, "symbolic-ref", "refs/remotes/origin/HEAD", "refs/remotes/origin/main")
	projects := []*Project{
		{ID: "/app", Name: "app", Path: "app", Dependencies: []string{"/lib"}},
		{ID: "/lib", Name: "lib", Path: "lib"},
		{ID: "/tool", Name: "tool", Path: "tool"},
	}
	return &Workspace{Root: tmp, Config: config, Projects: projects, Graph: BuildGraph(projects)}
}

func writeChange(t *testing.T, ws *Workspace, rel, content string) {
	t.Helper()
	path := filepath.Join(ws.Root, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func measureChange(t *testing.T, ws *Workspace) ChangeShape {
	t.Helper()
	selection, err := ImpactedSelectionForBaseline(ws, "")
	if err != nil {
		t.Fatalf("ImpactedSelectionForBaseline: %v", err)
	}
	shape, err := selection.ChangeShape(ws, ChangeShapeOptions{})
	if err != nil {
		t.Fatalf("ChangeShape: %v", err)
	}
	return shape
}

func TestChangeShape_SizesEveryCategoryWithoutJudgingIt(t *testing.T) {
	spectest.Proves(t, "cli/workspace-discovery-selection", "change-shape-report", "the-change-is-sized-by-category-and-changes-no-exit-code")
	t.Parallel()
	ws := changeShapeWorkspace(t, nil)
	// Tracked and edited: one line replaced, two added.
	writeChange(t, ws, "lib/lib.go", "package lib\n\nfunc A() {}\nfunc B() {}\n")
	// Untracked: counted by reading the file.
	writeChange(t, ws, "lib/lib_test.go", "package lib\n\nfunc TestA(t *testing.T) {}")
	writeChange(t, ws, "lib/doc/usage.md", "# Usage\n")
	writeChange(t, ws, "go.sum", "a v1 h1:x\nb v1 h1:y\n")
	writeChange(t, ws, "lib/logo.bin", "\x00\x01\x02")

	shape := measureChange(t, ws)
	want := map[ChangeCategory]ChangeSize{
		ChangeCode:      {Files: 2, Added: 4, Deleted: 1},
		ChangeTests:     {Files: 1, Added: 3},
		ChangeDocs:      {Files: 1, Added: 1},
		ChangeGenerated: {Files: 1, Added: 2},
	}
	if !reflect.DeepEqual(shape.Categories, want) {
		t.Errorf("categories = %+v, want %+v", shape.Categories, want)
	}
	if want := (ChangeSize{Files: 5, Added: 10, Deleted: 1}); shape.Total != want {
		t.Errorf("total = %+v, want %+v", shape.Total, want)
	}
	if got, want := shape.SizeExplanation(), "  Change size against origin/main: 5 files +10 -1 (code 2 files +4 -1 · tests 1 file +3 -0 · docs 1 file +1 -0 · generated 1 file +2 -0)"; got != want {
		t.Errorf("size line =\n%q\nwant\n%q", got, want)
	}
	if shape.MixedIntent() || shape.MixedIntentWarning() != "" {
		t.Errorf("a change inside one project is one intent: %+v", shape.Areas)
	}
}

func TestChangeShape_WarnsWhenCodeSpansUnrelatedAreas(t *testing.T) {
	spectest.Proves(t, "cli/workspace-discovery-selection", "change-shape-report", "unrelated-areas-warn-unless-an-epic-declares-them")
	t.Parallel()
	ws := changeShapeWorkspace(t, nil)
	writeChange(t, ws, "app/main.go", "package main\n// app\n")
	writeChange(t, ws, "tool/tool.go", "package tool\n// tool\n")

	shape := measureChange(t, ws)
	if want := [][]string{{"app"}, {"tool"}}; !reflect.DeepEqual(shape.Areas, want) {
		t.Fatalf("areas = %v, want %v", shape.Areas, want)
	}
	warning := shape.MixedIntentWarning()
	for _, want := range []string{"warning:", "2 unrelated areas", "app | tool", "epicBranches"} {
		if !strings.Contains(warning, want) {
			t.Errorf("warning %q does not name %q", warning, want)
		}
	}
	if record := shape.Record(); !record.MixedIntent || len(record.Categories) != len(ChangeCategories) {
		t.Errorf("record = %+v, want mixedIntent and every category present", record)
	}
}

func TestChangeShape_ADependencyJoinsTheAreas(t *testing.T) {
	spectest.Proves(t, "cli/workspace-discovery-selection", "change-shape-report", "unrelated-areas-warn-unless-an-epic-declares-them")
	t.Parallel()
	ws := changeShapeWorkspace(t, nil)
	writeChange(t, ws, "app/main.go", "package main\n// app\n")
	writeChange(t, ws, "lib/lib.go", "package lib\n// lib\n")
	// Docs and tests in an unrelated project follow the code; they open no area.
	writeChange(t, ws, "tool/README.md", "# Tool\n")
	writeChange(t, ws, "tool/tool_test.go", "package tool\n")

	shape := measureChange(t, ws)
	if want := [][]string{{"app", "lib"}}; !reflect.DeepEqual(shape.Areas, want) {
		t.Errorf("areas = %v, want %v", shape.Areas, want)
	}
	if shape.MixedIntent() {
		t.Error("app depends on lib: one area, no warning")
	}
}

func TestChangeShape_AnEpicBranchDeclaresTheSpread(t *testing.T) {
	spectest.Proves(t, "cli/workspace-discovery-selection", "change-shape-report", "unrelated-areas-warn-unless-an-epic-declares-them")
	t.Parallel()
	ws := changeShapeWorkspace(t, &wsproto.Config{EpicBranches: []string{"epic/*"}})
	runGitForImpact(t, ws.Root, "checkout", "-b", "epic/wide")
	writeChange(t, ws, "app/main.go", "package main\n// app\n")
	writeChange(t, ws, "tool/tool.go", "package tool\n// tool\n")

	shape := measureChange(t, ws)
	if len(shape.Areas) != 2 || !shape.OnEpic {
		t.Fatalf("areas = %v, onEpic = %v; want two areas on a declared epic", shape.Areas, shape.OnEpic)
	}
	if warning := shape.MixedIntentWarning(); warning != "" {
		t.Errorf("an epic branch declares the spread, got %q", warning)
	}
}

