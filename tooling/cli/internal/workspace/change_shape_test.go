func TestChangeShapeNotes(t *testing.T) {
	spectest.Proves(t, "cli/workspace-discovery-selection", "change-shape-report", "unrelated-areas-warn-unless-an-epic-declares-them")
	t.Parallel()
	shape := ChangeShape{
		Baseline:   "origin/main",
		Total:      ChangeSize{Files: 2, Added: 3},
		Categories: map[ChangeCategory]ChangeSize{ChangeCode: {Files: 2, Added: 3}},
		Areas:      [][]string{{"app"}, {"tool"}},
	}
	lines := strings.Split(strings.TrimSuffix(shape.Notes(false), "\n"), "\n")
	if len(lines) != 2 || lines[0] != "  Change size against origin/main: 2 files +3 -0 (code 2 files +3 -0)" || !strings.HasPrefix(lines[1], "  warning:") {
		t.Errorf("notes = %q, want the size line, then the warning", lines)
	}
	if got := shape.Notes(true); strings.Contains(got, "Change size") || !strings.HasPrefix(got, "  warning:") {
		t.Errorf("quiet notes = %q, want the warning alone", got)
	}
	shape.OnEpic = true
	if got := shape.Notes(false); strings.Contains(got, "warning:") {
		t.Errorf("an epic branch declares the spread, got %q", got)
	}
	if got := (ChangeShape{}).Notes(false); got != "" {
		t.Errorf("an empty change prints nothing, got %q", got)
	}
}

func TestOwningProject_IsTheNearestProjectDirectory(t *testing.T) {
	t.Parallel()
	dirs := projectDirs(&Workspace{Projects: []*Project{
		{ID: "/", Path: ""}, {ID: "/app", Path: "app"}, {ID: "/nested", Path: "app/sub"}, {ID: "/cli", Path: "tooling/cli"},
	}})
	// Where a file lives decides: a site that declares the CLI's script as an
	// asset, or an enclosing project that declares an asset in a nested one,
	// does not make the file its own.
	for file, want := range map[string]string{
		"tooling/cli/scripts/install.sh": "/cli",
		"tooling/cli/static/app.js":      "/cli",
		"app/main.go":                    "/app",
		"app/sub/public/x.js":            "/nested",
		"tooling/other/x.go":             "/",
		"go.work":                        "/",
	} {
		if got := owningProject(dirs, file); got != want {
			t.Errorf("owningProject(%q) = %q, want %q", file, got, want)
		}
	}
	if got := owningProject(projectDirs(&Workspace{Projects: []*Project{{ID: "/app", Path: "app"}}}), "tool/x.go"); got != "" {
		t.Errorf("a file no project holds has no owner, got %q", got)
	}
}

func TestChangeShapeEvidence_RecordsTheShapeUnlessTheRunOnlyPlans(t *testing.T) {
	spectest.Proves(t, "cli/workspace-discovery-selection", "change-shape-report", "the-change-is-sized-by-category-and-changes-no-exit-code")
	t.Parallel()
	ws := changeShapeWorkspace(t, nil)
	writeChange(t, ws, "app/main.go", "package main\n// app\n")
	selection, err := ImpactedSelectionForBaseline(ws, "")
	if err != nil {
		t.Fatalf("ImpactedSelectionForBaseline: %v", err)
	}
	events, notes := selection.ChangeShapeEvidence(ws, ChangeShapeOptions{})
	if len(events) != 1 || events[0].Type != ChangeShapeRecordType || !strings.HasPrefix(notes, "  Change size against origin/main: 1 file +2 -1") {
		t.Errorf("events = %+v, notes = %q; want one %s event and the size line", events, notes, ChangeShapeRecordType)
	}
	if events, notes := selection.ChangeShapeEvidence(ws, ChangeShapeOptions{PlanOnly: true}); events != nil || notes != "" {
		t.Errorf("a plan-only run measures nothing, got %+v and %q", events, notes)
	}
}
