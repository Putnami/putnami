// Committed, read-only artifact paths doctor inspects, all project-relative.
// Only artifacts a project commits are read; nothing under the ephemeral .gen/
// root and no runtime state is consulted, so a report is reproducible from the
// working tree alone.
const (
	// doctorCapabilitiesPath is the promoted capability manifest.
	doctorCapabilitiesPath = capabilities.CommittedPath // schema/capabilities.json
	// doctorConfigSchemaPath is the committed config schema manifest.
	doctorConfigSchemaPath = "schema/config.json"
	// doctorConfigJSONSchemaPath is the JSON Schema companion of the config
	// manifest, emitted by the same generator.
	doctorConfigJSONSchemaPath = "schema/config.jsonschema.json"
	// doctorOpenAPIPath is the committed OpenAPI specification.
	doctorOpenAPIPath = "schema/openapi.json"
	// doctorHTTPRoutesPath is the committed HTTP route inventory generated by
	// the Go and TypeScript application frameworks.
	doctorHTTPRoutesPath = "schema/http-routes.json"
	// doctorBaseConfigPath is the base config source (discover.go priority 10).
	doctorBaseConfigPath = "conf/.env.yaml"
	// doctorProjectConfigPath is the project's own authored configuration — the
	// file that declares what the project's committed artifacts may depend on.
	doctorProjectConfigPath = "putnami.json"
)

// doctorProject is the evaluation context for one project: where its committed
// artifacts live and under which profile they are judged. relPath is the
// workspace-relative project path used to build Evidence.Path; id is the
// project identity recorded in Finding.Project.
type doctorProject struct {
	absDir  string
	relPath string
	id      string
	// kind is the project's resolved type ("library", "application",
	// "template").
	kind string
	// generatedClient is true for a project the client generator writes: its
	// root holds client.putnami.json.
	generatedClient bool
	profile         doctor.Profile
}

// evaluateProject runs every manifest-derived check against one project's
// committed artifacts and returns the findings in a stable, per-check order.
// Callers sort the aggregate across projects; within a project the order is
// deterministic because each check appends in artifact/source order.
//
// The config schema and the committed config sources it governs are read and
// parsed exactly once here and shared by the config-schema and security-default
// checks (both derive purely from those same artifacts), rather than each check
// re-reading and re-parsing them.
func evaluateProject(p doctorProject) []doctor.Finding {
	var findings []doctor.Finding
	findings = append(findings, checkCapabilities(p)...)
	findings = append(findings, checkConfigArtifacts(p)...)
	findings = append(findings, checkCommittedManifestStability(p)...)
	findings = append(findings, checkSchemaCommitRegime(p)...)
	findings = append(findings, checkReadme(p)...)
	return findings
}

// doctorReadmePath is the page a reader or an agent opens first.
const doctorReadmePath = "README.md"

// checkReadme reports a project without a README.md at its root. Two kinds of
// project are exempt. A template ships README.md.template, the README of the
// project it renders, and a README.md of its own would ship in the archive
// beside it. A generated client is written by the client generator, so a
// README written by hand is not the generator's to keep.
func checkReadme(p doctorProject) []doctor.Finding {
	if p.kind == "template" || p.generatedClient {
		return nil
	}
	// The listing, not a stat, decides: a case-insensitive disk would accept
	// readme.md, which Linux CI and the documentation link check do not.
	// A symbolic link to a regular file is a README, as it is to a reader.
	entries, _ := os.ReadDir(p.absDir)
	for _, entry := range entries {
		if entry.Name() != doctorReadmePath {
			continue
		}
		if info, err := os.Stat(filepath.Join(p.absDir, doctorReadmePath)); err == nil && info.Mode().IsRegular() {
			return nil
		}
	}
	return []doctor.Finding{p.finding(doctor.CheckMissingReadme, false, doctorReadmePath, "",
		"the project has no README.md stating its purpose, its commands and where its docs live")}
}

// checkConfigArtifacts reads schema/config.json and its committed config sources
// once, then runs the schema-derived and security-default checks over the shared
// parse. A project with no committed schema contributes nothing; a schema that
// does not strict-parse yields a single CheckInvalidGeneratedSchema finding and
// stops (a broken schema cannot drive the value-derived checks, and the security
// checks must not guess at markers in it).
func checkConfigArtifacts(p doctorProject) []doctor.Finding {
	data, ok := readCommitted(p.absDir, doctorConfigSchemaPath)
	if !ok {
		return nil
	}

	m, diags := config.ParseSchemaManifest(data)
	if errs := diag.Errors(diags); len(errs) > 0 {
		return []doctor.Finding{p.finding(
			doctor.CheckInvalidGeneratedSchema, false,
			doctorConfigSchemaPath, "",
			fmt.Sprintf("committed config schema is invalid: %s", errs[0].String()))}
	}

	declared, assigned := readCommittedConfigPaths(p.absDir, p.profile)
	fields := collectSchemaFields(m)

	var findings []doctor.Finding
	findings = append(findings, checkConfigSchema(p, fields, declared, assigned)...)
	findings = append(findings, checkSecurityDefaults(p, fields, assigned)...)
	return findings
}

// checkCapabilities inspects schema/capabilities.json. A manifest whose required
// providers are not all present yields CheckIncompleteCapability findings (one
// per unsatisfied requirement); any other structural/parse error means the
// committed manifest is malformed or stale and yields a single
// CheckInvalidGeneratedSchema finding for the file. A project with no committed
// manifest contributes nothing.
func checkCapabilities(p doctorProject) []doctor.Finding {
	data, ok := readCommitted(p.absDir, doctorCapabilitiesPath)
	if !ok {
		return nil
	}

	_, diags := capabilities.ParseAndValidateManifestDocument(data)
	var findings []doctor.Finding
	var otherErrs []diag.Diagnostic
	for _, d := range diag.Errors(diags) {
		if d.Code == capabilities.ErrorCodeMissingRequiredProvider {
			findings = append(findings, p.finding(
				doctor.CheckIncompleteCapability, false,
				doctorCapabilitiesPath, d.Field, d.Message))
			continue
		}
		otherErrs = append(otherErrs, d)
	}
	if len(otherErrs) > 0 {
		findings = append(findings, p.finding(
			doctor.CheckInvalidGeneratedSchema, false,
			doctorCapabilitiesPath, "",
			fmt.Sprintf("committed capability manifest is invalid: %s", otherErrs[0].String())))
	}
	return findings
}

// checkConfigSchema runs the schema-derived checks over the pre-parsed config
// schema fields and the committed config sources they govern (both supplied by
// checkConfigArtifacts). It drives two derived checks: a required field set by
// no committed source is CheckMissingRequiredConfig, and a field with an env
// binding that ALSO carries a committed literal is CheckConfigShadowing (the env
// var at priority 80 silently overrides the file at priority 20).
//
// "Set by a committed source" is value-aware for a scalar leaf: a bare key with
// no value (`port:`) is a placeholder, not a value, so a required scalar left
// bare still surfaces as missing. A composite field (object/array/map) is
// satisfied by being declared, because the source subset yamlKeyPaths
// understands marks a parent key as declared but never assigned.
//
// Security: config VALUES are never read. readCommittedConfigPaths extracts key
// paths only, so Evidence names the field and never its resolved value, and
// sensitivity is read from the schema's own Sensitive flag.
func checkConfigSchema(p doctorProject, fields []schemaField, declared, assigned map[string]bool) []doctor.Finding {
	var findings []doctor.Finding
	for _, f := range fields {
		set := declared[f.path]
		if f.leaf {
			set = assigned[f.path]
		}
		if f.required && !set {
			findings = append(findings, p.finding(
				doctor.CheckMissingRequiredConfig, f.sensitive,
				doctorConfigSchemaPath, f.path,
				fmt.Sprintf("required configuration %q is set by no committed config source under the %s profile", f.path, p.profile)))
		}
		if f.env != "" && assigned[f.path] {
			findings = append(findings, p.finding(
				doctor.CheckConfigShadowing, f.sensitive,
				doctorConfigSchemaPath, f.path,
				fmt.Sprintf("configuration %q is set by a committed config source and by env binding %q; the env var silently wins at runtime", f.path, f.env)))
		}
	}
	return findings
}

// schemaField is one flattened config field: its dotted path plus the schema
// facts the checks key off. No value is ever carried.
type schemaField struct {
	path      string
	required  bool
	sensitive bool
	env       string
	// leaf is true for a value-bearing scalar field (string/int/bool/…) and false
	// for a composite (object/array/map). The missing-required check uses it to
	// pick the right "is it set" signal: a scalar must carry a value, a composite
	// only needs to be declared as a parent key.
	leaf bool
	// productionUnsafe is the schema's productionUnsafeDefault marker: the field
	// has a fallback default that is unsafe in production. The security checks key
	// off this marker (never off a package name).
	productionUnsafe bool
}

// isCompositeField reports whether a config field type nests further structure
// (object/array/map) rather than carrying a scalar value. yamlKeyPaths marks
// such a field's key as declared but never assigned, so composite fields are
// judged "set" by declaration while scalar leaves require an assigned value.
func isCompositeField(t string) bool {
	switch t {
	case config.FieldTypeObject, config.FieldTypeArray, config.FieldTypeMap:
		return true
	default:
		return false
	}
}

// collectSchemaFields flattens a config schema manifest into one schemaField
// per declared field, recursing into object fields so nested required/env-bound
// leaves are reached. The result is ordered by dotted path so findings derived
// from it are deterministic regardless of manifest field order.
func collectSchemaFields(m *config.SchemaManifest) []schemaField {
	var out []schemaField
	var walk func(prefix string, fields []config.FieldSchema)
	walk = func(prefix string, fields []config.FieldSchema) {
		for _, f := range fields {
			if f.Name == "" {
				continue
			}
			p := prefix + "." + f.Name
			out = append(out, schemaField{
				path:             p,
				required:         f.Required,
				sensitive:        f.Sensitive,
				env:              f.Env,
				leaf:             !isCompositeField(f.Type),
				productionUnsafe: f.ProductionUnsafeDefault,
			})
			if f.Type == config.FieldTypeObject && len(f.Fields) > 0 {
				walk(p, f.Fields)
			}
		}
	}
	for _, b := range m.Configs {
		if b.Path == "" {
			continue
		}
		walk(b.Path, b.Fields)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].path < out[j].path })
	return out
}

// readCommittedConfigPaths returns the union of key paths across the committed
// config sources that apply under profile: the base conf/.env.yaml and the
// profile-specific conf/.env.<profile>.yaml (the two sources a workspace
// commits; the dependency-merged .gen/conf and gitignored secrets sources are
// intentionally not read). declared holds every mapping key path; assigned
// holds the subset that carries an inline scalar value. Values are discarded.
func readCommittedConfigPaths(absDir string, profile doctor.Profile) (declared, assigned map[string]bool) {
	declared = map[string]bool{}
	assigned = map[string]bool{}
	sources := []string{
		doctorBaseConfigPath,
		"conf/.env." + string(profile) + ".yaml",
	}
	for _, rel := range sources {
		data, ok := readCommitted(absDir, rel)
		if !ok {
			continue
		}
		d, a := yamlKeyPaths(data)
		for k := range d {
			declared[k] = true
		}
		for k := range a {
			assigned[k] = true
		}
	}
	return declared, assigned
}

// readCommitted reads a project-relative committed artifact. It returns ok=false
// when the file is absent (the common case — most projects declare few
// artifacts) or unreadable, so a missing artifact is silently skipped rather
// than reported as a finding.
func readCommitted(absDir, rel string) ([]byte, bool) {
	data, err := os.ReadFile(filepath.Join(absDir, filepath.FromSlash(rel)))
	if err != nil {
		return nil, false
	}
	return data, true
}

// yamlKeyPaths extracts the dotted key paths declared in a block-style YAML
// config file. It is deliberately minimal — it understands the nested-map
// subset conf/.env*.yaml files use (comments, blank lines, "key:" nesting by
// space indentation, "key: value" leaves, quoted keys) — and it NEVER returns
// or interprets a value, so a resolved config value can never leave this
// function. declared holds every mapping key path; assigned holds paths whose
// line carries an inline scalar. Constructs outside the supported subset
// (sequences, tab indentation) are skipped conservatively rather than guessed.
func yamlKeyPaths(data []byte) (declared, assigned map[string]bool) {
	declared = map[string]bool{}
	assigned = map[string]bool{}

	type frame struct {
		indent int
		key    string
	}
	var stack []frame

	for _, raw := range strings.Split(string(data), "\n") {
		line := strings.TrimRight(raw, "\r")
		indent := 0
		for indent < len(line) && line[indent] == ' ' {
			indent++
		}
		// A tab inside the indentation region is not the supported subset;
		// skip the line rather than misattribute nesting.
		if indent < len(line) && line[indent] == '\t' {
			continue
		}
		content := line[indent:]
		if content == "" || strings.HasPrefix(content, "#") {
			continue
		}
		// Document markers and sequence entries are outside the map subset.
		if content == "---" || content == "..." || strings.HasPrefix(content, "- ") || content == "-" {
			continue
		}
		colon := strings.IndexByte(content, ':')
		if colon < 0 {
			continue
		}
		key := unquoteYAMLKey(strings.TrimSpace(content[:colon]))
		if key == "" {
			continue
		}
		rest := strings.TrimSpace(content[colon+1:])

		for len(stack) > 0 && stack[len(stack)-1].indent >= indent {
			stack = stack[:len(stack)-1]
		}
		keys := make([]string, 0, len(stack)+1)
		for _, f := range stack {
			keys = append(keys, f.key)
		}
		keys = append(keys, key)
		dotted := strings.Join(keys, ".")

		declared[dotted] = true
		if rest != "" && !strings.HasPrefix(rest, "#") {
			assigned[dotted] = true
		}
		stack = append(stack, frame{indent: indent, key: key})
	}
	return declared, assigned
}

// unquoteYAMLKey strips a single pair of surrounding quotes from a YAML mapping
// key so `"app"` and `'app'` resolve to the same path segment as `app`.
func unquoteYAMLKey(k string) string {
	if len(k) >= 2 {
		if (k[0] == '"' && k[len(k)-1] == '"') || (k[0] == '\'' && k[len(k)-1] == '\'') {
			return k[1 : len(k)-1]
		}
	}
	return k
}

// finding builds a Finding for one detected problem, stamping the profile-graded
// severity, the project identity, workspace-relative evidence, and the baked
// remediation for the code. Evidence carries a path and field name only — never
// a value.
func (p doctorProject) finding(code doctor.CheckCode, sensitive bool, artifactRel, field, message string) doctor.Finding {
	return doctor.Finding{
		Code:        code,
		Severity:    severityFor(code, p.profile, sensitive),
		Profile:     p.profile,
		Project:     p.id,
		Message:     message,
		Evidence:    []doctor.Evidence{{Path: path.Join(p.relPath, artifactRel), Field: field}},
		Remediation: doctor.Remediation(code),
	}
}

// severityFor grades a finding by profile: production is strict (high, or
// critical for the categories that must not reach production), while dev and
// test stay permissive (info and warning) so only production promotes an unsafe
// state to a blocking severity.
//
// Advisory codes are the exception and never reach a blocking severity — see
// advisoryCode.
func severityFor(code doctor.CheckCode, profile doctor.Profile, sensitive bool) doctor.Severity {
	if advisoryCode(code) {
		if profile == doctor.ProfileDev {
			return doctor.SeverityInfo
		}
		return doctor.SeverityWarning
	}
	switch profile {
	case doctor.ProfileProduction:
		if criticalUnderProduction(code, sensitive) {
			return doctor.SeverityCritical
		}
		return doctor.SeverityHigh
	case doctor.ProfileTest:
		return doctor.SeverityWarning
	default:
		return doctor.SeverityInfo
	}
}

// advisoryCode reports whether a code is a repository-hygiene finding rather
// than a production-readiness one, and so must never block a profile.
//
// The two stability codes describe how a committed artifact is COUPLED, not
// whether the workload is safe to run: a manifest that enumerates its dependency
// closure deploys exactly as well as one that does not. Grading them high under
// production would make `putnami doctor --profile production` fail for a build
// hygiene issue and push teams to waive a whole class, which is worse than a
// warning they act on. They stay warnings (info under dev), still waivable, and
// the gate stays about production safety.
//
// The workstation codes are advisory for the same reason: a CRLF checkout, a
// host without long paths or without the Visual C++ runtime concerns the
// machine, not the deployed workload. So is a missing README: it concerns the
// reader of the repository.
func advisoryCode(code doctor.CheckCode) bool {
	switch code {
	case doctor.CheckCommittedManifestStability, doctor.CheckUndeclaredSchemaCommit,
		doctor.CheckCRLFCheckout, doctor.CheckLongPathsDisabled, doctor.CheckGitLongPathsDisabled,
		doctor.CheckVCRuntimeMissing, doctor.CheckMissingReadme:
		return true
	default:
		return false
	}
}

// criticalUnderProduction reports whether a production finding is severe enough
// that it must not reach production (SeverityCritical) rather than merely block
// promotion (SeverityHigh): a missing sensitive value a secret must supply, and
// the two unsafe-default categories that silently lose data or auth state across
// a restart — a volatile persistence store (data loss) and an ephemeral signing
// key (every issued token is invalidated). Insecure transport and local rate
// limiting stay high. All other codes stay high under production.
func criticalUnderProduction(code doctor.CheckCode, sensitive bool) bool {
	switch code {
	case doctor.CheckMissingRequiredConfig:
		return sensitive
	case doctor.CheckVolatilePersistence, doctor.CheckEphemeralSigningKey:
		return true
	default:
		return false
	}
}
