// Result-only restores for declared-capture tasks.
//
// A remote hit restored the usual way downloads every blob of the entry and
// writes the task's outputs to the workspace. A run that reads none of those
// files pays for bytes nothing uses. When the provider echoes
// cache.CapabilityRestoreResultOnly, such a hit is restored result-only
// instead: the provider returns the result and the manifest and places no blob,
// core records the result in a local result-only entry
// (store/task_result_only.go), and the task reports its cached status without
// writing the workspace.
//
// # When does a run read a task's files
//
// taskFilesNeeded answers it once per task, from the plan alone, and answers
// "yes" whenever it cannot prove "no":
//
//   - the provider did not echo the capability, or no provider runs: every
//     restore keeps the behavior of a provider without it;
//   - the materialization mode is full, or it is toplevel and the task belongs
//     to a project the run selected (requestedByRun);
//   - a planned job runs after the task: it depends on it, or the plan orders
//     it after the task because it reads what the task writes (a resource the
//     task writes, or the generated client a contract provider writes into a
//     client's directory). The later job may execute, and even when it is a
//     hit its own cache key can read the task's outputs from the workspace (an
//     input pattern such as **/*.go matches the .gen/ files a generate task
//     writes), so serving the task without its files could change what the
//     later job computes. A local hit of the later job is no exemption: its
//     restore can still fail and fall back to execution;
//   - the task declares a report a reader consults after the run
//     (declaresPostRunReport);
//   - the task polices the drift of an output (policedOutputs). The judgment
//     compares the restored bytes with the ones the checkout holds, which is
//     how a checkout with stale committed generated bytes fails from a hit.
//
// The answer depends on job keys, never on cache keys, so a key that moves
// during the run cannot move it.
//
// # What a result-only hit does
//
// A trusted provider hit publishes a local result-only entry and serves the
// status; a hint hit is a quiet miss, because there is no blob to warm. Core
// does not verify the descriptor of a result-only hit, because it reads no
// blob: the provider must answer with the entry stored under the requested
// key. A local result-only entry serves a later run that does not need the
// files either, when no full local entry exists for the key; Negotiate counts
// it as a local hit and does not ask the provider for it. A full local entry
// always takes the full path, and its failed restore falls back to the
// provider's full restore or to an execution. A run that needs the files never
// reads a result-only entry: it restores the full entry from the provider and
// executes the task when that fails.
//
// A status-only hit takes no output lock, writes nothing to the workspace, and
// runs none of the restore follow-ups (drift judgment, stamp refresh, reserved
// artifact recovery), because each of them is about bytes it did not write; a
// task that needs one of them needs its files, by the rule above. The output
// files already in the workspace stay as they are, so they can be absent or
// belong to another key. It records the task's cache key for its dependents,
// replays the recorded events and marks the reuse, as every hit does.
package jobs

import (
	"context"
	"log/slog"
	"slices"
	"sync"
	"time"

	cache "go.putnami.dev/protocol/cache"
	extensionproto "go.putnami.dev/protocol/extension"
	features "go.putnami.dev/protocol/features"
	"go.putnami.dev/tooling/cli/internal/store"
)

// dependedOnJobs returns the key of every job that some planned job must wait
// for: its functional dependencies and its write-serialization predecessors.
func dependedOnJobs(planned []*ScheduledJob) map[string]bool {
	out := make(map[string]bool)
	for _, job := range planned {
		if job == nil {
			continue
		}
		for _, predecessor := range job.SchedulingPredecessors() {
			out[predecessor] = true
		}
	}
	return out
}

// taskFilesNeeded reports whether this run reads the files of job's cache
// entry. It is true unless the provider echoed the result-only capability and
// the plan proves that no reader exists; see this file's header for the rule.
func (r *RemoteCache) taskFilesNeeded(job *ScheduledJob) bool {
	if r == nil || job == nil || r.dependedOn == nil || !r.restoresResultOnly() {
		return true
	}
	switch r.provider.mode {
	case cache.ModeMinimal:
	case cache.ModeToplevel:
		if requestedByRun(job) {
			return true
		}
	default:
		return true
	}
	return r.dependedOn[job.Key()] || declaresPostRunReport(job) || len(policedOutputs(job)) > 0
}

// requestedByRun reports whether job delivers for a project the run's
// selection names. A job without a selection, and a job that runs once for the
// whole selection, count as requested.
func requestedByRun(job *ScheduledJob) bool {
	if job.Selection == nil || job.Project == nil || len(job.SelectedProjects) > 0 {
		return true
	}
	return slices.Contains(job.Selection.ProjectIDs, job.Project.ID)
}

// declaresPostRunReport reports whether job declares a report that a reader
// consults on disk after the scheduler finishes: the feature verification
// report and the executable criteria projection, which the spec gate reads
// from the command output directory. A command-output file whose path the
// task reports at run time may be either, so it counts too. Every other
// post-run reader uses the replayed result, which a status-only hit carries.
func declaresPostRunReport(job *ScheduledJob) bool {
	declaration := taskDeclarationOf(job)
	if declaration == nil {
		return false
	}
	for _, output := range declaration.Outputs {
		if output.EffectiveRoot() != extensionproto.OutputRootCommandOutput || output.Kind != extensionproto.OutputKindFile {
			continue
		}
		switch output.Path {
		case "", features.VerificationReportFilename, features.SpecCriteriaProjectionFilename:
			return true
		}
	}
	return false
}

// RestoreTaskResult asks the provider for the result of a declared-capture
// task whose files this run does not read, and records a trusted hit as a
// local result-only entry. It returns (nil, ReuseNone) for a miss, a hint, a
// payload this build cannot interpret, or any failure, and the caller then
// executes the task.
//
// It takes no lease. A lease keeps sibling sessions from downloading one
// entry twice, and a result-only restore downloads nothing; waiting on a
// sibling that downloads the full entry would only delay a status.
func (r *RemoteCache) RestoreTaskResult(
	ctx context.Context,
	hash string,
	job *ScheduledJob,
	cm *store.CacheManager,
) (*store.ResultOnlyTaskEntry, ReuseKind) {
	if r == nil || cm == nil || hash == "" {
		return nil, ReuseNone
	}
	sess, ok := r.ensureProvider(ctx, nil, cm)
	if !ok || !sess.RestoreResultOnly() {
		return nil, ReuseNone
	}
	restore, err := sess.Restore(ctx, &cache.RestoreParams{Key: store.RemoteTaskEntryKey(hash), ResultOnly: true})
	if err != nil {
		//nolint:gosec // G706 false positive: dynamic values are structured slog attributes, not a format string.
		slog.Warn("remote cache: provider restore failed; building locally",
			"project", job.Project.Name, "job", job.JobDef.Name, "error", err)
		return nil, ReuseNone
	}
	if restore.Status != cache.RestoreHit || restore.Result == nil || restore.Manifest == nil {
		return nil, ReuseNone
	}
	if !r.trust.Accepts(restore.Channel) {
		// A hint can warm blobs but never return a green result, and a
		// result-only restore fetched no blob to warm.
		return nil, ReuseNone
	}
	start := time.Now()
	recorded, err := cm.PublishResultOnlyTaskEntry(store.RemoteTaskEntryHit{
		Key:      hash,
		Result:   entryResultFromActionResult(restore.Result),
		Metadata: taskEntryMetadata(job, restore.Result.DurationMs),
		Manifest: restore.Manifest,
	})
	if err != nil {
		//nolint:gosec // G706 false positive: dynamic values are structured slog attributes, not a format string.
		slog.Debug("remote cache: result-only hit is not interpretable; building locally",
			"project", job.Project.Name, "job", job.JobDef.Name, "error", err)
		return nil, ReuseNone
	}
	var durationMs int64
	if recorded.Metadata != nil {
		durationMs = recorded.Metadata.DurationMs
	}
	r.recordRestoredHit(hash, actionResultFromEntryResult(recorded.Result, durationMs, 0, r.actionEvents),
		nil, durationMs, 0, start, time.Now())
	return recorded, ReuseRemoteCache
}

// serveStatusOnlyHit reports a recorded result as job's cached outcome
// without writing the workspace. It returns nil when the result cannot serve:
// a source rewriter's recorded edits must reach this worktree, so they need
// the full restore or an execution.
func (s *Scheduler) serveStatusOnlyHit(
	job *ScheduledJob,
	hash string,
	recorded *store.ResultOnlyTaskEntry,
	reuse ReuseKind,
	mu *sync.Mutex,
	hashes map[string]string,
) *JobResult {
	if recorded == nil || recorded.Result == nil {
		return nil
	}
	result := jobResultFromEntryResult(recorded.Result)
	if declaredSourceRewriter(job) && result.SourceMutated {
		return nil
	}

	mu.Lock()
	hashes[job.Key()] = hash
	mu.Unlock()

	if s.cfg.Debug {
		slog.Info("declared restore served a status-only hit", "job", job.Key(), "entry", recorded.Address)
	}

	result.MarkReuse(reuse)
	s.replayCacheEvents(job, result)
	return result
}
