// TestExecutedDriftJudgesAPathFromOutputInsideTheProjectReference is the
// pathFrom shape: the path is unknown before the run, so the reference is the
// project tree and the resolved path is looked up in it. Skipped directories
// (node_modules) are skipped on both sides, so a client that carries one does
// not report it.
func TestExecutedDriftJudgesAPathFromOutputInsideTheProjectReference(t *testing.T) {
	spectest.Proves(t, "cli/job-planning-execution", driftRequirement, "a-path-from-output-is-judged-inside-the-project-reference")
	job := driftJob(extension.OutputDriftFail, "", "clientOutput")
	f := newCaptureFixture(t, job)
	project := filepath.Join(f.ws.Root, captureTestProject)
	writeFileAt(t, filepath.Join(project, "src", "clients", "api.ts"), "export const api = 1\n")
	writeFileAt(t, filepath.Join(project, "src", "clients", "node_modules", "dep", "index.js"), "old\n")
	writeFileAt(t, filepath.Join(project, "src", "main.ts"), "import './clients/api'\n")

	reference := f.sched.snapshotExecutedDrift(job)
	entry := reference.entries["client"]
	if !entry.baseIsRoot || entry.base != project {
		t.Fatalf("pathFrom reference must digest the project root, got base=%q root=%v", entry.base, entry.baseIsRoot)
	}
	if _, walked := entry.tree["src/clients/node_modules/dep/index.js"]; walked {
		t.Fatal("the reference walked into node_modules")
	}

	// The generator rewrites the client, a dependency install churns
	// node_modules, and an unrelated source edit lands elsewhere in the project.
	writeFileAt(t, filepath.Join(project, "src", "clients", "api.ts"), "export const api = 2\n")
	writeFileAt(t, filepath.Join(project, "src", "clients", "node_modules", "dep", "index.js"), "new\n")
	writeFileAt(t, filepath.Join(project, "src", "main.ts"), "import './clients/api' // edited\n")

	result := f.sched.judgeExecutedDrift(job, portResult("clientOutput", "src/clients"), reference)
	if result.Status != "failed" {
		t.Fatalf("stale pathFrom client did not fail: %+v", result)
	}
	events := driftDiagnostics(result)
	if len(events) != 1 || !reflect.DeepEqual(events[0].Data["changed"], []any{"api.ts"}) ||
		!reflect.DeepEqual(events[0].Data["added"], []any{}) || events[0].Data["file"] != "proj/src/clients" {
		t.Fatalf("diagnostic = %+v", events)
	}

	// A port that reports nothing (optionalEmpty) has no path to judge.
	reference = f.sched.snapshotExecutedDrift(job)
	writeFileAt(t, filepath.Join(project, "src", "clients", "api.ts"), "export const api = 3\n")
	result = f.sched.judgeExecutedDrift(job, capturedResult(nil), reference)
	if result.Status != "success" {
		t.Fatalf("an output the task did not report was judged: %+v", result)
	}
}

// TestRestoredDriftIsJudgedAgainstTheCheckoutItLandsIn is the restore path —
// the CI shape: the entry was published by the run that regenerated the
// client, and a checkout holding stale committed bytes fails when the hit swaps
// the recorded tree in. The same hit on a checkout holding the regenerated
// bytes passes, so a warm and a cold run agree.
func TestRestoredDriftIsJudgedAgainstTheCheckoutItLandsIn(t *testing.T) {
	spectest.Proves(t, "cli/job-planning-execution", driftRequirement, "a-restored-entry-is-judged-against-the-checkout-it-lands-in")
	job := driftJob(extension.OutputDriftFail, "clients/go", "")
	f := newCaptureFixture(t, job)
	generated := filepath.Join(f.ws.Root, captureTestProject, "clients", "go", "client.gen.go")
	writeFileAt(t, generated, "package client // fresh\n")
	if !f.sched.storeDeclaredCapture(job, capturedResult(nil), captureHashA) {
		t.Fatal("declared capture did not publish an entry")
	}

	// Another checkout, stale committed bytes: the restore replaces them and
	// says so.
	writeFileAt(t, generated, "package client // stale\n")
	result := f.hitOrFail(t, job, captureHashA)
	if result.Status != "failed" || result.Error == nil || result.Error.Code != extension.OutputDriftDiagnosticCode {
		t.Fatalf("a restore over stale bytes did not fail: status=%s error=%+v", result.Status, result.Error)
	}
	if !result.CacheHit {
		t.Error("the verdict came from the restore path but the result is not marked as a hit")
	}
	if got := readFileAt(t, generated); got != "package client // fresh\n" {
		t.Errorf("the restore did not leave the recorded bytes in place: %q", got)
	}
	events := driftDiagnostics(result)
	if len(events) != 1 || !reflect.DeepEqual(events[0].Data["changed"], []any{"client.gen.go"}) {
		t.Fatalf("diagnostic = %+v", events)
	}

	// The checkout now holds the regenerated bytes: the same hit is clean, and
	// the diagnostic did not travel with the entry.
	result = f.hitOrFail(t, job, captureHashA)
	if result.Status != "success" || len(driftDiagnostics(result)) != 0 {
		t.Fatalf("a restore over equal bytes reported drift: status=%s events=%+v", result.Status, result.Events)
	}

	// An entry recorded EMPTY leaves the destination alone, and is judged
	// against an empty tree: committed bytes at a path the producing run wrote
	// nothing to are stale, exactly as the same generator executed cold would
	// report after removing them. The remedy on this path is a deletion.
	empty := driftJob(extension.OutputDriftFail, "clients/ts", "")
	g := newCaptureFixture(t, empty)
	if !g.sched.storeDeclaredCapture(empty, capturedResult(nil), captureHashB) {
		t.Fatal("an optional output the task did not produce must still cache its status")
	}
	if result := g.hitOrFail(t, empty, captureHashB); result.Status != "success" || len(driftDiagnostics(result)) != 0 {
		t.Fatalf("an empty restore over an absent path was judged as drift: %+v", result)
	}
	stale := filepath.Join(g.ws.Root, captureTestProject, "clients", "ts", "index.ts")
	writeFileAt(t, stale, "export {}\n")
	result = g.hitOrFail(t, empty, captureHashB)
	if result.Status != "failed" || len(driftDiagnostics(result)) != 1 ||
		!reflect.DeepEqual(driftDiagnostics(result)[0].Data["removed"], []any{"index.ts"}) ||
		!strings.Contains(driftDiagnostics(result)[0].Message, "delete the stale files") {
		t.Fatalf("an empty restore over stale committed bytes was not judged: %+v", result.Events)
	}
	if _, err := os.Stat(stale); err != nil {
		t.Fatal("the restore of an empty output must leave the destination alone; the verdict, not the swap, names the stale file")
	}
}

