// TestDriftReferenceIsNeverACacheKeyInput is the guard the whole mechanism
// rests on. The reference is a fact about the worktree, so the bytes at the
// policed path may change freely without moving the key; the POLICY is part of
// the contract, so declaring it moves the key exactly once. And the verdict is
// never a replayable failure: the next run must judge the worktree afresh.
func TestDriftReferenceIsNeverACacheKeyInput(t *testing.T) {
	spectest.Proves(t, "cli/job-planning-execution", driftRequirement, "the-reference-and-the-verdict-never-reach-the-cache-key-or-the-failure-cache")
	ws := makeExecutorTestWorkspace(t)
	cache := store.NewCacheManager(store.NewLocalStore(filepath.Join(ws.Root, ".putnami", "store")))
	newJob := func(policy string) *ScheduledJob {
		job := &ScheduledJob{
			Project:   &workspace.Project{ID: "/proj", Name: "proj", Path: "proj"},
			Extension: &extension.ExtensionDescription{Name: "@test/ext", Path: t.TempDir()},
			JobDef:    &extension.JobDefinition{Name: "build", CommandName: "build", ExtensionName: "@test/ext", Cache: true},
		}
		declareCacheTestTask(job, "generate")
		task := extension.TaskDefinition{Declares: &extension.TaskDeclaration{
			Outputs: map[string]extension.DeclaredOutput{
				"client": {Kind: extension.OutputKindDirectory, Path: "clients/go", Drift: policy},
			},
		}}
		job.Extension.Tasks["generate"] = task
		// The planner stamps the task-contract digest onto the job definition
		// (cli-model/extension pipeline expansion); the key reads it from there.
		job.JobDef.ContractDigest = proto.TaskContractDigest(task)
		return job
	}
	hash := func(policy string) string {
		t.Helper()
		got, err := computeJobCacheHash(ws, newJob(policy), nil, nil, cache, nil)
		if err != nil {
			t.Fatalf("compute task cache key: %v", err)
		}
		return got
	}

	generated := filepath.Join(ws.Root, "proj", "clients", "go", "client.gen.go")
	writeFileAt(t, generated, "package client // stale\n")
	stale := hash(extension.OutputDriftFail)
	writeFileAt(t, generated, "package client // fresh\n")
	writeFileAt(t, filepath.Join(ws.Root, "proj", "clients", "go", "extra.gen.go"), "package client\n")
	if fresh := hash(extension.OutputDriftFail); fresh != stale {
		t.Errorf("the bytes at a policed output moved the task cache key: the drift reference reached the key")
	}
	if hash("") == stale {
		t.Errorf("declaring a drift policy did not move the task cache key: the field is not in the task contract")
	}

	failed := &JobResult{
		Status:      "failed",
		EmittedMeta: true,
		Error:       &JobError{Code: extension.OutputDriftDiagnosticCode, Message: "drift"},
	}
	if recordableFailure(newJob(extension.OutputDriftFail), failed) {
		t.Error("a drift failure is recordable for replay: the next run would replay a verdict about a worktree it did not read")
	}
}

// TestDriftDiagnosticIsDeterministicAndBounded pins the message a reader sees:
// sorted paths, complete counts, a bounded list.
func TestDriftDiagnosticIsDeterministicAndBounded(t *testing.T) {
	before := driftTree{"b.go": "1", "a.go": "1", "gone.go": "1"}
	after := driftTree{"b.go": "2", "a.go": "1", "new.go": "1"}
	diff := compareDriftTrees(before, after)
	if !reflect.DeepEqual(diff.added, []string{"new.go"}) || !reflect.DeepEqual(diff.removed, []string{"gone.go"}) ||
		!reflect.DeepEqual(diff.changed, []string{"b.go"}) {
		t.Fatalf("diff = %+v", diff)
	}
	message := driftMessage("client", "proj/clients/go", diff)
	if !strings.Contains(message, "1 added, 1 removed, 1 changed; added new.go; removed gone.go; changed b.go") {
		t.Errorf("message = %q", message)
	}

	many := driftTree{}
	for i := 0; i < driftReportedPaths+5; i++ {
		many[strings.Repeat("f", i+1)+".go"] = "x"
	}
	message = driftMessage("client", "proj/clients/go", compareDriftTrees(driftTree{}, many))
	if !strings.Contains(message, "and 5 more") || strings.Count(message, "; added ") != driftReportedPaths {
		t.Errorf("bounded message = %q", message)
	}

	// A single-file output digests under "" and is named "." in the message.
	root := filepath.Join(t.TempDir(), "openapi.json")
	writeFileAt(t, root, "{}")
	tree, err := walkDriftTree(root, nil)
	if err != nil || len(tree) != 1 || tree[""] == "" {
		t.Fatalf("file root tree = %v err=%v", tree, err)
	}
	if got := driftMessage("schema", "proj/schema/openapi.json", compareDriftTrees(driftTree{}, tree)); !strings.Contains(got, "added .") {
		t.Errorf("single-file message = %q", got)
	}
	if tree, err := walkDriftTree(filepath.Join(t.TempDir(), "absent"), nil); err != nil || len(tree) != 0 {
		t.Fatalf("an absent root must be an empty tree, got %v err=%v", tree, err)
	}
	if _, err := os.Stat(root); err != nil {
		t.Fatal(err)
	}
}

// TestPreservedInstallTreeNeverReachesTheCapture proves a property on the
// engine: a consumer that lists the generated TypeScript client as a package of its own
// installs its dependencies INSIDE the declared output, and a hoisted install
// links a workspace package there as a symlink to a directory. The capture
// walk used to reach that link, open it as a file and fail every provider's
// capture ("copy_file_range: is a directory"), so no provider was ever
// cached. With the install tree preserved, the walk never enters it: the
// entry holds the generated bytes only, a restore leaves the install exactly
// as it finds it, and drift judges neither side of it.
func TestPreservedInstallTreeNeverReachesTheCapture(t *testing.T) {
	job := declaredJob("build~generate", "generate", &extension.TaskDeclaration{
		Outputs: map[string]extension.DeclaredOutput{"client": {
			Kind: extension.OutputKindDirectory, PathFrom: "clientOutput", OptionalEmpty: true,
			Drift: extension.OutputDriftFail, Preserves: []string{"node_modules", "putnami.json"},
		}},
	}, extension.ResourceRef{ID: clientsResourceID, Scope: extension.ResourceScopeProject})

	f := newCaptureFixture(t, job)
	dir := filepath.Join(f.ws.Root, captureTestProject, "clients", "ts")
	generated := filepath.Join(dir, "client.gen.ts")
	installed := filepath.Join(dir, "node_modules")
	writeFileAt(t, generated, "export const fresh = true\n")
	// The shape a hoisted install leaves: one real package directory and one
	// workspace package linked as a directory.
	writeFileAt(t, filepath.Join(installed, "left-pad", "index.js"), "module.exports = 1\n")
	linked := filepath.Join(f.ws.Root, "shared-package")
	writeFileAt(t, filepath.Join(linked, "index.js"), "module.exports = 2\n")
	if err := os.MkdirAll(filepath.Join(installed, "@scope"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(linked, filepath.Join(installed, "@scope", "shared")); err != nil {
		t.Skipf("symlink unavailable: %v", err)
	}

	reference := f.sched.snapshotExecutedDrift(job)
	result := f.sched.judgeExecutedDrift(job, portResult("clientOutput", "clients/ts"), reference)
	if result.Status != "success" || len(driftDiagnostics(result)) != 0 {
		t.Fatalf("the install tree was judged on the executed path: status=%s events=%+v", result.Status, result.Events)
	}
	if !f.sched.storeDeclaredCapture(job, portResult("clientOutput", "clients/ts"), captureHashA) {
		t.Fatal("declared capture did not publish an entry with an install tree inside the output")
	}
	entry, err := f.cache.LookupTaskEntry(captureHashA)
	if err != nil || entry == nil {
		t.Fatalf("no task-owned entry published: entry=%v err=%v", entry, err)
	}
	if len(entry.Outputs) != 1 || entry.Outputs[0].Files != 1 {
		t.Fatalf("the entry must hold the one generated file and nothing from the install tree: %+v", entry.Outputs)
	}

	// Another checkout: the install is gone and the generated file is stale.
	// The hit restores the generated bytes and materializes no install tree.
	if err := os.RemoveAll(installed); err != nil {
		t.Fatal(err)
	}
	writeFileAt(t, generated, "export const fresh = false\n")
	result = f.hitOrFail(t, job, captureHashA)
	events := driftDiagnostics(result)
	if result.Status != "failed" || len(events) != 1 || !reflect.DeepEqual(events[0].Data["changed"], []any{"client.gen.ts"}) {
		t.Fatalf("stale generated bytes were not judged, or the install tree was: status=%s events=%+v", result.Status, events)
	}
	if got := readFileAt(t, generated); got != "export const fresh = true\n" {
		t.Errorf("the restore did not place the generated client: %q", got)
	}
	if _, err := os.Lstat(installed); !os.IsNotExist(err) {
		t.Errorf("the restore materialized the install tree the entry must not hold, err=%v", err)
	}
}

