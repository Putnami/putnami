const driftRequirement = "generated-output-drift"

// driftJob is a generator task whose `client` output carries a drift policy:
// a literal directory when path is set, a pathFrom directory otherwise.
func driftJob(policy, path, port string) *ScheduledJob {
	output := extension.DeclaredOutput{Kind: extension.OutputKindDirectory, OptionalEmpty: true, Drift: policy}
	if path != "" {
		output.Path = path
	} else {
		output.PathFrom = port
	}
	return declaredJob("build~generate", "generate", &extension.TaskDeclaration{
		Outputs: map[string]extension.DeclaredOutput{"client": output},
	}, extension.ResourceRef{ID: clientsResourceID, Scope: extension.ResourceScopeProject})
}

// portResult is a successful result whose data reports one pathFrom port.
func portResult(port, value string) *JobResult {
	return capturedResult(map[string]any{port: value})
}

func driftDiagnostics(result *JobResult) []RawJobEvent {
	var events []RawJobEvent
	for _, event := range result.Events {
		if event.Type == EventTypeDiagnostic && event.Data["code"] == extension.OutputDriftDiagnosticCode {
			events = append(events, event)
		}
	}
	return events
}

// TestExecutedDriftFailsOnStaleBytesAndPassesOnEqualBytes is the executed
// path: the reference is the output as it stood before the task wrote, and the
// verdict is the difference with what the task wrote.
func TestExecutedDriftFailsOnStaleBytesAndPassesOnEqualBytes(t *testing.T) {
	spectest.Proves(t, "cli/job-planning-execution", driftRequirement, "an-executed-task-fails-on-stale-bytes-and-passes-on-equal-bytes")
	job := driftJob(extension.OutputDriftFail, "clients/go", "")
	f := newCaptureFixture(t, job)
	clientDir := filepath.Join(f.ws.Root, captureTestProject, "clients", "go")
	generated := filepath.Join(clientDir, "client.gen.go")
	writeFileAt(t, generated, "package client // stale\n")
	writeFileAt(t, filepath.Join(clientDir, "go.mod"), "module client\n")

	reference := f.sched.snapshotExecutedDrift(job)
	if reference == nil {
		t.Fatal("a task with a policed output took no reference")
	}
	// The task regenerates one file and adds another; go.mod is untouched.
	writeFileAt(t, generated, "package client // fresh\n")
	writeFileAt(t, filepath.Join(clientDir, "types.gen.go"), "package client\n")

	result := f.sched.judgeExecutedDrift(job, capturedResult(nil), reference)
	if result.Status != "failed" || result.Error == nil || result.Error.Code != extension.OutputDriftDiagnosticCode {
		t.Fatalf("stale committed bytes did not fail the task: status=%s error=%+v", result.Status, result.Error)
	}
	events := driftDiagnostics(result)
	if len(events) != 1 {
		t.Fatalf("want one drift diagnostic, got %d: %+v", len(events), result.Events)
	}
	event := events[0]
	if event.Data["severity"] != "error" || event.Data["output"] != "client" || event.Data["file"] != "proj/clients/go" {
		t.Errorf("diagnostic shape = %+v", event.Data)
	}
	if !reflect.DeepEqual(event.Data["added"], []any{"types.gen.go"}) || !reflect.DeepEqual(event.Data["changed"], []any{"client.gen.go"}) ||
		!reflect.DeepEqual(event.Data["removed"], []any{}) {
		t.Errorf("diagnostic lists = added %v removed %v changed %v", event.Data["added"], event.Data["removed"], event.Data["changed"])
	}
	if !strings.Contains(event.Message, "1 added, 0 removed, 1 changed") || !strings.Contains(event.Message, "commit them") {
		t.Errorf("message = %q", event.Message)
	}
	// The worktree keeps the regenerated bytes: the remedy is a commit, not a rerun.
	if got := readFileAt(t, generated); got != "package client // fresh\n" {
		t.Errorf("regenerated bytes were not left in place: %q", got)
	}

	// Equal bytes: the same task on the now-regenerated tree passes silently.
	reference = f.sched.snapshotExecutedDrift(job)
	writeFileAt(t, generated, "package client // fresh\n")
	result = f.sched.judgeExecutedDrift(job, capturedResult(nil), reference)
	if result.Status != "success" || len(driftDiagnostics(result)) != 0 {
		t.Fatalf("equal bytes reported drift: status=%s events=%+v", result.Status, result.Events)
	}
}

