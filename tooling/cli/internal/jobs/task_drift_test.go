// TestPreservedSubpathsAreNeitherCapturedRestoredNorJudged is protocol ADR
// 0005 on the engine's three paths, on the pathFrom shape the generated-client
// directories use: the project document and the module files a
// workspace commits inside a generated directory belong to the workspace. The
// capture leaves them out of the entry, a restore neither replaces nor deletes
// them, and neither the executed nor the restored verdict names them.
func TestPreservedSubpathsAreNeitherCapturedRestoredNorJudged(t *testing.T) {
	job := declaredJob("build~generate", "generate", &extension.TaskDeclaration{
		Outputs: map[string]extension.DeclaredOutput{"client": {
			Kind: extension.OutputKindDirectory, PathFrom: "clientOutput", OptionalEmpty: true,
			Drift: extension.OutputDriftFail, Preserves: []string{"putnami.json", "go.sum"},
		}},
	}, extension.ResourceRef{ID: clientsResourceID, Scope: extension.ResourceScopeProject})

	f := newCaptureFixture(t, job)
	dir := filepath.Join(f.ws.Root, captureTestProject, "clients", "go")
	generated := filepath.Join(dir, "client.gen.go")
	project := filepath.Join(dir, "putnami.json")
	gosum := filepath.Join(dir, "go.sum")
	writeFileAt(t, generated, "package client // fresh\n")
	writeFileAt(t, project, `{"name":"clients/go"}`+"\n")

	// Executed: the generator rewrote nothing it owns, and an author added a
	// go.sum meanwhile. Neither preserved file is drift.
	reference := f.sched.snapshotExecutedDrift(job)
	writeFileAt(t, gosum, "example.com/x v1.0.0 h1:abc=\n")
	result := f.sched.judgeExecutedDrift(job, portResult("clientOutput", "clients/go"), reference)
	if result.Status != "success" || len(driftDiagnostics(result)) != 0 {
		t.Fatalf("a preserved file was judged on the executed path: status=%s events=%+v", result.Status, result.Events)
	}

	if !f.sched.storeDeclaredCapture(job, portResult("clientOutput", "clients/go"), captureHashA) {
		t.Fatal("declared capture did not publish an entry")
	}

	// Another checkout: the project document was edited and go.sum is gone.
	// The hit restores the generated client and leaves both alone.
	writeFileAt(t, project, `{"name":"clients/go","tags":["edited"]}`+"\n")
	if err := os.Remove(gosum); err != nil {
		t.Fatal(err)
	}
	result = f.hitOrFail(t, job, captureHashA)
	if result.Status != "success" || len(driftDiagnostics(result)) != 0 {
		t.Fatalf("a preserved file was judged on the restore path: status=%s events=%+v", result.Status, result.Events)
	}
	if got := readFileAt(t, project); got != `{"name":"clients/go","tags":["edited"]}`+"\n" {
		t.Errorf("the restore replaced the preserved project document: %q", got)
	}
	if _, err := os.Stat(gosum); !os.IsNotExist(err) {
		t.Errorf("the restore materialized a preserved file the entry must not hold, err=%v", err)
	}
	if got := readFileAt(t, generated); got != "package client // fresh\n" {
		t.Errorf("the restore did not place the generated client: %q", got)
	}

	// A stale generated file is still drift: preserving the workspace's files
	// does not stop the output from being judged.
	writeFileAt(t, generated, "package client // stale\n")
	result = f.hitOrFail(t, job, captureHashA)
	events := driftDiagnostics(result)
	if result.Status != "failed" || len(events) != 1 || !reflect.DeepEqual(events[0].Data["changed"], []any{"client.gen.go"}) {
		t.Fatalf("stale generated bytes beside preserved files were not judged: status=%s events=%+v", result.Status, events)
	}
}
