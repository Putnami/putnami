#!/bin/sh
# Writes releases.go, the table of Ruby releases @putnami/ruby pins, from one
# spinel-coop/rv-ruby GitHub release: every stable patch of the minors below
# that has an archive for each of the four platforms the lock keys, with the
# SHA-256 GitHub records for each archive.
#
#   ruby/extension/scripts/rv-ruby-releases.sh 20261023
#
# It needs curl and jq. GITHUB_TOKEN, when set, authenticates the request.
set -eu

tag=${1:?usage: rv-ruby-releases.sh <rv-ruby release tag>}
minors='3\.2|3\.3|3\.4|4\.0'
out="$(cd "$(dirname "$0")/.." && pwd)/releases.go"
api="https://api.github.com/repos/spinel-coop/rv-ruby/releases/tags/$tag"

set -- -fsSL -H "Accept: application/vnd.github+json"
if [ -n "${GITHUB_TOKEN:-}" ]; then
  set -- "$@" -H "Authorization: Bearer $GITHUB_TOKEN"
fi

tmp="$out.tmp"
trap 'rm -f "$tmp"' EXIT
curl "$@" "$api" | jq -r --arg tag "$tag" --arg minors "$minors" '
def platforms: {"ventura": "darwin/amd64", "arm64_sonoma": "darwin/arm64", "x86_64_linux": "linux/amd64", "arm64_linux": "linux/arm64"};
[.assets[]
  | . as $asset
  | ($asset.name | capture("^ruby-(?<version>(" + $minors + ")\\.[0-9]+)\\.(?<build>[a-z0-9_]+)\\.tar\\.gz$")) as $m
  | select(platforms[$m.build] != null)
  | {
      version: $m.version,
      platform: platforms[$m.build],
      digest: (($asset.digest // error("\($asset.name) has no digest")) | ltrimstr("sha256:"))
    }
  | if (.digest | test("^[0-9a-f]{64}$")) then . else error("\($asset.name): \(.digest) is no SHA-256") end]
| group_by(.version)
| map(select(length == 4))
| sort_by(.[0].version | split(".") | map(tonumber))
| if length == 0 then error("release \($tag) holds no archive set") else . end
| "// Code generated by scripts/rv-ruby-releases.sh \($tag); DO NOT EDIT.\n\n"
  + "package ruby\n\n"
  + "// rvRubyRelease is the spinel-coop/rv-ruby release the archives come from.\n"
  + "const rvRubyRelease = \"\($tag)\"\n\n"
  + "// releases lists the shipped releases, oldest first: every stable patch of\n"
  + "// 3.2, 3.3, 3.4 and 4.0 that the rv-ruby release holds for each platform.\n"
  + "var releases = []release{\n"
  + (map(
      "\t{\"\(.[0].version)\", map[string]string{\n"
      + (sort_by(.platform)
         | map("\t\t\"\(.platform)\":" + (if (.platform | startswith("linux")) then "  " else " " end) + "\"\(.digest)\",\n")
         | add)
      + "\t}},\n")
    | add)
  + "}"
' > "$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "wrote $out"
