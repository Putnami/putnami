package contracts

import (
	"encoding/json"
	"fmt"
	"strings"
)

// RenderMarkdown lowers the canonical contract into deterministic reference
// documentation. The result is a generated artifact, so contracts check can
// detect documentation drift with the same byte comparison used for Go types
// and JSON Schema.
func RenderMarkdown(m *Manifest) []byte {
	if m == nil {
		return nil
	}
	var b strings.Builder
	title := m.Name
	if m.Discovery != nil && m.Discovery.Title != "" {
		title = m.Discovery.Title
	}
	fmt.Fprintf(&b, "# %s\n\n", markdownCell(title))
	b.WriteString("<!-- Code generated by go.putnami.dev/protocol/contracts. DO NOT EDIT. -->\n\n")
	if m.Discovery != nil {
		if m.Discovery.Summary != "" {
			fmt.Fprintf(&b, "%s\n\n", m.Discovery.Summary)
		}
		if m.Discovery.Version != "" {
			fmt.Fprintf(&b, "Contract version: `%s`\n\n", markdownCell(m.Discovery.Version))
		}
		if len(m.Discovery.Tags) > 0 {
			fmt.Fprintf(&b, "Tags: `%s`\n\n", markdownCell(strings.Join(m.Discovery.Tags, "`, `")))
		}
	}

	for _, enum := range m.Enums {
		fmt.Fprintf(&b, "## Enum `%s`\n\n", markdownCell(enum.Name))
		writeDescription(&b, enum.Description)
		b.WriteString("| Name | Wire value | Description |\n| --- | --- | --- |\n")
		for _, value := range enum.Values {
			fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", markdownCell(value.Name), markdownCell(value.Value), markdownCell(value.Description))
		}
		b.WriteString("\n")
	}

	for _, union := range m.Unions {
		fmt.Fprintf(&b, "## Union `%s`\n\n", markdownCell(union.Name))
		writeDescription(&b, union.Description)
		fmt.Fprintf(&b, "Discriminator: `%s`\n\n", markdownCell(union.Discriminator))
		b.WriteString("| Tag | Shape | Description |\n| --- | --- | --- |\n")
		for _, variant := range union.Variants {
			shape := variant.Struct
			if shape == "" {
				names := make([]string, 0, len(variant.Fields))
				for _, field := range variant.Fields {
					names = append(names, field.Name)
				}
				shape = strings.Join(names, ", ")
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", markdownCell(variant.Tag), markdownCell(shape), markdownCell(variant.Description))
		}
		b.WriteString("\n")
	}

	for _, dto := range m.Structs {
		fmt.Fprintf(&b, "## DTO `%s`\n\n", markdownCell(dto.Name))
		writeDescription(&b, dto.Description)
		b.WriteString("| Field | Type | Required | Description |\n| --- | --- | --- | --- |\n")
		for _, field := range dto.Fields {
			typ := field.Type
			if field.Repeated {
				typ += "[]"
			}
			required := "yes"
			if field.Optional {
				required = "no"
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s |\n", markdownCell(field.Name), markdownCell(typ), required, markdownCell(field.Description))
		}
		b.WriteString("\n")
	}

	writeConfigDocs(&b, m.ConfigFields)
	writeNamedDocs(&b, "Scopes", m.Scopes, func(v Scope) (string, string) { return v.Name, v.Description })
	writeCapabilityDocs(&b, m.Capabilities)
	writeGrantDocs(&b, m.Grants)
	writeClaimDocs(&b, m.Claims)
	writeNamedDocs(&b, "Principal kinds", m.PrincipalKinds, func(v PrincipalKind) (string, string) { return v.Name, v.Description })

	return []byte(strings.TrimRight(b.String(), "\n") + "\n")
}

func writeConfigDocs(b *strings.Builder, values []ConfigField) {
	if len(values) == 0 {
		return
	}
	b.WriteString("## Configuration\n\n")
	b.WriteString("| Field | Type | Required | Default | Sensitive | Description |\n| --- | --- | --- | --- | --- | --- |\n")
	for _, value := range values {
		fmt.Fprintf(b, "| `%s` | `%s` | %s | `%s` | %s | %s |\n",
			markdownCell(value.Name), markdownCell(value.Type), yesNo(value.Required),
			markdownCell(markdownDefault(value.Default)), yesNo(value.Sensitive), markdownCell(value.Description))
	}
	b.WriteString("\n")
}

func writeCapabilityDocs(b *strings.Builder, values []Capability) {
	if len(values) == 0 {
		return
	}
	b.WriteString("## Capabilities\n\n")
	b.WriteString("| Name | Scopes | Description |\n| --- | --- | --- |\n")
	for _, value := range values {
		fmt.Fprintf(b, "| `%s` | `%s` | %s |\n", markdownCell(value.Name),
			markdownCell(strings.Join(value.Scopes, ", ")), markdownCell(value.Description))
	}
	b.WriteString("\n")
}

func writeGrantDocs(b *strings.Builder, values []Grant) {
	if len(values) == 0 {
		return
	}
	b.WriteString("## Grants\n\n")
	b.WriteString("| Name | Capability | Description |\n| --- | --- | --- |\n")
	for _, value := range values {
		fmt.Fprintf(b, "| `%s` | `%s` | %s |\n", markdownCell(value.Name),
			markdownCell(value.Capability), markdownCell(value.Description))
	}
	b.WriteString("\n")
}

func writeClaimDocs(b *strings.Builder, values []Claim) {
	if len(values) == 0 {
		return
	}
	b.WriteString("## Claims\n\n")
	b.WriteString("| Name | Type | Required | Description |\n| --- | --- | --- | --- |\n")
	for _, value := range values {
		fmt.Fprintf(b, "| `%s` | `%s` | %s | %s |\n", markdownCell(value.Name),
			markdownCell(value.Type), yesNo(value.Required), markdownCell(value.Description))
	}
	b.WriteString("\n")
}

func markdownDefault(value any) string {
	if value == nil {
		return "—"
	}
	raw, err := json.Marshal(value)
	if err != nil {
		return "—"
	}
	return string(raw)
}

func yesNo(value bool) string {
	if value {
		return "yes"
	}
	return "no"
}

func writeDescription(b *strings.Builder, description string) {
	if description != "" {
		fmt.Fprintf(b, "%s\n\n", description)
	}
}

func writeNamedDocs[T any](b *strings.Builder, title string, values []T, project func(T) (string, string)) {
	if len(values) == 0 {
		return
	}
	fmt.Fprintf(b, "## %s\n\n", title)
	b.WriteString("| Name | Description |\n| --- | --- |\n")
	for _, value := range values {
		name, description := project(value)
		fmt.Fprintf(b, "| `%s` | %s |\n", markdownCell(name), markdownCell(description))
	}
	b.WriteString("\n")
}

func markdownCell(value string) string {
	value = strings.ReplaceAll(value, "|", "\\|")
	value = strings.ReplaceAll(value, "\r", " ")
	return strings.ReplaceAll(value, "\n", " ")
}
